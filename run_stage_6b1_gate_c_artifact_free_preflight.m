function results = run_stage_6b1_gate_c_artifact_free_preflight(output_dir)
%RUN_STAGE_6B1_GATE_C_ARTIFACT_FREE_PREFLIGHT Run the frozen 18 checks.

    setup_project;
    project_root = fileparts(mfilename('fullpath'));
    contract = gate_c_contract(project_root);
    verify_contract(contract);
    contract.source_hash_manifest = source_hash_manifest(project_root);
    if nargin < 1 || isempty(output_dir)
        output_dir = contract.output_directory;
    end
    result_path = fullfile(output_dir, 'stage_6b1_gate_c_results.mat');
    if isfile(result_path)
        error('ACAM:Stage6b1GateCOutputExists', ...
            'Refusing to overwrite completed output %s.', output_dir);
    end
    output_lock = acquire_output_lock(output_dir, mfilename);
    code_analyzer_pass = run_code_analyzer(contract.source_files);
    checks = test_stage6b1_gate_c();
    gate = struct('pass', code_analyzer_pass && height(checks) == 18 && ...
        all(checks.passed), 'code_analyzer_pass', code_analyzer_pass, ...
        'observed_checks', height(checks), ...
        'passed_checks', nnz(checks.passed), ...
        'failed_checks', nnz(~checks.passed));
    if gate.pass
        verdict = ["STAGE 6B1 GATE C PASS: artifact-free information-", ...
            "boundary, verified-policy, fallback, actuator, and split ", ...
            "checks passed. Gate D may proceed."];
    else
        verdict = "STAGE 6B1 GATE C FAIL: Gate D remains blocked.";
    end
    results = struct('contract', contract, 'gate', gate, ...
        'checks', checks, 'gate_d_authorized', gate.pass, ...
        'ml_training_authorized', false, 'verdict', join(verdict, ''), ...
        'completed_at', datetime('now'));
    writetable(checks, fullfile(output_dir, ...
        'stage_6b1_gate_c_checks.csv'));
    save(result_path, 'results', '-v7.3');
    digest = sha256_file(result_path);
    write_text([result_path, '.sha256'], sprintf('%s\n', digest));
    write_result(output_dir, results, digest);
    fprintf('%s\n', results.verdict);
    assert(~isempty(output_lock));
end

function contract = gate_c_contract(project_root)
    source_files = { ...
        fullfile(project_root, 'modules', 'pipeline', ...
            'validate_stage6b1_decision_context.m'), ...
        fullfile(project_root, 'modules', 'pipeline', ...
            'build_stage6b1_decision_context.m'), ...
        fullfile(project_root, 'modules', 'pipeline', ...
            'generate_stage6b1_optimizer_target.m'), ...
        fullfile(project_root, 'modules', 'pipeline', ...
            'run_stage6b1_verified_policy.m'), ...
        fullfile(project_root, 'modules', 'pipeline', ...
            'validate_stage6b1_split_isolation.m'), ...
        fullfile(project_root, 'modules', 'guidance', ...
            'build_joint_drag_robust_evaluator.m'), ...
        fullfile(project_root, 'modules', 'guidance', ...
            'build_gate_b_joint_drag_evaluator.m'), ...
        fullfile(project_root, 'test_stage6b1_gate_c.m'), ...
        fullfile(project_root, ...
            'run_stage_6b1_gate_c_artifact_free_preflight.m')};
    contract = struct('version', 1, ...
        'source_document', fullfile(project_root, ...
            'STAGE_6B1_GATE_C_ARTIFACT_FREE_PREFLIGHT_CONTRACT.md'), ...
        'source_document_sha256', ...
            'D098DFC589DFCB4119E3E0D2A87ADB2BCA78F4090A1ED366462AF3701ECD27BA', ...
        'parent_path', fullfile(project_root, 'outputs', ...
            'stage_6b1_gate_b_corrected_evaluator_confirmation_v1', ...
            'stage_6b1_gate_b_confirmation_results.mat'), ...
        'parent_sha256', ...
            '3EB6579B149B5617929FD807DAB5F7BA01DB70597F0075835D165C8920B858D1', ...
        'expected_checks', 18, 'source_files', {source_files}, ...
        'output_directory', fullfile(project_root, 'outputs', ...
            'stage_6b1_gate_c_artifact_free_preflight_v1'));
end

function verify_contract(contract)
    assert(strcmpi(sha256_file(contract.source_document), ...
        contract.source_document_sha256), ...
        'Gate C contract changed after freezing.');
    assert(strcmpi(sha256_file(contract.parent_path), ...
        contract.parent_sha256), 'Gate B confirmation artifact changed.');
    parent = load(contract.parent_path, 'results');
    assert(parent.results.gate.pass && parent.results.gate_c_authorized, ...
        'Gate B confirmation did not authorize Gate C.');
end

function pass = run_code_analyzer(files)
    pass = true;
    for k = 1:numel(files)
        issues = checkcode(files{k}, '-id');
        if ~isempty(issues)
            pass = false;
            for j = 1:numel(issues)
                fprintf('Code Analyzer: %s L%d %s %s\n', files{k}, ...
                    issues(j).line, issues(j).id, issues(j).message);
            end
        end
    end
end

function manifest = source_hash_manifest(project_root)
    runner = fullfile(project_root, ...
        'run_stage_6b1_gate_c_artifact_free_preflight.m');
    files = string(matlab.codetools.requiredFilesAndProducts(runner));
    files = files(:);
    files = unique([files(startsWith(lower(files), ...
        lower(string(project_root)))); string(fullfile(project_root, ...
        'STAGE_6B1_GATE_C_ARTIFACT_FREE_PREFLIGHT_CONTRACT.md'))]);
    files = sort(files);
    relative_path = strings(numel(files), 1);
    sha256 = strings(numel(files), 1);
    for k = 1:numel(files)
        relative_path(k) = erase(files(k), string(project_root) + filesep);
        sha256(k) = sha256_file(files(k));
    end
    manifest = table(relative_path, sha256);
end

function digest = sha256_file(path)
    algorithm = System.Security.Cryptography.SHA256.Create();
    stream = System.IO.File.OpenRead(char(path));
    cleanup = onCleanup(@() stream.Close());
    bytes = uint8(algorithm.ComputeHash(stream));
    digest = upper(reshape(dec2hex(bytes, 2).', 1, []));
    assert(~isempty(cleanup));
end

function write_text(path, content)
    file = fopen(path, 'w');
    assert(file >= 0, 'Could not write Gate C output.');
    cleanup = onCleanup(@() fclose(file));
    fprintf(file, '%s', content);
    assert(~isempty(cleanup));
end

function write_result(output_dir, results, digest)
    content = sprintf([ ...
        '# Stage 6b1 Gate C artifact-free implementation preflight\n\n', ...
        '**%s**\n\n', ...
        '- Checks passed: %d / %d\n', ...
        '- Code Analyzer pass: %d\n', ...
        '- Gate pass: %d\n', ...
        '- Gate D authorized: %d\n', ...
        '- ML training authorized: 0\n', ...
        '- Result MAT SHA-256: `%s`\n'], ...
        results.verdict, results.gate.passed_checks, ...
        results.contract.expected_checks, ...
        results.gate.code_analyzer_pass, results.gate.pass, ...
        results.gate_d_authorized, digest);
    write_text(fullfile(output_dir, 'RESULT.md'), content);
end
