function report = validate_cara_poc(cara_root)
%VALIDATE_CARA_POC Compare the local Foster 2-D Pc with NASA CARA.
%
% cara_root is the checked-out root of NASA's CARA_Analysis_Tools SDK. The
% SDK is kept external to the project; this function is an optional Stage 7
% validation harness and is not part of the canonical training pipeline.

    cara_root = char(cara_root);
    cara_dist = fullfile(cara_root, 'DistributedMatlab');
    data_path = fullfile(cara_root, 'DataFiles', 'AlfanoInputData', ...
                          'Alfano_2009_Test_Cases');
    if ~isfolder(cara_dist) || ~isfolder(data_path)
        error('ACAM:CaraSdkNotFound', ...
              'Expected CARA SDK folders were not found below %s.', cara_root);
    end

    previous_path = path();
    cleanup = onCleanup(@() path(previous_path));
    addpath(genpath(cara_dist));

    params = struct('case_list', 1:11, 'data_path', data_path);
    conjunctions = GetAlfanoTestCases(params);
    published_pc = [ ...
        1.46749549e-1, 6.22226700e-3, 1.00351176e-1, ...
        4.93234060e-2, 4.44873860e-2, 4.33545500e-3, ...
        1.58147000e-4, 3.69480080e-2, 2.90146291e-1, ...
        2.90146291e-1, 2.67202600e-3];
    alfano_monte_carlo_pc = 1e-8 * [ ...
        0.217467140, 0.015736620, 0.100846420, 0.073089530, ...
        0.044498913, 0.004300500, 0.000161462, 0.035256080, ...
        0.365116060, 0.362952470, 0.003328530];
    project_pc = zeros(1, numel(published_pc));
    cara_pc = zeros(size(project_pc));

    for k = 1:numel(project_pc)
        rel_pos = conjunctions.X1(1:3, k) - conjunctions.X2(1:3, k);
        rel_vel = conjunctions.X1(4:6, k) - conjunctions.X2(4:6, k);
        project_pc(k) = calculate_poc_2d(rel_pos, rel_vel, ...
            conjunctions.C1(1:3, 1:3, k), conjunctions.C2(1:3, 1:3, k), ...
            conjunctions.HBR(k));
        cara_pc(k) = Pc2D_Foster( ...
            conjunctions.X1(1:3, k)', conjunctions.X1(4:6, k)', ...
            conjunctions.C1(:, :, k), conjunctions.X2(1:3, k)', ...
            conjunctions.X2(4:6, k)', conjunctions.C2(:, :, k), ...
            conjunctions.HBR(k), 1e-8, 'circle');
    end

    report = struct( ...
        'case_numbers', 1:numel(project_pc), ...
        'project_pc', project_pc, ...
        'cara_pc', cara_pc, ...
        'published_pc', published_pc, ...
        'alfano_monte_carlo_pc', alfano_monte_carlo_pc, ...
        'relative_error_to_cara', abs(project_pc - cara_pc) ./ cara_pc, ...
        'relative_error_to_published', ...
            abs(project_pc - published_pc) ./ published_pc, ...
        'relative_difference_to_monte_carlo', ...
            abs(project_pc - alfano_monte_carlo_pc) ./ alfano_monte_carlo_pc, ...
        'cara_tolerance', 1e-6, ...
        'published_tolerance', 1e-3);
    report.pass_against_cara = ...
        report.relative_error_to_cara <= report.cara_tolerance;
    report.pass_against_published = ...
        report.relative_error_to_published <= report.published_tolerance;
    report.pass = all(report.pass_against_cara) && ...
                  all(report.pass_against_published);
end
