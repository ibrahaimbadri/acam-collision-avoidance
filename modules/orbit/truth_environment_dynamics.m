function [dXdt, diagnostics] = truth_environment_dynamics( ...
        t, X, c, environment, physical)
%TRUTH_ENVIRONMENT_DYNAMICS Truth-only NRLMSISE-00 and SRP perturbations.

    base_constants = c;
    if environment.include_nrlmsise
        base_constants.A = 0;
    end
    dXdt = twoBodyJ2Drag_simple(t, X, base_constants);
    r = X(1:3);
    v = X(4:6);
    drag_acceleration = zeros(3, 1);
    density = NaN;
    if environment.include_nrlmsise
        utc = environment.epoch_utc + seconds(t);
        utc_vector = datevec(utc);
        lla = eci2lla(r', utc_vector);
        day_of_year = day(utc, 'dayofyear');
        seconds_of_day = seconds(timeofday(utc));
        if isfield(environment, 'space_weather_profile')
            weather = space_weather_at_utc( ...
                environment.space_weather_profile, utc, lla(2));
            [~, densities] = atmosnrlmsise00(lla(3), lla(1), lla(2), ...
                year(utc), day_of_year, seconds_of_day, ...
                weather.local_solar_time_h, weather.f107_average, ...
                weather.f107_daily, weather.magnetic_index, ...
                'Oxygen', 'None');
        else
            [~, densities] = atmosnrlmsise00(lla(3), lla(1), lla(2), ...
                year(utc), day_of_year, seconds_of_day, 'Oxygen', 'None');
        end
        density = densities(6);
        if isfield(environment, 'density_residual_profile')
            density = density * exp(density_residual_at_utc( ...
                environment.density_residual_profile, utc, ...
                environment.density_residual_sign));
        end
        omega = [0; 0; environment.earth_rotation_radps];
        relative_velocity = v - cross(omega, r);
        drag_acceleration = -0.5 * density * ...
            physical.drag_coefficient * ...
            (physical.drag_area_m2 / physical.mass_kg) * ...
            norm(relative_velocity) * relative_velocity;
    end

    srp_acceleration = zeros(3, 1);
    illuminated = true;
    if environment.include_srp
        fraction = min(max(t / environment.duration_s, 0), 1);
        sun_position = environment.sun_position_start_m + fraction * ...
            (environment.sun_position_end_m - ...
             environment.sun_position_start_m);
        to_sun = sun_position - r;
        sun_direction = sun_position / norm(sun_position);
        behind_earth = dot(r, sun_direction) < 0;
        distance_to_shadow_axis = norm( ...
            r - dot(r, sun_direction) * sun_direction);
        illuminated = ~(behind_earth && distance_to_shadow_axis < c.Re);
        if illuminated
            srp_acceleration = -environment.solar_pressure_npm2 * ...
                physical.reflectivity_coefficient * ...
                (physical.srp_area_m2 / physical.mass_kg) * ...
                (environment.astronomical_unit_m / norm(to_sun))^2 * ...
                (to_sun / norm(to_sun));
        end
    end
    dXdt(4:6) = dXdt(4:6) + drag_acceleration + srp_acceleration;
    diagnostics = struct('density_kgpm3', density, ...
        'drag_acceleration_mps2', norm(drag_acceleration), ...
        'srp_acceleration_mps2', norm(srp_acceleration), ...
        'illuminated', illuminated);
end
