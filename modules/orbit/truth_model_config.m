function config = truth_model_config(mode)
%TRUTH_MODEL_CONFIG Versioned truth-only force-model contract.

    if nargin < 1 || isempty(mode)
        mode = 'nominal';
    end
    mode = validatestring(mode, ...
        {'nominal', 'nrlmsise', 'nrlmsise_srp'});
    config = struct( ...
        'version', 1, ...
        'mode', mode, ...
        'include_nrlmsise', ~strcmp(mode, 'nominal'), ...
        'include_srp', strcmp(mode, 'nrlmsise_srp'), ...
        'earth_rotation_radps', 7.2921150e-5, ...
        'solar_pressure_npm2', 4.5344321e-6, ...
        'astronomical_unit_m', 149597870700, ...
        'propagation_rel_tol', 1e-10, ...
        'propagation_abs_tol', 1e-12, ...
        'space_weather_mode', 'matlab_defaults', ...
        'nrlmsise_space_weather', ...
            'MATLAB defaults unless a recorded space_weather_profile is attached', ...
        'nominal_filter_model', 'twoBodyJ2Drag_simple unchanged', ...
        'scope_note', ['Truth-only sensitivity contract. The EKF, STM and ', ...
                       'covariance propagation remain nominal.']);
end
