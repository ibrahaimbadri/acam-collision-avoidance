function pair = truth_dynamics_pair(context, c, duration_s)
%TRUTH_DYNAMICS_PAIR Rebuild per-object truth dynamics for one time arc.
%
% Function handles are deliberately short-lived and are never persisted.
% CONTEXT stores only the versioned model, absolute arc epoch, and physical
% properties, so checkpoints remain plain-data contracts.

    validateattributes(duration_s, {'numeric'}, ...
        {'real', 'finite', 'scalar'}, mfilename, 'duration_s');
    nominal = struct( ...
        'target', @(t, X) twoBodyJ2Drag_simple(t, X, c), ...
        'debris', @(t, X) twoBodyJ2Drag_simple(t, X, c), ...
        'mode', 'nominal', 'contract_version', 0);
    if ~isfield(context, 'truth_model') || ...
            strcmp(context.truth_model.mode, 'nominal')
        pair = nominal;
        if isfield(context, 'truth_model')
            pair.contract_version = context.truth_model.version;
        end
        return;
    end

    required = {'truth_epoch_utc', 'target_physical', 'debris_physical'};
    for k = 1:numel(required)
        if ~isfield(context, required{k})
            error('ACAM:IncompleteTruthContext', ...
                  'Truth context is missing %s.', required{k});
        end
    end
    if isempty(which('atmosnrlmsise00'))
        error('ACAM:MissingAerospaceToolbox', ...
              'NRLMSISE truth propagation requires Aerospace Toolbox.');
    end
    model = context.truth_model;
    epoch = context.truth_epoch_utc;
    if isempty(epoch.TimeZone)
        epoch.TimeZone = 'UTC';
    end
    interpolation_duration_s = duration_s;
    if interpolation_duration_s == 0
        interpolation_duration_s = 1;
    end
    if model.include_srp
        if isempty(which('planetEphemeris'))
            error('ACAM:MissingAerospaceToolbox', ...
                  'SRP truth propagation requires Aerospace Toolbox.');
        end
        end_epoch = epoch + seconds(interpolation_duration_s);
        sun_start = planetEphemeris(juliandate(epoch), ...
            'Earth', 'Sun', '432t', 'km')' * 1e3;
        sun_end = planetEphemeris(juliandate(end_epoch), ...
            'Earth', 'Sun', '432t', 'km')' * 1e3;
    else
        sun_start = [model.astronomical_unit_m; 0; 0];
        sun_end = sun_start;
    end
    environment = struct( ...
        'include_nrlmsise', model.include_nrlmsise, ...
        'include_srp', model.include_srp, ...
        'epoch_utc', epoch, ...
        'duration_s', interpolation_duration_s, ...
        'sun_position_start_m', sun_start, ...
        'sun_position_end_m', sun_end, ...
        'earth_rotation_radps', model.earth_rotation_radps, ...
        'solar_pressure_npm2', model.solar_pressure_npm2, ...
        'astronomical_unit_m', model.astronomical_unit_m);
    if isfield(model, 'space_weather_profile')
        environment.space_weather_profile = model.space_weather_profile;
    end
    target_environment = environment;
    debris_environment = environment;
    if isfield(model, 'density_residual_profile')
        target_environment.density_residual_profile = ...
            model.density_residual_profile;
        debris_environment.density_residual_profile = ...
            model.density_residual_profile;
        target_environment.density_residual_sign = 1;
        debris_environment.density_residual_sign = -1;
    end
    pair = struct( ...
        'target', @(t, X) truth_environment_dynamics( ...
            t, X, c, target_environment, context.target_physical), ...
        'debris', @(t, X) truth_environment_dynamics( ...
            t, X, c, debris_environment, context.debris_physical), ...
        'mode', model.mode, ...
        'contract_version', model.version);
end
