function observation = simulate_cdm_observation(scenario, c, lead_time_s, ...
                                                seed, config)
%SIMULATE_CDM_OBSERVATION Create a consistent TCA state/covariance message.

    if nargin < 5 || isempty(config)
        config = cdm_observation_config();
    end
    validateattributes(lead_time_s, {'numeric'}, ...
        {'real', 'finite', 'scalar', 'positive'}, mfilename, 'lead_time_s');
    validateattributes(seed, {'numeric'}, ...
        {'real', 'finite', 'scalar', 'integer', 'nonnegative'}, ...
        mfilename, 'seed');
    lead_hours = lead_time_s / 3600;
    index = find(abs(config.supported_lead_hours - lead_hours) < 1e-9, 1);
    if isempty(index)
        error('ACAM:UnsupportedCdmLeadTime', ...
              'CDM lead time %.3g h is not configured.', lead_hours);
    end
    scale = config.tca_covariance_scales(index);
    R_rtn = hill_to_eci(scenario.X_cpa_sat);
    velocity_covariance = R_rtn * ...
        diag(config.velocity_sigma_rtn_mps.^2) * R_rtn';
    P_sat_tca = blkdiag(scale * scenario.C_sat, ...
                        scale * velocity_covariance);
    P_deb_tca = blkdiag(scale * scenario.C_deb, ...
                        scale * velocity_covariance);
    stream = RandStream('mt19937ar', 'Seed', mod(double(seed), 2^32 - 1));
    error_sat = chol(P_sat_tca, 'lower') * randn(stream, 6, 1);
    error_deb = chol(P_deb_tca, 'lower') * randn(stream, 6, 1);
    X_sat_tca = scenario.X_cpa_sat(:) + error_sat;
    X_deb_tca = scenario.X_cpa_deb(:) + error_deb;
    X_sat_decision = propagate_backward(X_sat_tca, lead_time_s, c);
    X_deb_decision = propagate_backward(X_deb_tca, lead_time_s, c);

    estimate = struct( ...
        'X_sat', X_sat_decision, ...
        'X_deb', X_deb_decision, ...
        'X_sat_tca', X_sat_tca, ...
        'X_deb_tca', X_deb_tca, ...
        'C_sat_tca', P_sat_tca(1:3, 1:3), ...
        'C_deb_tca', P_deb_tca(1:3, 1:3), ...
        'remaining_time', lead_time_s);
    diagnostics = struct( ...
        'lead_time_s', lead_time_s, ...
        'covariance_scale', scale, ...
        'P_sat_tca', P_sat_tca, ...
        'P_deb_tca', P_deb_tca, ...
        'sat_tca_position_error_m', norm(error_sat(1:3)), ...
        'deb_tca_position_error_m', norm(error_deb(1:3)), ...
        'sat_tca_velocity_error_mps', norm(error_sat(4:6)), ...
        'deb_tca_velocity_error_mps', norm(error_deb(4:6)), ...
        'nees_sat', error_sat' * (P_sat_tca \ error_sat), ...
        'nees_deb', error_deb' * (P_deb_tca \ error_deb), ...
        'expected_nees', 6, ...
        'contract', 'CDM-style estimated TCA state and covariance');
    observation = struct('estimate', estimate, ...
                         'diagnostics', diagnostics, ...
                         'config', config, 'seed', seed);
end

function X_start = propagate_backward(X_tca, duration_s, c)
    options = odeset('RelTol', 1e-8, 'AbsTol', 1e-10, ...
                     'Events', @(t, X) earth_collision_event(t, X, c));
    [t, X] = ode45(@(time, state) twoBodyJ2Drag_simple(time, state, c), ...
                   [0, -duration_s], X_tca, options);
    if abs(t(end) + duration_s) > 1
        error('ACAM:CdmBackPropagationFailed', ...
              'Estimated CDM state did not reach the decision epoch.');
    end
    X_start = X(end, :)';
end

function R_h2e = hill_to_eci(X)
    r_hat = X(1:3) / norm(X(1:3));
    h_hat = cross(X(1:3), X(4:6));
    if norm(h_hat) <= eps
        error('ACAM:InvalidHillFrame', ...
              'TCA state has zero angular momentum.');
    end
    h_hat = h_hat / norm(h_hat);
    t_hat = cross(h_hat, r_hat);
    R_h2e = [r_hat, t_hat, h_hat];
end
