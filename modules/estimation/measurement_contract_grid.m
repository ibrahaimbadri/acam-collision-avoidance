function grid = measurement_contract_grid()
%MEASUREMENT_CONTRACT_GRID Frozen tracking sensitivity candidates and gates.
%
% These are synthetic full-state observation assumptions, not claims about a
% particular radar network. Quality and cadence vary independently (2 x 2).

    base = ekf_tracking_config();
    quality = struct( ...
        'label', {'moderate', 'precise'}, ...
        'position_sigma_m', {100, 30}, ...
        'velocity_sigma_mps', {0.10, 0.03});
    cadence = struct( ...
        'label', {'sparse', 'frequent'}, ...
        'pass_duration_s', {600, 1200}, ...
        'period_scale', {0.90, 0.45});
    candidates = repmat(struct( ...
        'id', '', 'quality', '', 'cadence', '', 'config', base), 4, 1);
    index = 0;
    for q = 1:numel(quality)
        for d = 1:numel(cadence)
            index = index + 1;
            config = base;
            config.measurement_position_sigma_m = ...
                quality(q).position_sigma_m;
            config.measurement_velocity_sigma_mps = ...
                quality(q).velocity_sigma_mps;
            config.visibility_pass_duration_s = cadence(d).pass_duration_s;
            config.visibility_period_scale = cadence(d).period_scale;
            config.calibration_note = sprintf( ...
                ['predeclared grid: %s quality, %s cadence; ', ...
                 'synthetic full-state measurements only'], ...
                quality(q).label, cadence(d).label);
            candidates(index) = struct( ...
                'id', sprintf('%s_%s', quality(q).label, cadence(d).label), ...
                'quality', quality(q).label, ...
                'cadence', cadence(d).label, ...
                'config', config);
        end
    end
    grid = struct( ...
        'version', 1, ...
        'purpose', ['screen observation assumptions before model training; ', ...
                    'not operational sensor validation'], ...
        'paired_common_scenarios', true, ...
        'candidates', candidates, ...
        'screening_gates', struct( ...
            'minimum_dangerous_scenarios', 8, ...
            'minimum_dangerous_recall', 0.80, ...
            'maximum_false_alarm_rate', 0.25, ...
            'maximum_median_absolute_log10_error', 1.0, ...
            'minimum_log10_correlation', 0.50, ...
            'minimum_median_mean_nees', 3.0, ...
            'maximum_median_mean_nees', 12.0, ...
            'minimum_median_mean_nis', 3.0, ...
            'maximum_median_mean_nis', 12.0), ...
        'selection_rule', [ ...
            'shortlist only gate-passing candidate/lead pairs; rank by ', ...
            'misses, false alarms, Pc error, correlation, consistency, ', ...
            'observation burden, then prefer more decision lead']);
end
