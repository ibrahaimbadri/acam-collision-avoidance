function [contract, message] = cdm_sequence_contract()
%CDM_SEQUENCE_CONTRACT Versioned model-facing CDM time-series schema.

    contract = struct( ...
        'name', 'ACAM_CDM_SEQUENCE', ...
        'version', 1, ...
        'ordering', 'earliest issue to latest issue', ...
        'time_basis', 'seconds remaining to TCA', ...
        'risk_units', 'probability in [0,1]', ...
        'frame', 'RTN at TCA', ...
        'object_roles', 'target=controlled spacecraft, chaser=other object');

    nan3 = nan(3, 1);
    nan6 = nan(6, 1);
    nan33 = nan(3, 3);
    message = struct( ...
        'message_id', '', ...
        'event_id', '', ...
        'source', '', ...
        'time_to_tca_s', NaN, ...
        'collision_probability', NaN, ...
        'maximum_collision_probability', NaN, ...
        'miss_distance_m', NaN, ...
        'relative_speed_mps', NaN, ...
        'relative_position_rtn_m', nan3, ...
        'relative_velocity_rtn_mps', nan3, ...
        'target_position_covariance_rtn_m2', nan33, ...
        'chaser_position_covariance_rtn_m2', nan33, ...
        'combined_position_covariance_rtn_m2', nan33, ...
        'target_state_eci_tca', nan6, ...
        'chaser_state_eci_tca', nan6, ...
        'target_state_eci_at_message', nan6, ...
        'chaser_state_eci_at_message', nan6, ...
        'altitude_m', NaN, ...
        'spacecraft_mass_kg', NaN, ...
        'hbr_m', NaN);
end
