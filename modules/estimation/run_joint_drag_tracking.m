function [tracking, observations] = run_joint_drag_tracking( ...
        scenario, c, config, seed, observations)
%RUN_JOINT_DRAG_TRACKING Joint drag/density Cartesian EKF.

    duration_s = min(scenario.t_to_cpa - config.reserve_before_tca_s, ...
        config.max_tracking_duration_s);
    duration_s = floor(duration_s / config.dt_s) * config.dt_s;
    if duration_s < config.dt_s
        error('ACAM:InvalidTrackingWindow', 'Joint tracking window is empty.');
    end
    stream = RandStream('mt19937ar', 'Seed', mod(double(seed), 2^32 - 1));
    prior_sigma = [repmat(config.prior_position_sigma_m, 1, 3), ...
                   repmat(config.prior_velocity_sigma_mps, 1, 3)];
    reference_cd_area_mass = c.Cd * c.A / c.scenario_mass;
    true_target_scale = log(scenario.target_physical.drag_coefficient * ...
        scenario.target_physical.area_to_mass_m2pkg / reference_cd_area_mass);
    true_debris_scale = log(scenario.debris_physical.drag_coefficient * ...
        scenario.debris_physical.area_to_mass_m2pkg / reference_cd_area_mass);
    if strcmp(config.ballistic_prior_mode, 'scenario_noisy')
        prior_stream = RandStream('mt19937ar', 'Seed', mod(double( ...
            config.ballistic_prior_seed_offset + scenario.scenario_seed), ...
            2^32 - 1));
        target_ballistic_sigma = config.target_ballistic_prior_sigma_log;
        debris_ballistic_sigma = config.debris_ballistic_prior_sigma_log;
        target_mean = true_target_scale + ...
            target_ballistic_sigma * randn(prior_stream);
        debris_mean = true_debris_scale + ...
            debris_ballistic_sigma * randn(prior_stream);
    else
        target_ballistic_sigma = config.ballistic_prior_sigma_log;
        debris_ballistic_sigma = config.ballistic_prior_sigma_log;
        target_mean = log(config.population_mean_cd * ...
            config.target_median_area_to_mass_m2pkg / reference_cd_area_mass);
        debris_mean = log(config.population_mean_cd * ...
            config.debris_median_area_to_mass_m2pkg / reference_cd_area_mass);
    end
    state = [scenario.X0_sat + prior_sigma(:) .* randn(stream, 6, 1); ...
             scenario.X0_deb + prior_sigma(:) .* randn(stream, 6, 1); ...
             target_mean; debris_mean; 0];
    variances = [prior_sigma.^2, prior_sigma.^2, ...
        target_ballistic_sigma^2, debris_ballistic_sigma^2, ...
        config.density_stationary_sigma_log^2];
    if config.differential_density_enabled
        state(end + 1, 1) = 0;
        variances(end + 1) = ...
            config.differential_density_stationary_sigma_log^2;
    end
    covariance = diag(variances);
    measurement_sigma = [repmat(config.measurement_position_sigma_m, 1, 3), ...
                         repmat(config.measurement_velocity_sigma_mps, 1, 3)];
    if nargin < 5 || isempty(observations)
        times = (0:config.dt_s:duration_s)';
        tolerance = truth_propagation_tolerance(scenario, ...
            struct('rel_tol', 1e-8, 'abs_tol', 1e-10));
        options = odeset('RelTol', tolerance.rel_tol, ...
            'AbsTol', tolerance.abs_tol);
        truth_dynamics = truth_dynamics_pair(scenario, c, duration_s);
        [~, target_truth] = ode45( ...
            truth_dynamics.target, times, scenario.X0_sat, options);
        [~, debris_truth] = ode45( ...
            truth_dynamics.debris, times, scenario.X0_deb, options);
        truth = [target_truth, debris_truth];
        noise = randn(stream, numel(times), 12) .* ...
            [measurement_sigma, measurement_sigma];
        measurements = truth + noise;
        available = visibility_schedule( ...
            times, scenario.orbital_period, seed, config);
        observations = struct('times', times, 'truth', truth, ...
            'target_truth', target_truth, 'debris_truth', debris_truth, ...
            'measurements', measurements, 'available', available, ...
            'seed', seed, 'truth_model_mode', truth_dynamics.mode);
    else
        required = {'times', 'truth', 'target_truth', 'debris_truth', ...
                    'measurements', 'available', 'seed', 'truth_model_mode'};
        if ~all(isfield(observations, required)) || observations.seed ~= seed
            error('ACAM:InvalidJointObservationSet', ...
                  'Reused observations do not match this tracking seed.');
        end
        times = observations.times;
        truth = observations.truth;
        target_truth = observations.target_truth;
        debris_truth = observations.debris_truth;
        measurements = observations.measurements;
        available = observations.available;
    end
    n = numel(times);
    H = [eye(12), zeros(12, config.state_dimension - 12)];
    R = diag([measurement_sigma.^2, measurement_sigma.^2]);
    history = zeros(n, config.state_dimension);
    covariance_history = zeros(config.state_dimension, ...
        config.state_dimension, n);
    nees12 = NaN(n, 1);
    nis12 = NaN(n, 1);
    innovations = NaN(n, 12);
    for k = 1:n
        if k > 1
            [state, Phi, Q] = joint_drag_transition(state, config.dt_s, c, config);
            covariance = Phi * covariance * Phi' + Q;
            covariance = (covariance + covariance') / 2;
        end
        assert_spd(covariance, k, 'prediction');
        if available(k)
            innovation = measurements(k, :)' - H * state;
            S = H * covariance * H' + R;
            S = (S + S') / 2;
            assert_spd(S, k, 'innovation');
            K = covariance * H' / S;
            state = state + K * innovation;
            IKH = eye(config.state_dimension) - K * H;
            covariance = IKH * covariance * IKH' + K * R * K';
            covariance = (covariance + covariance') / 2;
            nis12(k) = innovation' * (S \ innovation);
            innovations(k, :) = innovation';
        end
        assert_spd(covariance, k, 'posterior');
        orbital_error = state(1:12) - truth(k, :)';
        orbital_covariance = covariance(1:12, 1:12);
        nees12(k) = orbital_error' * (orbital_covariance \ orbital_error);
        history(k, :) = state';
        covariance_history(:, :, k) = covariance;
    end
    observed = times(available);
    tracking = struct('state', state, 'covariance', covariance, ...
        'tracking_duration_s', duration_s, 'measurement_available', available, ...
        'diagnostics', struct( ...
            'truth_state_final', truth(end, :)', ...
            'truth_target_final', target_truth(end, :)', ...
            'truth_debris_final', debris_truth(end, :)', ...
            'true_target_log_drag_scale', true_target_scale, ...
            'true_debris_log_drag_scale', true_debris_scale, ...
            'target_ballistic_prior_mean', target_mean, ...
            'debris_ballistic_prior_mean', debris_mean, ...
            'target_ballistic_prior_sigma', target_ballistic_sigma, ...
            'debris_ballistic_prior_sigma', debris_ballistic_sigma, ...
            'estimated_target_log_drag_scale', state(13), ...
            'estimated_debris_log_drag_scale', state(14), ...
            'estimated_shared_log_density', state(15), ...
            'mean_nees12', mean(nees12, 'omitnan'), ...
            'mean_nis12', mean(nis12, 'omitnan'), ...
            'nees12', nees12, 'nis12', nis12, ...
            'innovations', innovations, 'measurement_schedule', available, ...
            'observation_times_s', observed, 'state_history', history, ...
            'covariance_history', covariance_history, ...
            'cross_covariance_fro', norm(covariance(1:6, 7:12), 'fro'), ...
            'truth_model_mode', observations.truth_model_mode));
end

function available = visibility_schedule(times, orbital_period, seed, config)
    interval = config.visibility_period_scale * orbital_period;
    phase = mod(double(seed), interval);
    available = mod(times + phase, interval) <= config.visibility_pass_duration_s;
    if config.include_initial_observation, available(1) = true; end
end

function assert_spd(P, sample, label)
    [~, status] = chol((P + P') / 2);
    if status ~= 0 || any(~isfinite(P), 'all')
        error('ACAM:JointEkfCovarianceInvalid', ...
            'Joint %s covariance is invalid at sample %d.', label, sample);
    end
end
