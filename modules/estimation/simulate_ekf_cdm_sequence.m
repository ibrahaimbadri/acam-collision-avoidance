function [sequence, audit] = simulate_ekf_cdm_sequence( ...
        scenario, c, lead_times_s, seed, tracking_config)
%SIMULATE_EKF_CDM_SEQUENCE Carry one EKF through successive CDM updates.

    if nargin < 5 || isempty(tracking_config)
        tracking_config = ekf_tracking_config();
    end
    validateattributes(lead_times_s, {'numeric'}, ...
        {'real', 'finite', 'vector', 'positive'}, ...
        mfilename, 'lead_times_s');
    leads = sort(lead_times_s(:), 'descend');
    window_s = tracking_config.max_tracking_duration_s;
    starts_before_tca_s = leads + window_s;
    if scenario.t_to_cpa <= starts_before_tca_s(1)
        error('ACAM:InvalidLinkedEkfSchedule', ...
              'Scenario starts too late for the first tracking window.');
    end
    [sat_starts, deb_starts] = states_before_tca( ...
        scenario, starts_before_tca_s, c);
    [~, template] = cdm_sequence_contract();
    messages = repmat(template, numel(leads), 1);
    audit_messages = cell(numel(leads), 1);
    event_id = sprintf('synthetic-ekf-%d', scenario.scenario_seed);
    posterior = [];
    previous_lead_s = NaN;
    for i = 1:numel(leads)
        gap_diagnostics = struct('duration_s', 0, ...
            'process_noise_approximation', 'none');
        if i > 1
            gap_s = previous_lead_s - starts_before_tca_s(i);
            if gap_s < 0
                error('ACAM:OverlappingLinkedEkfWindows', ...
                      'Tracking windows overlap; reduce window duration.');
            end
            [posterior.X_sat, posterior.P_sat, gap_sat] = ...
                propagate_state_covariance(posterior.X_sat, ...
                    posterior.P_sat, gap_s, c, tracking_config);
            [posterior.X_deb, posterior.P_deb, gap_deb] = ...
                propagate_state_covariance(posterior.X_deb, ...
                    posterior.P_deb, gap_s, c, tracking_config);
            gap_diagnostics = struct( ...
                'duration_s', gap_s, 'satellite', gap_sat, ...
                'debris', gap_deb, ...
                'process_noise_approximation', ...
                    gap_sat.process_noise_approximation);
        end
        segment = scenario;
        segment.X0_sat = sat_starts(:, i);
        segment.X0_deb = deb_starts(:, i);
        segment.t_to_cpa = starts_before_tca_s(i);
        segment.orbital_period = scenario.orbital_period;
        if isfield(scenario, 'truth_tca_epoch_utc')
            segment.truth_epoch_utc = scenario.truth_tca_epoch_utc - ...
                seconds(starts_before_tca_s(i));
        end
        tracking = run_ekf_tracking( ...
            segment, c, tracking_config, seed + 1000 * i, posterior);
        posterior = struct( ...
            'X_sat', tracking.X_sat_est, ...
            'X_deb', tracking.X_deb_est, ...
            'P_sat', tracking.P_sat, ...
            'P_deb', tracking.P_deb);
        message_id = sprintf('%s-%ds', event_id, round(leads(i)));
        platform = struct( ...
            'event_id', event_id, ...
            'spacecraft_mass_kg', scenario.mass, ...
            'hbr_m', scenario.hbr_m);
        [messages(i), assessment, tca_state] = generate_cdm_from_estimate( ...
            posterior, platform, c, leads(i), tracking_config, message_id);
        audit_messages{i} = struct( ...
            'message_id', message_id, ...
            'nominal_lead_s', leads(i), ...
            ... % Decision-epoch posterior, already computed above. Exposed
            ... % so diagnostics can separate estimate error from covariance
            ... % error without re-running the filter. Nothing else reads it.
            'decision_posterior', posterior, ...
            ... % Authoritative 6x6 TCA covariances from the CDM's own
            ... % propagation. Consumers needing velocity or cross-covariance
            ... % terms must read these rather than recompute.
            'tca_state', tca_state, ...
            'tracking', tracking.diagnostics, ...
            'gap_propagation', gap_diagnostics, ...
            'conjunction_assessment', assessment);
        previous_lead_s = leads(i);
    end
    raw = struct( ...
        'event_id', event_id, ...
        'source', 'synthetic_linked_ekf', ...
        'messages', messages, ...
        'metadata', struct( ...
            'relative_state_convention', 'target minus chaser', ...
            'risk_scale', 'probability', ...
            'maneuver_validation_supported', true, ...
            'notes', ['One EKF posterior continued through successive ', ...
                      'tracking windows; synthetic measurement model.']));
    sequence = parse_cdm_sequence(raw);
    audit = struct( ...
        'event_id', event_id, ...
        'proposal_collision_probability', scenario.Pc_initial, ...
        'messages', {audit_messages});
end

function [sat_states, deb_states] = states_before_tca( ...
        scenario, durations_s, c)
    [sorted_durations, order] = sort(durations_s, 'ascend');
    final_time = -sorted_durations(end);
    truth_tolerance = truth_propagation_tolerance(scenario, ...
        struct('rel_tol', 1e-8, 'abs_tol', 1e-10));
    options = odeset('RelTol', truth_tolerance.rel_tol, ...
                     'AbsTol', truth_tolerance.abs_tol, ...
                     'Events', @(t, X) earth_collision_event(t, X, c));
    context = scenario;
    if isfield(scenario, 'truth_tca_epoch_utc')
        context.truth_epoch_utc = scenario.truth_tca_epoch_utc;
    end
    truth_dynamics = truth_dynamics_pair(context, c, final_time);
    sat_solution = ode45(truth_dynamics.target, ...
                         [0, final_time], scenario.X_cpa_sat, options);
    deb_solution = ode45(truth_dynamics.debris, ...
                         [0, final_time], scenario.X_cpa_deb, options);
    if abs(sat_solution.x(end) - final_time) > 1 || ...
            abs(deb_solution.x(end) - final_time) > 1
        error('ACAM:LinkedEkfBackPropagationFailed', ...
              'Truth propagation did not reach every tracking window.');
    end
    sat_states = zeros(6, numel(durations_s));
    deb_states = zeros(6, numel(durations_s));
    sat_states(:, order) = deval(sat_solution, -sorted_durations');
    deb_states(:, order) = deval(deb_solution, -sorted_durations');
end
