function Q = process_noise_covariance(duration_s, config)
%PROCESS_NOISE_COVARIANCE White-acceleration process noise in SI units.

    validateattributes(duration_s, {'numeric'}, ...
        {'real', 'finite', 'scalar', 'nonnegative'}, ...
        mfilename, 'duration_s');
    q = config.process_acceleration_psd_m2ps3 * ...
        config.process_noise_scale;
    validateattributes(q, {'numeric'}, ...
        {'real', 'finite', 'scalar', 'nonnegative'}, mfilename, ...
        'process_acceleration_psd_m2ps3');
    I = eye(3);
    Q = q * [ ...
        duration_s^3 / 3 * I, duration_s^2 / 2 * I; ...
        duration_s^2 / 2 * I, duration_s * I];
end
