function [X_final, P_final, diagnostics] = propagate_state_covariance( ...
        X_initial, P_initial, duration_s, c, tracking_config)
%PROPAGATE_STATE_COVARIANCE Propagate one estimate and its covariance.

    validateattributes(X_initial, {'numeric'}, ...
        {'real', 'finite', 'vector', 'numel', 6}, mfilename, 'X_initial');
    validateattributes(P_initial, {'numeric'}, ...
        {'real', 'finite', 'size', [6, 6]}, mfilename, 'P_initial');
    validateattributes(duration_s, {'numeric'}, ...
        {'real', 'finite', 'scalar', 'nonnegative'}, ...
        mfilename, 'duration_s');
    if duration_s == 0
        X_final = X_initial(:);
        P_final = (P_initial + P_initial') / 2;
        diagnostics = struct('duration_s', 0, 'process_noise_steps', 0, ...
            'process_noise_approximation', 'none');
        return;
    end
    step_s = tracking_config.covariance_propagation_step_s;
    validateattributes(step_s, {'numeric'}, ...
        {'real', 'finite', 'scalar', 'positive'}, ...
        mfilename, 'covariance_propagation_step_s');
    X_final = X_initial(:);
    P_final = (P_initial + P_initial') / 2;
    Phi_total = eye(6);
    elapsed_s = 0;
    num_steps = 0;
    while elapsed_s < duration_s
        dt_s = min(step_s, duration_s - elapsed_s);
        [X_final, Phi_step] = propagate_state_and_stm(X_final, dt_s, c);
        P_final = Phi_step * P_final * Phi_step' + ...
                  process_noise_covariance(dt_s, tracking_config);
        P_final = (P_final + P_final') / 2;
        Phi_total = Phi_step * Phi_total;
        elapsed_s = elapsed_s + dt_s;
        num_steps = num_steps + 1;
    end
    [~, status] = chol(P_final);
    if status ~= 0 || any(~isfinite(P_final), 'all')
        error('ACAM:EstimateCovarianceInvalid', ...
              'Propagated covariance is not finite SPD.');
    end
    diagnostics = struct( ...
        'duration_s', duration_s, ...
        'process_noise_steps', num_steps, ...
        'covariance_step_s', step_s, ...
        'state_transition_matrix', Phi_total, ...
        'process_noise_approximation', ...
            ['short-step white acceleration, dynamically transported ', ...
             'through the nonlinear reference orbit']);
end
