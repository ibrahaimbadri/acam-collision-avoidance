function tracking = run_ekf_tracking(scenario, c, config, seed, initial_estimate)
%RUN_EKF_TRACKING Run deterministic simulated Cartesian EKF tracking.
%
% The satellite and debris filters have independent noisy priors, independent
% measurement noise, and independent posterior covariances.  The visibility
% schedule is deterministic from the saved seed/configuration and deliberately
% does not force the final sample to be observed.

    if nargin < 3 || isempty(config)
        config = ekf_tracking_config();
    end
    if nargin < 4
        seed = scenario.scenario_seed;
    end
    if nargin < 5
        initial_estimate = [];
    end
    validateattributes(seed, {'numeric'}, ...
        {'real', 'finite', 'scalar', 'integer', 'nonnegative'}, ...
        mfilename, 'seed');

    tracking_duration_s = min( ...
        scenario.t_to_cpa - config.reserve_before_tca_s, ...
        config.max_tracking_duration_s);
    tracking_duration_s = floor(tracking_duration_s / config.dt_s) * ...
                          config.dt_s;
    if tracking_duration_s < config.dt_s || ...
            scenario.t_to_cpa - tracking_duration_s <= 0
        error('ACAM:InvalidTrackingWindow', ...
              'EKF tracking window must leave a positive maneuver window.');
    end

    tspan = (0:config.dt_s:tracking_duration_s)';
    n_samples = numel(tspan);
    truth_tolerance = truth_propagation_tolerance(scenario, ...
        struct('rel_tol', 1e-8, 'abs_tol', 1e-10));
    options = odeset('RelTol', truth_tolerance.rel_tol, ...
                     'AbsTol', truth_tolerance.abs_tol);
    truth_dynamics = truth_dynamics_pair(scenario, c, tracking_duration_s);
    [~, X_sat_true] = ode45(truth_dynamics.target, ...
                            tspan, scenario.X0_sat, options);
    [~, X_deb_true] = ode45(truth_dynamics.debris, ...
                            tspan, scenario.X0_deb, options);

    stream = RandStream('mt19937ar', 'Seed', mod(double(seed), 2^32 - 1));
    prior_sigma = [repmat(config.prior_position_sigma_m, 1, 3), ...
                   repmat(config.prior_velocity_sigma_mps, 1, 3)];
    if isempty(initial_estimate)
        prior_covariance_sat = diag(prior_sigma.^2);
        prior_covariance_deb = prior_covariance_sat;
        X_sat_prior = scenario.X0_sat + ...
            prior_sigma(:) .* randn(stream, 6, 1);
        X_deb_prior = scenario.X0_deb + ...
            prior_sigma(:) .* randn(stream, 6, 1);
    else
        required = {'X_sat', 'X_deb', 'P_sat', 'P_deb'};
        for i = 1:numel(required)
            if ~isfield(initial_estimate, required{i})
                error('ACAM:InvalidEkfInitialEstimate', ...
                      'Missing initial_estimate.%s.', required{i});
            end
        end
        X_sat_prior = initial_estimate.X_sat(:);
        X_deb_prior = initial_estimate.X_deb(:);
        prior_covariance_sat = initial_estimate.P_sat;
        prior_covariance_deb = initial_estimate.P_deb;
        validateattributes(X_sat_prior, {'numeric'}, ...
            {'real', 'finite', 'numel', 6}, mfilename, ...
            'initial_estimate.X_sat');
        validateattributes(X_deb_prior, {'numeric'}, ...
            {'real', 'finite', 'numel', 6}, mfilename, ...
            'initial_estimate.X_deb');
        if ~covariance_is_spd(prior_covariance_sat) || ...
                ~covariance_is_spd(prior_covariance_deb)
            error('ACAM:InvalidEkfInitialEstimate', ...
                  'Initial posterior covariances must be SPD.');
        end
    end

    measurement_sigma = [ ...
        repmat(config.measurement_position_sigma_m, 1, 3), ...
        repmat(config.measurement_velocity_sigma_mps, 1, 3)];
    measurement_available = visibility_schedule( ...
        tspan, scenario.orbital_period, seed, config);
    measurement_noise_sat = randn(stream, n_samples, 6) .* measurement_sigma;
    measurement_noise_deb = randn(stream, n_samples, 6) .* measurement_sigma;
    Z_sat = X_sat_true + measurement_noise_sat;
    Z_deb = X_deb_true + measurement_noise_deb;

    [sat_history, P_sat, P_sat_history, nees_sat, nis_sat, ...
        innovations_sat] = run_filter( ...
        Z_sat, X_sat_true, tspan, X_sat_prior, prior_covariance_sat, ...
        measurement_available, config, c);
    [deb_history, P_deb, P_deb_history, nees_deb, nis_deb, ...
        innovations_deb] = run_filter( ...
        Z_deb, X_deb_true, tspan, X_deb_prior, prior_covariance_deb, ...
        measurement_available, config, c);

    observed_times = tspan(measurement_available);
    if isempty(observed_times)
        last_observation_time_s = NaN;
        time_since_last_observation_s = tracking_duration_s;
    else
        last_observation_time_s = observed_times(end);
        time_since_last_observation_s = tracking_duration_s - ...
                                        last_observation_time_s;
    end

    sat_position_error = sat_history(end, 1:3)' - X_sat_true(end, 1:3)';
    deb_position_error = deb_history(end, 1:3)' - X_deb_true(end, 1:3)';
    sat_velocity_error = sat_history(end, 4:6)' - X_sat_true(end, 4:6)';
    deb_velocity_error = deb_history(end, 4:6)' - X_deb_true(end, 4:6)';
    diagnostics = struct( ...
        'continued_from_previous_posterior', ~isempty(initial_estimate), ...
        'tracking_duration_s', tracking_duration_s, ...
        'remaining_time_s', scenario.t_to_cpa - tracking_duration_s, ...
        'num_observations_sat', nnz(measurement_available), ...
        'num_observations_deb', nnz(measurement_available), ...
        'last_observation_time_s', last_observation_time_s, ...
        'time_since_last_observation_s', time_since_last_observation_s, ...
        'est_error_sat_m', norm(sat_position_error), ...
        'est_error_deb_m', norm(deb_position_error), ...
        'est_error_sat_velocity_mps', norm(sat_velocity_error), ...
        'est_error_deb_velocity_mps', norm(deb_velocity_error), ...
        'truth_state_sat_final', X_sat_true(end, :)', ...
        'truth_state_deb_final', X_deb_true(end, :)', ...
        'initial_prior_error_sat_m', norm(X_sat_prior - scenario.X0_sat), ...
        'initial_prior_error_deb_m', norm(X_deb_prior - scenario.X0_deb), ...
        'posterior_trace_sat', trace(P_sat), ...
        'posterior_trace_deb', trace(P_deb), ...
        'mean_nees_sat', finite_mean(nees_sat), ...
        'mean_nees_deb', finite_mean(nees_deb), ...
        'mean_nis_sat', finite_mean(nis_sat), ...
        'mean_nis_deb', finite_mean(nis_deb), ...
        'expected_nees', 6, ...
        'expected_nis', 6, ...
        'num_finite_nees_sat', nnz(isfinite(nees_sat)), ...
        'num_finite_nees_deb', nnz(isfinite(nees_deb)), ...
        'num_finite_nis_sat', nnz(isfinite(nis_sat)), ...
        'num_finite_nis_deb', nnz(isfinite(nis_deb)), ...
        'covariance_spd_sat', covariance_is_spd(P_sat), ...
        'covariance_spd_deb', covariance_is_spd(P_deb), ...
        'measurement_model', config.measurement_model_label, ...
        'covariance_assumption', config.covariance_assumption, ...
        'truth_model_mode', truth_dynamics.mode, ...
        'truth_model_contract_version', truth_dynamics.contract_version, ...
        'visibility_seed', seed, ...
        'measurement_schedule', measurement_available, ...
        'observation_times_s', observed_times, ...
        'nees_sat', nees_sat, ...
        'nees_deb', nees_deb, ...
        'nis_sat', nis_sat, ...
        'nis_deb', nis_deb, ...
        'innovations_sat', innovations_sat, ...
        'innovations_deb', innovations_deb, ...
        'P_sat_history', P_sat_history, ...
        'P_deb_history', P_deb_history);

    % Opt-in exact draw audit, off by default. Stage 5a compares candidates
    % that differ only in process_noise_scale and must PROVE they saw
    % identical stochastic inputs rather than assume equal seeds imply it.
    % Exact arrays, not a checksum: no collision risk and no serialization
    % ambiguity. The caller compares with isequaln and discards the raw
    % arrays before checkpointing.
    if isfield(config, 'return_draw_audit') && config.return_draw_audit
        diagnostics.draw_audit = struct( ...
            'prior_error_sat', X_sat_prior(:) - scenario.X0_sat(:), ...
            'prior_error_deb', X_deb_prior(:) - scenario.X0_deb(:), ...
            'measurement_noise_sat', measurement_noise_sat, ...
            'measurement_noise_deb', measurement_noise_deb, ...
            'measurement_schedule', measurement_available, ...
            'observation_times_s', observed_times);
    end

    tracking = struct( ...
        'X_sat_est', sat_history(end, :)', ...
        'X_deb_est', deb_history(end, :)', ...
        'P_sat', P_sat, ...
        'P_deb', P_deb, ...
        'tracking_duration_s', tracking_duration_s, ...
        'est_error_sat_m', norm(sat_position_error), ...
        'est_error_deb_m', norm(deb_position_error), ...
        'measurement_available', measurement_available, ...
        'diagnostics', diagnostics);
end

function available = visibility_schedule(tspan, orbital_period, seed, config)
    pass_interval = config.visibility_period_scale * orbital_period;
    phase = mod(double(seed), pass_interval);
    available = mod(tspan + phase, pass_interval) <= ...
                config.visibility_pass_duration_s;
    if config.include_initial_observation
        available(1) = true;
    end
end

function [history, P, P_history, nees, nis, innovations] = run_filter( ...
        measurements, truth, tspan, x_prior, P_prior, available, config, c)
    n_samples = numel(tspan);
    dt = config.dt_s;
    H = eye(6);
    R = diag([ ...
        repmat(config.measurement_position_sigma_m, 1, 3).^2, ...
        repmat(config.measurement_velocity_sigma_mps, 1, 3).^2]);
    Q = process_noise_covariance(dt, config);
    x_est = x_prior;
    P = (P_prior + P_prior') / 2;
    if ~covariance_is_spd(P)
        error('ACAM:EkfCovarianceInvalid', 'Initial EKF covariance is not SPD.');
    end

    history = zeros(n_samples, 6);
    P_history = zeros(6, 6, n_samples);
    nees = NaN(n_samples, 1);
    nis = NaN(n_samples, 1);
    innovations = NaN(n_samples, 6);
    options = odeset('RelTol', 1e-8, 'AbsTol', 1e-10);

    for k = 1:n_samples
        if k == 1
            x_pred = x_est;
            P_pred = P;
        else
            [~, x_temp] = ode45(@(t, X) twoBodyJ2Drag_simple(t, X, c), ...
                                [0, dt], x_est, options);
            x_pred = x_temp(end, :)';
            Phi = compute_state_transition_jacobian(x_est, dt, c);
            P_pred = Phi * P * Phi' + Q;
            P_pred = (P_pred + P_pred') / 2;
        end
        if ~covariance_is_spd(P_pred)
            error('ACAM:EkfCovarianceInvalid', ...
                  'EKF predicted covariance is not SPD at sample %d.', k);
        end

        if available(k)
            innovation = measurements(k, :)' - H * x_pred;
            S = H * P_pred * H' + R;
            S = (S + S') / 2;
            if ~covariance_is_spd(S)
                error('ACAM:EkfInnovationInvalid', ...
                      'EKF innovation covariance is not SPD at sample %d.', k);
            end
            K = P_pred * H' / S;
            x_est = x_pred + K * innovation;
            I_KH = eye(6) - K * H;
            P = I_KH * P_pred * I_KH' + K * R * K';
            innovations(k, :) = innovation';
            nis(k) = innovation' * (S \ innovation);
        else
            x_est = x_pred;
            P = P_pred;
        end
        P = (P + P') / 2;
        if ~covariance_is_spd(P)
            error('ACAM:EkfCovarianceInvalid', ...
                  'EKF posterior covariance is not SPD at sample %d.', k);
        end
        history(k, :) = x_est';
        P_history(:, :, k) = P;
        error_state = x_est - truth(k, :)';
        nees(k) = error_state' * (P \ error_state);
    end
end

function value = covariance_is_spd(P)
    P = (P + P') / 2;
    [~, status] = chol(P);
    value = status == 0 && all(isfinite(P(:)));
end

function value = finite_mean(values)
    values = values(isfinite(values));
    if isempty(values)
        value = NaN;
    else
        value = mean(values);
    end
end
