function contract = sample_independent_physical_properties(target_mass_kg)
%SAMPLE_INDEPENDENT_PHYSICAL_PROPERTIES Draw recorded Stage 5e properties.
%
% The ranges define an experiment distribution, not catalog prevalence.
% Target and debris draws are independent. Area-to-mass ratios are sampled
% log-uniformly because the physically relevant range spans decades.

    validateattributes(target_mass_kg, {'numeric'}, ...
        {'real', 'finite', 'scalar', 'positive'}, mfilename, ...
        'target_mass_kg');

    target = draw_properties(target_mass_kg, [0.003, 0.015], [2.0, 2.4], ...
        [1.1, 1.6]);
    debris_mass_kg = log_uniform(1, 200);
    debris = draw_properties(debris_mass_kg, [0.005, 0.10], [2.0, 2.4], ...
        [1.1, 1.8]);
    contract = struct( ...
        'version', 2, ...
        'design', 'independent_recorded_experiment_distribution', ...
        'stratum_name', 'sampled_independent', ...
        'available_strata', {{'sampled_independent'}}, ...
        'target', target, 'debris', debris, ...
        'target_area_to_mass_range_m2pkg', [0.003, 0.015], ...
        'debris_area_to_mass_range_m2pkg', [0.005, 0.10], ...
        'scope_note', ['Independent experiment draws; not population ', ...
                       'frequency or catalog-prevalence claims.']);
end

function value = draw_properties(mass_kg, ratio_range, cd_range, cr_range)
    ratio = log_uniform(ratio_range(1), ratio_range(2));
    cd = uniform(cd_range(1), cd_range(2));
    cr = uniform(cr_range(1), cr_range(2));
    value = struct( ...
        'mass_kg', mass_kg, ...
        'drag_area_m2', mass_kg * ratio, ...
        'drag_coefficient', cd, ...
        'srp_area_m2', mass_kg * ratio, ...
        'reflectivity_coefficient', cr, ...
        'area_to_mass_m2pkg', ratio, ...
        'ballistic_coefficient_kgpm2', 1 / (cd * ratio));
end

function value = uniform(low, high)
    value = low + (high - low) * rand();
end

function value = log_uniform(low, high)
    value = exp(log(low) + (log(high) - log(low)) * rand());
end
