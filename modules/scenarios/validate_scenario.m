function diagnostics = validate_scenario(scenario, c, config, tca_diagnostics)
%VALIDATE_SCENARIO Apply the Stage 4 orbital and TCA acceptance checks.

    states = [scenario.X0_sat; scenario.X0_deb; ...
              scenario.X_cpa_sat; scenario.X_cpa_deb];
    finite_states = all(isfinite(states));
    finite_covariance = all(isfinite([scenario.C_sat(:); scenario.C_deb(:)]));
    [energy_sat, perigee_sat] = orbital_metrics(scenario.X_cpa_sat, c);
    [energy_deb, perigee_deb] = orbital_metrics(scenario.X_cpa_deb, c);

    [~, sat_cov_status] = chol((scenario.C_sat + scenario.C_sat') / 2);
    [~, deb_cov_status] = chol((scenario.C_deb + scenario.C_deb') / 2);
    covariance_ok = sat_cov_status == 0 && deb_cov_status == 0;
    diagnostics = struct();
    diagnostics.finite = finite_states && finite_covariance;
    diagnostics.orbital_energy_valid = isfinite(energy_sat) && isfinite(energy_deb) && ...
                                        energy_sat < 0 && energy_deb < 0;
    diagnostics.perigee_valid = isfinite(perigee_sat) && isfinite(perigee_deb) && ...
                                perigee_sat >= c.Re + config.min_perigee_altitude_m && ...
                                perigee_deb >= c.Re + config.min_perigee_altitude_m;
    diagnostics.covariance_positive_definite = covariance_ok;
    diagnostics.propagation_valid = ...
        tca_diagnostics.satellite_propagation_end_s >= ...
            tca_diagnostics.search_interval(2) - 1 && ...
        tca_diagnostics.debris_propagation_end_s >= ...
            tca_diagnostics.search_interval(2) - 1 && ...
        tca_diagnostics.minimum_satellite_radius_m > c.Re && ...
        tca_diagnostics.minimum_debris_radius_m > c.Re;
    diagnostics.tca_inside_interval = tca_diagnostics.tca_inside_interval;
    diagnostics.tca_orthogonality_residual = ...
        tca_diagnostics.orthogonality_residual;
    % Gate on the induced miss-distance error, which is in the same unit and
    % budget as the miss-distance tolerance beside it. The cosine and the
    % time offset are reported for continuity but no longer decide anything.
    diagnostics.tca_time_offset_s = tca_diagnostics.tca_time_offset_s;
    diagnostics.along_track_residual_m = ...
        tca_diagnostics.along_track_residual_m;
    diagnostics.induced_miss_error_m = tca_diagnostics.induced_miss_error_m;
    diagnostics.tca_refinement_status = tca_diagnostics.refinement_status;
    % Named for what it checks. The old name said "orthogonality" long after
    % the check stopped testing orthogonality, which is how the same gate
    % got misdiagnosed twice in failure reports.
    diagnostics.tca_stationarity_valid = ...
        diagnostics.induced_miss_error_m <= ...
            config.tca_induced_miss_error_tolerance_m;
    diagnostics.miss_distance_m = norm(scenario.rel_pos);
    diagnostics.miss_distance_error_m = abs(diagnostics.miss_distance_m - ...
                                             scenario.requested_miss_distance_m);
    diagnostics.miss_distance_valid = diagnostics.miss_distance_error_m <= ...
                                      config.tca_miss_distance_tolerance_m;
    diagnostics.round_trip_position_error_m = ...
        tca_diagnostics.round_trip_position_error_m;
    diagnostics.round_trip_position_valid = ...
        isfinite(diagnostics.round_trip_position_error_m) && ...
        diagnostics.round_trip_position_error_m <= ...
            config.round_trip_position_tolerance_m;
    diagnostics.valid = diagnostics.finite && diagnostics.covariance_positive_definite && ...
        diagnostics.orbital_energy_valid && diagnostics.perigee_valid && ...
        diagnostics.propagation_valid && diagnostics.tca_inside_interval && ...
        diagnostics.tca_stationarity_valid && diagnostics.miss_distance_valid && ...
        diagnostics.round_trip_position_valid;
end

function [specific_energy, perigee_radius] = orbital_metrics(X, c)
    r = X(1:3);
    v = X(4:6);
    specific_energy = 0.5 * dot(v, v) - c.mu / norm(r);
    if specific_energy < 0
        semi_major_axis = -c.mu / (2 * specific_energy);
        eccentricity_vector = ((dot(v, v) - c.mu / norm(r)) * r - ...
                               dot(r, v) * v) / c.mu;
        eccentricity = norm(eccentricity_vector);
        perigee_radius = semi_major_axis * (1 - eccentricity);
    else
        perigee_radius = NaN;
    end
end
