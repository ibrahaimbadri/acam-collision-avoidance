function [scenario, metadata, attempt_log] = ...
        generate_synthetic_scenario(config, c, seed)
%GENERATE_SYNTHETIC_SCENARIO Create one verified nonlinear LEO encounter.
%
% The optional third output records EVERY acceptance check for EVERY
% attempt, not just the first check that failed. Reporting only the first
% failure hides masking: a gate tested early can absorb candidates that
% would also have failed a later gate, so removing it appears to create new
% failures that were in fact always present.

    rng(seed, 'twister');
    last_failure = 'no candidate was attempted';
    attempt_log = struct('attempt', {}, 'stage', {}, 'checks', {});
    propagation_tolerance = struct( ...
        'rel_tol', field_or_default(config, 'propagation_rel_tol', 1e-8), ...
        'abs_tol', field_or_default(config, 'propagation_abs_tol', 1e-10));
    % 'required' reproduces historical behaviour exactly and is the default.
    band_gate_mode = validatestring( ...
        field_or_default(config, 'pc_band_gate_mode', 'required'), ...
        {'required', 'diagnostic'}, mfilename, 'pc_band_gate_mode');

    for attempt = 1:config.max_attempts_per_scenario
        altitude = uniform_value(config.primary_altitude_range_m);
        eccentricity = uniform_value(config.primary_eccentricity_range);
        inclination = deg2rad(uniform_value(config.inclination_range_deg));
        raan = 2 * pi * rand();
        argument_of_perigee = 2 * pi * rand();
        true_anomaly = 2 * pi * rand();
        [X_cpa_sat, orbital_basis] = sample_primary_orbit( ...
            c, altitude, eccentricity, inclination, raan, ...
            argument_of_perigee, true_anomaly);

        if isfield(config, 'force_stress')
            is_stress = logical(config.force_stress);
        else
            is_stress = rand() < config.stress_fraction;
        end
        if is_stress
            time_options = config.stress_time_to_tca_s;
        else
            time_options = config.core_time_to_tca_s;
        end
        requested_tca = time_options(randi(numel(time_options)));
        hbr_m = uniform_value(config.hbr_range_m);
        mass = uniform_value(config.mass_range_kg);
        physical_mode = validatestring(field_or_default(config, ...
            'physical_property_mode', 'fixed_strata'), ...
            {'fixed_strata', 'sampled_independent'});
        if strcmp(physical_mode, 'sampled_independent')
            physical = sample_independent_physical_properties(mass);
        else
            physical = physical_property_strata(mass, ...
                field_or_default(config, 'physical_property_stratum', 'matched'));
        end
        truth_model = truth_model_config( ...
            field_or_default(config, 'truth_model_mode', 'nominal'));
        space_weather_mode = validatestring(field_or_default(config, ...
            'space_weather_mode', 'matlab_defaults'), ...
            {'matlab_defaults', 'seeded_variable'});
        if strcmp(space_weather_mode, 'seeded_variable')
            if ~truth_model.include_nrlmsise
                error('ACAM:InertSpaceWeatherProfile', ...
                    'Variable space weather requires NRLMSISE truth.');
            end
            truth_model.version = 2;
            truth_model.space_weather_mode = space_weather_mode;
            truth_model.space_weather_profile = sample_space_weather_profile( ...
                field_or_default(config, 'truth_epoch_utc', ...
                    datetime(2025, 3, 20, 12, 0, 0, 'TimeZone', 'UTC')), ...
                field_or_default(config, 'space_weather_seed_offset', 9180001) + seed);
            truth_model.nrlmsise_space_weather = ...
                'recorded seeded-variable F10.7A/F10.7/seven-Ap profile';
        end
        if isfield(config, 'density_residual_spec')
            if ~truth_model.include_nrlmsise
                error('ACAM:InertDensityResidualProfile', ...
                    'Density-residual sensitivity requires NRLMSISE truth.');
            end
            truth_model.version = max(truth_model.version, 3);
            truth_model.density_residual_profile = ...
                sample_density_residual_profile( ...
                field_or_default(config, 'truth_epoch_utc', ...
                datetime(2025, 3, 20, 12, 0, 0, 'TimeZone', 'UTC')), ...
                field_or_default(config, 'density_residual_seed_offset', ...
                17180001) + seed, config.density_residual_spec);
        end
        % A non-matched property stratum is INERT under nominal truth: the
        % nominal model applies one shared Cd, area and mass to both
        % objects, so requesting differential_4x without also selecting an
        % NRLMSISE truth mode silently produces a matched result and no
        % error. That combination once yielded a bit-identical "4x" run
        % that would have read as a clean null. Fail loudly instead.
        if ~strcmp(physical.stratum_name, 'matched') && ...
                ~truth_model.include_nrlmsise
            error('ACAM:InertPhysicalPropertyStratum', ...
                  ['Physical-property stratum "%s" has no effect under ', ...
                   'truth model "%s": the nominal model shares one set of ', ...
                   'ballistic properties between both objects. Select an ', ...
                   'NRLMSISE truth mode, or use the matched stratum.'], ...
                  physical.stratum_name, truth_model.mode);
        end
        truth_model.propagation_rel_tol = propagation_tolerance.rel_tol;
        truth_model.propagation_abs_tol = propagation_tolerance.abs_tol;
        truth_context = struct( ...
            'truth_model', truth_model, ...
            'truth_epoch_utc', field_or_default(config, 'truth_epoch_utc', ...
                datetime(2025, 3, 20, 12, 0, 0, 'TimeZone', 'UTC')), ...
            'target_physical', physical.target, ...
            'debris_physical', physical.debris);
        % Contract version 6: the proposal covariance is per encounter
        % family, so the sigmas cannot be built until the family is known.
        % The three uniforms are still DRAWN here, in the original order and
        % count, and mapped onto the family's range below. That keeps the
        % random stream identical to version 5, so any profile that gives
        % both families the same range -- terminal_reference_scenario_config,
        % and therefore C1, C2, Stage D and Stage D2 -- reproduces its
        % previous scenario population bit for bit.
        sigma_draws = [rand(), rand(), rand()];
        R_local = orbital_basis;

        if isfield(config, 'force_encounter_family')
            encounter_family = char(config.force_encounter_family);
        elseif isfield(config, 'crossing_fraction') && ...
                rand() < config.crossing_fraction
            encounter_family = 'crossing';
        else
            encounter_family = 'co_orbital';
        end
        crossing_angle_deg = NaN;
        if strcmp(encounter_family, 'crossing')
            crossing_angle_deg = ...
                uniform_value(config.crossing_angle_range_deg);
            v_deb = rotate_about_axis(X_cpa_sat(4:6), R_local(:, 1), ...
                                      deg2rad(crossing_angle_deg));
            rel_vel_cpa = X_cpa_sat(4:6) - v_deb;
            relative_speed = norm(rel_vel_cpa);
            rel_pos_direction = perpendicular_direction(rel_vel_cpa);
        else
            relative_speed = uniform_value(config.relative_speed_range_mps);
            if rand() < 0.5
                relative_speed = -relative_speed;
            end
            rel_vel_cpa = relative_speed * R_local(:, 2);
            rel_pos_direction = R_local(:, 1);
        end

        family_ranges = proposal_sigma_for_family(config, encounter_family);
        sigma_r = map_to_range(family_ranges.radial_m, sigma_draws(1));
        sigma_t = map_to_range(family_ranges.tangential_m, sigma_draws(2));
        sigma_h = map_to_range(family_ranges.cross_track_m, sigma_draws(3));
        C_sat = R_local * diag([sigma_r^2, sigma_t^2, sigma_h^2]) * R_local';
        C_deb = R_local * diag([(1.15*sigma_r)^2, (0.90*sigma_t)^2, ...
                                (1.25*sigma_h)^2]) * R_local';
        C_sat = (C_sat + C_sat') / 2;
        C_deb = (C_deb + C_deb') / 2;

        band_index = config.pc_band_index;
        target_range = config.pc_band_target_ranges(band_index, :);
        target_pc = sample_log_uniform(target_range(1), target_range(2));
        [miss_distance, distance_ok] = solve_miss_distance( ...
            target_pc, rel_vel_cpa, rel_pos_direction, C_sat, C_deb, hbr_m);
        if ~distance_ok
            last_failure = 'target Pc was outside the achievable covariance range';
            attempt_log(end + 1) = struct('attempt', attempt, ...
                'stage', 'miss_distance_solve', 'checks', []); %#ok<AGROW>
            continue;
        end

        rel_pos_cpa = miss_distance * rel_pos_direction;
        X_cpa_deb = [X_cpa_sat(1:3) - rel_pos_cpa; ...
                     X_cpa_sat(4:6) - rel_vel_cpa];
        c_local = c;
        c_local.HBR = hbr_m;
        c_local.scenario_mass = mass;

        tca_truth_context = truth_context;
        tca_truth_context.truth_epoch_utc = ...
            truth_context.truth_epoch_utc + seconds(requested_tca);
        backward_dynamics = truth_dynamics_pair( ...
            tca_truth_context, c_local, -requested_tca);
        [back_ok, X0_sat, X0_deb] = backpropagate_to_epoch( ...
            X_cpa_sat, X_cpa_deb, requested_tca, c_local, ...
            propagation_tolerance, backward_dynamics);
        if ~back_ok
            last_failure = 'back-propagation reached an invalid trajectory';
            attempt_log(end + 1) = struct('attempt', attempt, ...
                'stage', 'backpropagation', 'checks', []); %#ok<AGROW>
            continue;
        end

        search_interval = [max(60, requested_tca - config.tca_bracket_half_width_s), ...
                           requested_tca + config.tca_bracket_half_width_s];
        forward_dynamics = truth_dynamics_pair( ...
            truth_context, c_local, search_interval(2));
        try
            [tca, X_sat_tca, X_deb_tca, actual_distance, residual, tca_info] = ...
                find_tca(X0_sat, X0_deb, search_interval, c_local, ...
                         requested_tca, X_cpa_sat, X_cpa_deb, ...
                         propagation_tolerance, forward_dynamics);
        catch ME
            if is_ode_failure(ME)
                last_failure = 'forward propagation failed during TCA search';
                attempt_log(end + 1) = struct('attempt', attempt, ...
                    'stage', 'tca_search', 'checks', []); %#ok<AGROW>
                continue;
            end
            rethrow(ME);
        end

        scenario = struct( ...
            'X0_sat', X0_sat, ...
            'X0_deb', X0_deb, ...
            'X_cpa_sat', X_sat_tca, ...
            'X_cpa_deb', X_deb_tca, ...
            'rel_pos', X_sat_tca(1:3) - X_deb_tca(1:3), ...
            'rel_vel', X_sat_tca(4:6) - X_deb_tca(4:6), ...
            't_to_cpa', tca, ...
            'requested_tca_s', requested_tca, ...
            'requested_miss_distance_m', miss_distance, ...
            'dist_cpa', actual_distance, ...
            'altitude', norm(X_sat_tca(1:3)) - c.Re, ...
            'mass', mass, ...
            'target_physical', physical.target, ...
            'debris_physical', physical.debris, ...
            'physical_property_contract_version', physical.version, ...
            'physical_property_stratum', physical.stratum_name, ...
            'truth_model', truth_model, ...
            'truth_epoch_utc', truth_context.truth_epoch_utc, ...
            'truth_tca_epoch_utc', ...
                truth_context.truth_epoch_utc + seconds(tca), ...
            'hbr_m', hbr_m, ...
            'HBR', hbr_m, ...
            'C_sat', C_sat, ...
            'C_deb', C_deb, ...
            'orbital_period', orbital_period(X_sat_tca, c), ...
            'tca_orthogonality_residual', residual, ...
            'requested_risk_band', config.pc_band_labels{band_index}, ...
            'target_pc', target_pc, ...
            'encounter_family', encounter_family, ...
            'crossing_angle_deg', crossing_angle_deg, ...
            'relative_speed_mps', relative_speed, ...
            'scenario_seed', seed);

        checks = validate_scenario(scenario, c_local, config, tca_info);
        Pc_initial = calculatePoC(scenario.rel_pos, scenario.rel_vel, ...
                                  C_sat, C_deb, hbr_m);
        actual_band = pc_band_index(Pc_initial);
        checks.pc_band_valid = actual_band == band_index;
        checks.requested_band_index = band_index;
        checks.realised_band_index = actual_band;
        checks.pc_band_gate_mode = band_gate_mode;
        checks.target_pc = target_pc;
        checks.actual_pc = Pc_initial;
        % Log the complete check set before deciding, so masking between
        % gates is measurable rather than inferred.
        attempt_log(end + 1) = struct('attempt', attempt, ...
            'stage', 'validation', 'checks', checks); %#ok<AGROW>
        % Band membership is a PROPOSAL-SAMPLING criterion, not a validity
        % criterion. In 'required' mode it rejects, exactly as before. In
        % 'diagnostic' mode it is recorded and does not reject, because
        % applying it to a treatment arm conditions eligibility on an
        % outcome the treatment causes. Every physical and numerical gate in
        % checks.valid remains mandatory in both modes, and there is no
        % retry seeking a case that stays in band.
        band_gate_satisfied = checks.pc_band_valid || ...
                              strcmp(band_gate_mode, 'diagnostic');
        if ~(checks.valid && band_gate_satisfied)
            last_failure = validation_failure_reason(checks);
            continue;
        end

        scenario.Pc_initial = Pc_initial;
        % Retained on every scenario so a band excursion is visible to
        % downstream consumers rather than inferable only from the log.
        scenario.pc_band_gate_mode = band_gate_mode;
        scenario.requested_band_index = band_index;
        scenario.realised_band_index = actual_band;
        scenario.pc_band_valid = checks.pc_band_valid;
        scenario.geometry = residual;
        metadata = struct( ...
            'requested_risk_band', config.pc_band_labels{band_index}, ...
            'pc_band_gate_mode', band_gate_mode, ...
            'requested_band_index', band_index, ...
            'realised_band_index', actual_band, ...
            'realised_risk_band', config.pc_band_labels{actual_band}, ...
            'pc_band_valid', checks.pc_band_valid, ...
            'actual_tca_s', tca, ...
            'tca_verified', true, ...
            'tca_orthogonality_residual', residual, ...
            'tca_time_offset_s', tca_info.tca_time_offset_s, ...
            'tca_along_track_residual_m', tca_info.along_track_residual_m, ...
            'tca_induced_miss_error_m', tca_info.induced_miss_error_m, ...
            'tca_refinement_status', tca_info.refinement_status, ...
            'orbital_energy_valid', checks.orbital_energy_valid, ...
            'perigee_valid', checks.perigee_valid, ...
            'propagation_fidelity', truth_model.mode, ...
            'fallback_used', false, ...
            'round_trip_position_error_m', ...
                tca_info.round_trip_position_error_m, ...
            'optimizer_exit_status', NaN, ...
            'initial_pc', Pc_initial, ...
            'final_pc', NaN, ...
            'random_seed', seed, ...
            'requested_tca_s', requested_tca, ...
            'requested_miss_distance_m', miss_distance, ...
            'actual_miss_distance_m', actual_distance, ...
            'miss_distance_error_m', checks.miss_distance_error_m, ...
            'target_pc', target_pc, ...
            'scenario_profile', profile_label(is_stress), ...
            'encounter_family', encounter_family, ...
            'crossing_angle_deg', crossing_angle_deg, ...
            'relative_speed_mps', relative_speed, ...
            'pc_band_index', band_index, ...
            'attempts', attempt, ...
            'hbr_m', hbr_m, ...
            'physical_property_contract_version', physical.version, ...
            'physical_property_stratum', physical.stratum_name, ...
            'truth_model_contract_version', truth_model.version, ...
            'truth_model_mode', truth_model.mode, ...
            'truth_epoch_utc', char(truth_context.truth_epoch_utc), ...
            'target_mass_kg', physical.target.mass_kg, ...
            'target_area_to_mass_m2pkg', ...
                physical.target.area_to_mass_m2pkg, ...
            'target_ballistic_coefficient_kgpm2', ...
                physical.target.ballistic_coefficient_kgpm2, ...
            'debris_mass_kg', physical.debris.mass_kg, ...
            'debris_area_to_mass_m2pkg', ...
                physical.debris.area_to_mass_m2pkg, ...
            'debris_ballistic_coefficient_kgpm2', ...
                physical.debris.ballistic_coefficient_kgpm2, ...
            'optimizer_fidelity', 'not_run', ...
            'evaluation_fidelity', truth_model.mode);
        return;
    end

    % A caller asking for the attempt log is diagnosing acceptance, so it
    % needs the log more than it needs an exception.
    if nargout >= 3
        scenario = [];
        metadata = struct('generation_failed', true, ...
                          'failure_reason', last_failure);
        return;
    end
    error('ACAM:ScenarioGenerationFailed', ...
          'Could not generate band %d with seed %d: %s.', ...
          config.pc_band_index, seed, last_failure);
end

function value = field_or_default(config, name, default_value)
    if isfield(config, name)
        value = config.(name);
    else
        value = default_value;
    end
end

function label = profile_label(is_stress)
    if is_stress
        label = 'stress';
    else
        label = 'core';
    end
end

function [X, R_local] = sample_primary_orbit(c, altitude, e, inc, raan, argp, nu)
    a = c.Re + altitude;
    p = a * (1 - e^2);
    radius = p / (1 + e * cos(nu));
    r_pqw = radius * [cos(nu); sin(nu); 0];
    v_pqw = sqrt(c.mu / p) * [-sin(nu); e + cos(nu); 0];

    R3_raan = [cos(raan), -sin(raan), 0; ...
               sin(raan), cos(raan), 0; 0, 0, 1];
    R1_inc = [1, 0, 0; 0, cos(inc), -sin(inc); ...
              0, sin(inc), cos(inc)];
    R3_argp = [cos(argp), -sin(argp), 0; ...
               sin(argp), cos(argp), 0; 0, 0, 1];
    Q = R3_raan * R1_inc * R3_argp;
    r = Q * r_pqw;
    v = Q * v_pqw;
    r_hat = r / norm(r);
    h_hat = cross(r, v) / norm(cross(r, v));
    t_hat = cross(h_hat, r_hat);
    R_local = [r_hat, t_hat, h_hat];
    X = [r; v];
end

function [distance, ok] = solve_miss_distance(target_pc, rel_vel, direction, ...
                                               C_sat, C_deb, hbr_m)
    pc_at_zero = calculatePoC([0; 0; 0], rel_vel, C_sat, C_deb, hbr_m);
    if pc_at_zero < target_pc
        distance = NaN;
        ok = false;
        return;
    end

    lower = 0;
    upper = 100;
    pc_at_upper = calculatePoC(upper * direction, rel_vel, ...
                               C_sat, C_deb, hbr_m);
    while pc_at_upper > target_pc && upper < 1e6
        upper = upper * 2;
        pc_at_upper = calculatePoC(upper * direction, rel_vel, ...
                                   C_sat, C_deb, hbr_m);
    end
    if pc_at_upper > target_pc
        distance = NaN;
        ok = false;
        return;
    end

    for k = 1:60
        middle = (lower + upper) / 2;
        pc_middle = calculatePoC(middle * direction, rel_vel, ...
                                 C_sat, C_deb, hbr_m);
        if pc_middle > target_pc
            lower = middle;
        else
            upper = middle;
        end
    end
    distance = (lower + upper) / 2;
    ok = isfinite(distance) && distance > 0;
end

function [ok, X0_sat, X0_deb] = backpropagate_to_epoch( ...
        X_cpa_sat, X_cpa_deb, t_cpa, c, propagation_tolerance, ...
        dynamics_pair)
    ok = false;
    X0_sat = [];
    X0_deb = [];
    options = odeset('RelTol', propagation_tolerance.rel_tol, ...
                     'AbsTol', propagation_tolerance.abs_tol, ...
                     'Events', @(t, X) earth_collision_event(t, X, c));
    warning_state = warning('off', 'MATLAB:ode113:IntegrationTolNotMet');
    cleanup = onCleanup(@() warning(warning_state));
    try
        sat_solution = ode113(dynamics_pair.target, ...
                              [0, -t_cpa], X_cpa_sat, options);
        deb_solution = ode113(dynamics_pair.debris, ...
                              [0, -t_cpa], X_cpa_deb, options);
        if abs(sat_solution.x(end) + t_cpa) > 1 || ...
                abs(deb_solution.x(end) + t_cpa) > 1
            return;
        end
        X0_sat = sat_solution.y(:, end);
        X0_deb = deb_solution.y(:, end);
        ok = all(isfinite([X0_sat; X0_deb]));
    catch ME
        if ~is_ode_failure(ME)
            rethrow(ME);
        end
    end
end

function v_rotated = rotate_about_axis(v, axis, angle_rad)
%ROTATE_ABOUT_AXIS Rodrigues rotation, used to build a crossing debris orbit.
% Rotating the velocity about the radial direction preserves |r|, |v|, and
% the flight-path angle, so the debris orbit has the same semi-major axis
% and eccentricity as the target and differs only in plane.
    axis = axis(:) / norm(axis);
    v = v(:);
    v_rotated = v * cos(angle_rad) + cross(axis, v) * sin(angle_rad) + ...
                axis * dot(axis, v) * (1 - cos(angle_rad));
end

function direction = perpendicular_direction(reference)
%PERPENDICULAR_DIRECTION Uniform unit vector orthogonal to reference.
% At TCA the miss vector is orthogonal to the relative velocity, so the miss
% direction must be sampled inside that plane rather than fixed to radial.
    reference = reference(:) / norm(reference);
    if abs(reference(1)) > 0.9
        seed_axis = [0; 1; 0];
    else
        seed_axis = [1; 0; 0];
    end
    basis_a = cross(reference, seed_axis);
    basis_a = basis_a / norm(basis_a);
    basis_b = cross(reference, basis_a);
    phase = 2 * pi * rand();
    direction = basis_a * cos(phase) + basis_b * sin(phase);
    direction = direction / norm(direction);
end

function value = uniform_value(range)
    value = range(1) + rand() * (range(2) - range(1));
end

function value = map_to_range(range, u)
%MAP_TO_RANGE The deterministic half of UNIFORM_VALUE, for a pre-drawn u.
    value = range(1) + u * (range(2) - range(1));
end

function ranges = proposal_sigma_for_family(config, family)
%PROPOSAL_SIGMA_FOR_FAMILY The per-family proposal covariance, contract v6.
%
% Fails loudly rather than falling back to the retired flat fields. A config
% that still carries only sigma_radial_range_m predates version 6, and
% silently substituting a default would reintroduce exactly the mismatch
% between the proposal and the tracked covariance that version 6 removes.
    if ~isfield(config, 'proposal_sigma_ranges')
        error('ACAM:MissingProposalSigmaRanges', ...
              ['Scenario config predates contract version 6: it has no ', ...
               'proposal_sigma_ranges. Set it per encounter family; see ', ...
               'SCENARIO_GENERATION_CONFIG.']);
    end
    if ~isfield(config.proposal_sigma_ranges, family)
        error('ACAM:MissingProposalSigmaFamily', ...
              'proposal_sigma_ranges has no entry for family "%s".', family);
    end
    ranges = config.proposal_sigma_ranges.(family);
end

function value = sample_log_uniform(lower, upper)
    value = exp(log(lower) + rand() * (log(upper) - log(lower)));
end

function period = orbital_period(X, c)
    energy = 0.5 * dot(X(4:6), X(4:6)) - c.mu / norm(X(1:3));
    semi_major_axis = -c.mu / (2 * energy);
    period = 2 * pi * sqrt(semi_major_axis^3 / c.mu);
end

function reason = validation_failure_reason(checks)
    fields = {'finite', 'covariance_positive_definite', ...
              'orbital_energy_valid', 'perigee_valid', ...
              'propagation_valid', 'tca_inside_interval', ...
              'tca_stationarity_valid', 'miss_distance_valid', ...
              'pc_band_valid', 'round_trip_position_valid'};
    reason = 'validation check failed';
    for k = 1:numel(fields)
        if ~checks.(fields{k})
            reason = fields{k};
            return;
        end
    end
end

function value = is_ode_failure(ME)
    value = startsWith(ME.identifier, 'MATLAB:ode') || ...
            contains(lower(ME.message), 'ode') || ...
            strcmp(ME.identifier, 'ACAM:TcaPropagationFailed');
end
