function contract = physical_property_strata(target_mass_kg, stratum_name)
%PHYSICAL_PROPERTY_STRATA Fixed per-object properties for causal truth tests.
%
% These are sensitivity strata, not a population model. Stage A varies only
% the debris area-to-mass ratio while holding Cd and Cr fixed, so a paired
% change can be attributed to differential drag/SRP rather than mixed draws.
%
% Sources:
% - NASA SmallSat Deorbit Systems gives 100 kg / 0.5 m^2 (A/m=0.005)
%   and commonly assumes Cd=2.2:
%   https://www.nasa.gov/smallsat-institute/sst-soa/deorbit-systems/
% - NASA SNAPSHOT debris estimates were mostly A/m=0.1--0.2 m^2/kg:
%   https://ntrs.nasa.gov/api/citations/20060028182/downloads/20060028182.pdf
% - Cr=1.3 is retained from the earlier diagnostic and lies inside the
%   physical absorption/reflection interval [1,2]; it is not calibrated.

    validateattributes(target_mass_kg, {'numeric'}, ...
        {'real', 'finite', 'scalar', 'positive'}, mfilename, ...
        'target_mass_kg');
    if nargin < 2 || isempty(stratum_name)
        stratum_name = 'matched';
    end
    stratum_name = validatestring(stratum_name, ...
        {'matched', 'differential_4x', 'differential_20x'});

    target_ratio = 0.005;
    debris_ratio = struct('matched', 0.005, ...
        'differential_4x', 0.02, 'differential_20x', 0.10).(stratum_name);
    cd = 2.2;
    cr = 1.3;
    debris_mass_kg = 50;

    contract = struct( ...
        'version', 1, ...
        'design', 'fixed_causal_strata_not_population_sampling', ...
        'stratum_name', stratum_name, ...
        'available_strata', {{'matched', 'differential_4x', ...
                              'differential_20x'}}, ...
        'target', properties(target_mass_kg, target_ratio, cd, cr), ...
        'debris', properties(debris_mass_kg, debris_ratio, cd, cr), ...
        'scope_note', ['Fixed sensitivity values for paired causal tests; ', ...
                       'not frequencies or realistic population ranges.']);
end

function value = properties(mass_kg, area_to_mass_m2pkg, cd, cr)
    value = struct( ...
        'mass_kg', mass_kg, ...
        'drag_area_m2', mass_kg * area_to_mass_m2pkg, ...
        'drag_coefficient', cd, ...
        'srp_area_m2', mass_kg * area_to_mass_m2pkg, ...
        'reflectivity_coefficient', cr, ...
        'area_to_mass_m2pkg', area_to_mass_m2pkg, ...
        'ballistic_coefficient_kgpm2', ...
            1 / (cd * area_to_mass_m2pkg));
end
