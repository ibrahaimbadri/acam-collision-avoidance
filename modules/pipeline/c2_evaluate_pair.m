function pair = c2_evaluate_pair(selected, contract, c)
%C2_EVALUATE_PAIR Replay one selected encounter under every property stratum.
%
% The requested encounter is verified identical across strata, so the only
% difference between arms is the physical-property treatment. Shared by the
% primary pilot runner and the v2 correction runner.

    pair = struct('seed', selected.seed, 'family', selected.family, ...
        'control_bin', selected.terminal_bin, 'status', 'not_run', ...
        'failure_reason', '', 'rows', struct([]), ...
        'partial_rows', struct([]), 'completed_strata', strings(0, 1), ...
        'band_status', struct([]));
    rows = {};
    band = {};
    matched_request = [];
    try
        for s = 1:numel(contract.strata)
            config = contract.scenario_config;
            config.force_encounter_family = selected.family;
            config.pc_band_index = selected.proposal_band;
            config.physical_property_stratum = contract.strata{s};
            config.pc_band_gate_mode = ...
                contract.pc_band_gate_mode_by_stratum{s};
            [scenario, metadata, attempt_log] = ...
                generate_synthetic_scenario(config, c, selected.seed);
            if isempty(scenario)
                stage = '';
                if ~isempty(attempt_log), stage = attempt_log(end).stage; end
                error('ACAM:C2ReplayGenerationFailed', ...
                    '%s replay failed at %s: %s', contract.strata{s}, ...
                    stage, metadata.failure_reason);
            end
            % Band outcome for every arm, whether or not the band held. In
            % diagnostic mode an excursion is a result, so it has to reach
            % the artifacts rather than only the generator's metadata.
            band{s} = struct('seed', selected.seed, ...
                'stratum', string(contract.strata{s}), ...
                'gate_mode', string(scenario.pc_band_gate_mode), ...
                'requested_band', scenario.requested_band_index, ...
                'realised_band', scenario.realised_band_index, ...
                'pc_band_valid', scenario.pc_band_valid, ...
                'proposal_pc', scenario.Pc_initial); %#ok<AGROW>
            pair.band_status = [band{:}]';
            request = c2_request_fingerprint(scenario);
            verify_request(selected.request, request, selected.seed);
            if isempty(matched_request)
                matched_request = request;
            else
                verify_request(matched_request, request, selected.seed);
            end
            c_local = c2_scenario_constants(c, scenario);
            [sequence, audit] = simulate_ekf_cdm_sequence( ...
                scenario, c_local, contract.lead_hours * 3600, ...
                contract.decision_seed_offset + double(selected.seed), ...
                contract.decision_tracking_config);
            if strcmp(contract.strata{s}, 'matched')
                terminal_cdm = selected.terminal_cdm;
            else
                terminal = generate_terminal_cdm_reference( ...
                    scenario, c_local, ...
                    contract.terminal_seed_offset + double(selected.seed), ...
                    contract.terminal_config);
                terminal_cdm = terminal.cdm;
            end
            stratum_rows = risk_rows(sequence, audit, terminal_cdm, ...
                scenario, selected, contract, contract.strata{s});
            rows = [rows; num2cell(stratum_rows)]; %#ok<AGROW>
        end
        pair.status = 'complete';
        pair.rows = [rows{:}]';
    catch ME
        pair.status = 'failed';
        pair.failure_reason = sprintf('%s: %s', ME.identifier, ME.message);
        % Retain whichever arm already completed. Discarding a finished
        % matched control because the treatment arm failed throws away
        % valid, expensive control data and leaves no record of what the
        % case looked like before the treatment was applied. The pair is
        % still 'failed' and still excluded from paired analysis; these
        % rows exist for audit and for single-arm reporting only.
        if ~isempty(rows)
            pair.partial_rows = [rows{:}]';
            pair.completed_strata = unique(string({pair.partial_rows.stratum}));
        end
    end
end

function rows = risk_rows(sequence, audit, terminal_cdm, scenario, ...
                          selected, contract, stratum)
    rows = repmat(risk_row_template(), numel(audit.messages), 1);
    terminal_pc = terminal_cdm.collision_probability;
    own_dangerous = terminal_pc >= contract.action_threshold_pc;
    for k = 1:numel(audit.messages)
        item = audit.messages{k};
        message_index = find(strcmp({sequence.messages.message_id}, ...
                                    item.message_id), 1);
        message = sequence.messages(message_index);
        decision_pc = message.collision_probability;
        decision_trigger = decision_pc >= contract.action_threshold_pc;
        error_eci = (message.target_state_eci_tca(1:3) - ...
            message.chaser_state_eci_tca(1:3)) - ...
            (scenario.X_cpa_sat(1:3) - scenario.X_cpa_deb(1:3));
        R = hill_to_eci(message.target_state_eci_tca);
        covariance = regularize_covariance( ...
            message.combined_position_covariance_rtn_m2);
        error_rtn = R' * error_eci;
        relative_nees = error_rtn' * (covariance \ error_rtn);
        tracking = item.tracking;
        signed_log_error = safe_log10(decision_pc, contract.log_pc_floor) - ...
                           safe_log10(terminal_pc, contract.log_pc_floor);
        rows(k) = struct( ...
            'seed', selected.seed, 'family', string(selected.family), ...
            'control_bin', selected.terminal_bin, ...
            'proposal_band', selected.proposal_band, ...
            'stratum', string(stratum), ...
            'lead_hours', item.nominal_lead_s / 3600, ...
            'decision_pc', decision_pc, 'terminal_pc', terminal_pc, ...
            'decision_trigger', decision_trigger, ...
            'control_label_dangerous', selected.terminal_bin == 3, ...
            'own_terminal_dangerous', own_dangerous, ...
            'correct_against_control', ...
                decision_trigger == (selected.terminal_bin == 3), ...
            'correct_against_own_terminal', ...
                decision_trigger == own_dangerous, ...
            'signed_log_error', signed_log_error, ...
            'absolute_log_error', abs(signed_log_error), ...
            'tca_relative_error_m', norm(error_eci), ...
            'tca_relative_nees', relative_nees, ...
            'tca_nees_within_95', ...
                relative_nees <= contract.chi_square_3d_95, ...
            'mean_nees_sat', tracking.mean_nees_sat, ...
            'mean_nees_deb', tracking.mean_nees_deb, ...
            'mean_nis_sat', tracking.mean_nis_sat, ...
            'mean_nis_deb', tracking.mean_nis_deb);
    end
end

function row = risk_row_template()
    row = struct('seed', NaN, 'family', "", 'control_bin', NaN, ...
        'proposal_band', NaN, 'stratum', "", 'lead_hours', NaN, ...
        'decision_pc', NaN, 'terminal_pc', NaN, ...
        'decision_trigger', false, 'control_label_dangerous', false, ...
        'own_terminal_dangerous', false, 'correct_against_control', false, ...
        'correct_against_own_terminal', false, 'signed_log_error', NaN, ...
        'absolute_log_error', NaN, 'tca_relative_error_m', NaN, ...
        'tca_relative_nees', NaN, 'tca_nees_within_95', false, ...
        'mean_nees_sat', NaN, 'mean_nees_deb', NaN, ...
        'mean_nis_sat', NaN, 'mean_nis_deb', NaN);
end

function verify_request(expected, actual, seed)
    numeric_names = {'target_pc', 'requested_tca_s', ...
        'requested_miss_distance_m', 'hbr_m', 'mass_kg'};
    ok = expected.seed == actual.seed && strcmp(expected.family, actual.family);
    for k = 1:numel(numeric_names)
        a = expected.(numeric_names{k});
        b = actual.(numeric_names{k});
        scale = max([1, abs(a), abs(b)]);
        ok = ok && abs(a - b) <= 1e-10 * scale;
    end
    if isnan(expected.crossing_angle_deg)
        ok = ok && isnan(actual.crossing_angle_deg);
    else
        ok = ok && abs(expected.crossing_angle_deg - ...
                       actual.crossing_angle_deg) <= 1e-10;
    end
    if ~ok
        error('ACAM:C2PairingViolation', ...
              'Seed %d did not reproduce the same requested encounter.', seed);
    end
end

function value = safe_log10(pc, floor_value)
    value = log10(max(pc, floor_value));
end

function P = regularize_covariance(P)
    P = (P + P') / 2;
    if any(~isfinite(P), 'all') || min(eig(P)) <= 0
        error('ACAM:C2InvalidCovariance', ...
              'C2 received a non-SPD position covariance.');
    end
end

function R_h2e = hill_to_eci(X)
    r_hat = X(1:3) / norm(X(1:3));
    h_hat = cross(X(1:3), X(4:6));
    h_hat = h_hat / norm(h_hat);
    t_hat = cross(h_hat, r_hat);
    R_h2e = [r_hat, t_hat, h_hat];
end
