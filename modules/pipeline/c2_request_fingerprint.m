function request = c2_request_fingerprint(scenario)
%C2_REQUEST_FINGERPRINT Requested encounter, before any treatment-dependent result.
%
% Identifies the encounter that was asked for, so the same request can be
% verified across strata. Contains nothing that the physical-property
% treatment is allowed to change.

    request = struct('seed', scenario.scenario_seed, ...
        'family', scenario.encounter_family, ...
        'target_pc', scenario.target_pc, ...
        'requested_tca_s', scenario.requested_tca_s, ...
        'requested_miss_distance_m', scenario.requested_miss_distance_m, ...
        'hbr_m', scenario.hbr_m, 'mass_kg', scenario.mass, ...
        'crossing_angle_deg', scenario.crossing_angle_deg);
end
