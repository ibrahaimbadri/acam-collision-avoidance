function [verdict, contributor, matched_pass] = ...
        c2_verdict(summary, cells, cell_counts, pairing_ok, contract)
%C2_VERDICT Frozen Stage C2 decision rule. Thresholds come from the contract.

    enough = pairing_ok && all(cell_counts(:) >= contract.minimum_common_per_cell) && ...
        all(cells.n_common >= contract.minimum_common_per_cell);
    contributor = false;
    matched_pass = false;
    if ~enough
        verdict = 'C2 INCONCLUSIVE: fewer than 10 common pairs in a required cell';
        return;
    end
    for lead = contract.lead_hours
        all_row = summary(summary.group == "all" & ...
                          summary.lead_hours == lead, :);
        family_rows = summary(summary.group ~= "all" & ...
                              summary.lead_hours == lead, :);
        contributor = contributor || ( ...
            all_row.median_abs_log_error_increase >= ...
                contract.minimum_median_abs_error_increase && ...
            all_row.fraction_worsened >= contract.minimum_fraction_worsened && ...
            all(family_rows.median_abs_log_error_increase > 0));
        lead_cells = cells(cells.lead_hours == lead, :);
        bin2 = lead_cells(lead_cells.control_bin == 2, :);
        bin3 = lead_cells(lead_cells.control_bin == 3, :);
        matched_detail_ok = all(bin2.matched_trigger_rate <= ...
                                contract.maximum_matched_far) && ...
                            all(bin3.matched_trigger_rate >= ...
                                contract.minimum_matched_recall);
        matched_error_ok = all_row.median_matched_abs_log_error <= ...
                           contract.maximum_matched_median_abs_log_error;
        matched_pass = matched_pass || (matched_detail_ok && matched_error_ok);
    end
    if contributor && matched_pass
        verdict = ['C2 POSITIVE: differential drag is a general risk-level ', ...
                   'contributor and matched boundary calibration passes'];
    elseif contributor
        verdict = ['C2 POSITIVE BUT NOT SOLE CAUSE: differential drag adds ', ...
                   'risk error while matched boundary calibration already fails'];
    else
        family_positive = false;
        for family = string(contract.families)
            part = summary(summary.group == family, :);
            family_positive = family_positive || any( ...
                part.median_abs_log_error_increase >= ...
                    contract.minimum_median_abs_error_increase & ...
                part.fraction_worsened >= contract.minimum_fraction_worsened);
        end
        if family_positive
            verdict = ['C2 FAMILY-CONDITIONAL: only one encounter family ', ...
                       'shows the predeclared harmful risk effect'];
        else
            verdict = ['C2 NEGATIVE: state shift is absorbed or co-moves ', ...
                       'with the terminal reference'];
        end
    end
end
