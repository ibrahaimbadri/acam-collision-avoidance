function decision = build_stage6b1_decision_context(message, tracking, ...
        filter, decision_epoch_utc, weather)
%BUILD_STAGE6B1_DECISION_CONTEXT Copy only operational Stage 6b1 inputs.

    assumptions = physical_property_strata( ...
        message.spacecraft_mass_kg, 'differential_4x');
    force = force_model_discrepancy_config();
    planning_scenario = struct( ...
        'target_physical', assumptions.target, ...
        'debris_physical', assumptions.debris, ...
        'force_environment', struct( ...
            'solar_pressure_npm2', force.solar_pressure_npm2, ...
            'astronomical_unit_m', force.astronomical_unit_m), ...
        'information_source', ...
            'frozen_stage6b1_sensitivity_assumptions');
    operational_tracking = struct( ...
        'state', tracking.state, 'covariance', tracking.covariance, ...
        'mean_nis12', tracking.diagnostics.mean_nis12, ...
        'measurement_available_fraction', ...
            mean(tracking.measurement_available));
    operational_weather = struct( ...
        'f107_average', weather.f107_average, ...
        'f107_daily', weather.f107_daily, ...
        'magnetic_index', weather.magnetic_index, ...
        'local_solar_time_h', weather.local_solar_time_h);
    operational_filter = sanitize_stage6b1_filter_config(filter);
    decision = struct('message', message, ...
        'tracking', operational_tracking, ...
        'planning_scenario', planning_scenario, ...
        'filter', operational_filter, ...
        'decision_epoch_utc', decision_epoch_utc, ...
        'weather', operational_weather);
    validate_stage6b1_decision_context(decision);
end
