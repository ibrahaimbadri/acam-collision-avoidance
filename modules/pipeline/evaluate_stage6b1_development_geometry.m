function record = evaluate_stage6b1_development_geometry( ...
        contexts, model, c, geometry_index)
%EVALUATE_STAGE6B1_DEVELOPMENT_GEOMETRY Compare both locked policy paths.

    persistent warmed
    if isempty(warmed)
        warmed = false;
    end
    try
        rows = cell(numel(contexts), 1);
        for arm_index = 1:numel(contexts)
            context = contexts(arm_index);
            c_local = c;
            c_local.HBR = context.decision.message.hbr_m;
            c_local.scenario_mass = ...
                context.decision.message.spacecraft_mass_kg;
            if context.target.triggered && ~warmed
                run_surrogate(context, model, c_local);
                run_numerical(context, c_local);
                warmed = true;
            end
            if mod(geometry_index, 2) == 1
                surrogate_timer = tic;
                [policy, features] = run_surrogate(context, model, c_local);
                surrogate_runtime_s = toc(surrogate_timer);
                numerical_timer = tic;
                numerical = run_numerical(context, c_local);
                numerical_runtime_s = toc(numerical_timer);
            else
                numerical_timer = tic;
                numerical = run_numerical(context, c_local);
                numerical_runtime_s = toc(numerical_timer);
                surrogate_timer = tic;
                [policy, features] = run_surrogate(context, model, c_local);
                surrogate_runtime_s = toc(surrogate_timer);
            end
            policy_truth = truth_audit(context, policy, c_local);
            numerical_truth = truth_audit(context, numerical, c_local);
            feature_error = norm(features(:) - context.target.features(:), Inf);
            rows{arm_index} = result_row(context, policy, numerical, ...
                policy_truth, numerical_truth, surrogate_runtime_s, ...
                numerical_runtime_s, feature_error, c_local);
        end
        record = struct('status', "complete", ...
            'geometry_id', string(contexts(1).geometry_id), ...
            'rows', vertcat(rows{:}), 'error_id', "", 'error_message', "");
    catch ME
        record = struct('status', "failed", ...
            'geometry_id', string(contexts(1).geometry_id), ...
            'rows', struct([]), 'error_id', string(ME.identifier), ...
            'error_message', string(ME.message));
    end
end

function [result, features] = run_surrogate(context, model, c)
    decision = context.decision;
    [evaluator, ~] = build_joint_drag_robust_evaluator( ...
        decision.message, decision.tracking, decision.planning_scenario, ...
        decision.filter, c, decision.decision_epoch_utc);
    [zero_pc, zero_details] = evaluator(zeros(3, 1), 0);
    assert(zero_details.completed && isfinite(zero_pc), ...
        'Stage 6b1 surrogate zero-burn evaluation failed.');
    features = decision_features(decision, zero_pc);
    proposer = @(values) propose_stage6b1_action(model, values);
    verifier = @(dV) evaluate_vector(evaluator, dV);
    fallback = @(~) full_optimizer(decision, c, evaluator, zero_pc);
    config = struct('reserve_factor', 1.10, ...
        'robust_zero_burn_pc', zero_pc);
    result = run_stage6b1_verified_policy(decision, features, proposer, ...
        verifier, fallback, c, config);
end

function result = run_numerical(context, c)
    decision = context.decision;
    [evaluator, ~] = build_joint_drag_robust_evaluator( ...
        decision.message, decision.tracking, decision.planning_scenario, ...
        decision.filter, c, decision.decision_epoch_utc);
    [zero_pc, zero_details] = evaluator(zeros(3, 1), 0);
    assert(zero_details.completed && isfinite(zero_pc), ...
        'Stage 6b1 numerical zero-burn evaluation failed.');
    trigger_pc = max(decision.message.collision_probability, zero_pc);
    result = struct('status', "stay", 'triggered', ...
        trigger_pc > c.pc_maneuver_threshold, 'trigger_pc', trigger_pc, ...
        'action_source', "stay", 'dV_hill', zeros(3, 1), ...
        'final_pc', zero_pc, 'optimizer_calls', 0, 'verifier_calls', 0);
    if ~result.triggered
        return;
    end
    result.optimizer_calls = 1;
    [dV, info] = full_optimizer(decision, c, evaluator, zero_pc);
    if ~strcmp(string(info.status), "success") || ...
            numel(dV) ~= 3 || any(~isfinite(dV)) || norm(dV) <= 0
        result.status = "no_solution";
        result.action_source = "none";
        result.final_pc = Inf;
        return;
    end
    try
        reserved = apply_maneuver_reserve(dV, 1.10, c.max_maneuver_mps);
        result.verifier_calls = 1;
        [pc, details] = evaluate_vector(evaluator, reserved);
    catch
        result.status = "no_solution";
        result.action_source = "none";
        result.final_pc = Inf;
        return;
    end
    if details.completed && isfinite(pc) && pc <= c.pc_target_remediation
        result.status = "numerical_verified";
        result.action_source = "numerical";
        result.dV_hill = reserved;
        result.final_pc = pc;
    else
        result.status = "no_solution";
        result.action_source = "none";
        result.final_pc = Inf;
    end
end

function [dV, info] = full_optimizer(decision, c, evaluator, zero_pc)
    search = maneuver_search_config('six_axis');
    search.candidate_evaluator = evaluator;
    search.candidate_evaluator_fidelity = ...
        'complete_post_burn_tca_joint_covariance';
    search.decision_pc_override = max( ...
        decision.message.collision_probability, zero_pc);
    search.decision_trigger_source = ...
        'max(published CDM Pc, complete robust zero-burn Pc)';
    [dV, should_maneuver, ~, info] = ...
        compute_cdm_oracle(decision.message, c, search);
    if ~should_maneuver
        dV = nan(3, 1);
    end
end

function features = decision_features(decision, zero_pc)
    tracking = struct('state', decision.tracking.state, ...
        'covariance', decision.tracking.covariance, ...
        'diagnostics', struct('mean_nis12', ...
            decision.tracking.mean_nis12), ...
        'measurement_available', ...
            decision.tracking.measurement_available_fraction);
    features = build_truth_audited_features(decision.message, tracking, ...
        zero_pc, decision.weather);
end

function [pc, details] = evaluate_vector(evaluator, dV)
    magnitude = norm(dV);
    if magnitude == 0
        direction = zeros(3, 1);
    else
        direction = dV(:) / magnitude;
    end
    [pc, details] = evaluator(direction, magnitude);
end

function audit = truth_audit(context, policy, c)
    if policy.status == "no_solution"
        audit = struct('completed', false, 'safe', false, 'pc', Inf, ...
            'status', "no_solution");
        return;
    end
    [safe, ~, pc, details] = evaluate_joint_drag_truth_candidate( ...
        context.audit, policy.dV_hill, c);
    audit = struct('completed', details.completed && isfinite(pc), ...
        'safe', safe && details.completed && isfinite(pc), 'pc', pc, ...
        'status', string(details.status));
end

function row = result_row(context, policy, numerical, policy_truth, ...
        numerical_truth, policy_runtime_s, numerical_runtime_s, ...
        feature_error, c)
    policy_unsafe = ~policy_truth.completed || ~policy_truth.safe || ...
        policy.status == "no_solution";
    numerical_unsafe = ~numerical_truth.completed || ...
        ~numerical_truth.safe || numerical.status == "no_solution";
    row = struct('geometry_id', string(context.geometry_id), ...
        'seed', context.seed, 'family', string(context.family), ...
        'risk_band', context.risk_band, 'split', string(context.split), ...
        'arm', string(context.arm), 'triggered', context.target.triggered, ...
        'target_status', context.target.status, ...
        'target_available', context.target.status == "success", ...
        'feature_identity_error', feature_error, ...
        'trigger_invariant_pass', policy.triggered == ...
            context.target.triggered && numerical.triggered == ...
            context.target.triggered, ...
        'policy_status', policy.status, ...
        'policy_action_source', policy.action_source, ...
        'policy_proposal_status', policy.proposal_status, ...
        'policy_raw_proposal_verified', policy.status == "ml_verified", ...
        'policy_fallback_used', policy.fallback_calls > 0, ...
        'policy_no_solution', policy.status == "no_solution", ...
        'policy_planning_pc', policy.final_pc, ...
        'policy_dv_radial_mps', policy.dV_hill(1), ...
        'policy_dv_along_track_mps', policy.dV_hill(2), ...
        'policy_dv_cross_track_mps', policy.dV_hill(3), ...
        'policy_dv_magnitude_mps', norm(policy.dV_hill), ...
        'policy_truth_completed', policy_truth.completed, ...
        'policy_truth_safe', policy_truth.safe, ...
        'policy_truth_pc', policy_truth.pc, ...
        'policy_unsafe', policy_unsafe, ...
        'numerical_status', numerical.status, ...
        'numerical_no_solution', numerical.status == "no_solution", ...
        'numerical_planning_pc', numerical.final_pc, ...
        'numerical_dv_radial_mps', numerical.dV_hill(1), ...
        'numerical_dv_along_track_mps', numerical.dV_hill(2), ...
        'numerical_dv_cross_track_mps', numerical.dV_hill(3), ...
        'numerical_dv_magnitude_mps', norm(numerical.dV_hill), ...
        'numerical_truth_completed', numerical_truth.completed, ...
        'numerical_truth_safe', numerical_truth.safe, ...
        'numerical_truth_pc', numerical_truth.pc, ...
        'numerical_unsafe', numerical_unsafe, ...
        'paired_excess_failure', policy_unsafe && ~numerical_unsafe, ...
        'policy_runtime_s', policy_runtime_s, ...
        'numerical_runtime_s', numerical_runtime_s, ...
        'runtime_ratio', policy_runtime_s / numerical_runtime_s, ...
        'action_limit_pass', norm(policy.dV_hill) <= ...
            c.max_maneuver_mps * (1 + 1e-12) && ...
            norm(numerical.dV_hill) <= ...
            c.max_maneuver_mps * (1 + 1e-12));
end
