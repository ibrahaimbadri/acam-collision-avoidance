function [rows, contexts] = generate_truth_audited_geometry(item, contract, c)
%GENERATE_TRUTH_AUDITED_GEOMETRY Build both frozen truth-arm rows.

    config = contract.scenario_config;
    config.force_encounter_family = item.family;
    config.pc_band_index = item.band;
    base = generate_synthetic_scenario(config, c, item.seed);
    assert(~isempty(base), 'Stage 6a geometry generation failed.');
    c_local = c2_scenario_constants(c, base);
    filter = stage5h_drag_filter_config(contract.fixed_candidate);
    row_cells = cell(numel(contract.arms), 1);
    context_cells = cell(numel(contract.arms), 1);
    for arm_index = 1:numel(contract.arms)
        arm = contract.arms(arm_index);
        scenario = apply_arm(base, arm, item.seed, contract);
        segment = decision_segment(scenario, c_local, contract.lead_s, ...
            filter.max_tracking_duration_s);
        [tracking, ~] = run_joint_drag_tracking(segment, c_local, filter, ...
            contract.measurement_seed_offset + item.seed, []);
        event_id = sprintf('stage_6a-%d-%s', item.seed, arm.name);
        platform = struct('event_id', event_id, ...
            'spacecraft_mass_kg', scenario.mass, 'hbr_m', scenario.hbr_m);
        estimate = struct('state', tracking.state, ...
            'covariance', tracking.covariance);
        [message, diagnostics, tca] = generate_joint_drag_cdm( ...
            estimate, platform, c_local, contract.lead_s, filter, event_id);
        [row_cells{arm_index}, context_cells{arm_index}] = evaluate_arm( ...
            item, arm, scenario, segment, tracking, message, diagnostics, ...
            tca, filter, c_local, contract);
    end
    rows = vertcat(row_cells{:});
    contexts = vertcat(context_cells{:});
end

function [row, context] = evaluate_arm(item, arm, scenario, segment, ...
        tracking, message, diagnostics, tca, filter, c, contract)
    decision_epoch = segment.truth_epoch_utc + ...
        seconds(tracking.tracking_duration_s);
    [planning_evaluator, envelope] = build_joint_drag_robust_evaluator( ...
        message, tracking, scenario, filter, c, decision_epoch);
    [robust_zero_pc, ~] = ...
        planning_evaluator(zeros(3, 1), 0);
    trigger_pc = max(message.collision_probability, robust_zero_pc);
    triggered = trigger_pc > c.pc_maneuver_threshold;
    dual_only = message.collision_probability <= c.pc_maneuver_threshold && ...
        triggered;
    search = maneuver_search_config();
    search.candidate_evaluator = planning_evaluator;
    search.candidate_evaluator_fidelity = envelope.fidelity;
    search.decision_pc_override = trigger_pc;
    search.decision_trigger_source = ...
        'max(published CDM Pc, robust zero-burn worst Pc)';
    [optimizer_dv, oracle_maneuver, ~, oracle_info] = ...
        compute_cdm_oracle(message, c, search);
    optimizer_magnitude = norm(optimizer_dv);
    reserved_dv = apply_maneuver_reserve(optimizer_dv, ...
        contract.robust_dv_reserve_factor, c.max_maneuver_mps);
    [reserved_planning_pc, reserved_planning_details] = ...
        evaluate_hill(planning_evaluator, reserved_dv);
    fixed_dv = zeros(3, 1);
    if triggered, fixed_dv(2) = 0.05; end
    [fixed_planning_pc, fixed_planning_details] = ...
        evaluate_hill(planning_evaluator, fixed_dv);

    withheld = truth_replay_scenario(scenario, segment, tracking, ...
        message, tca);
    [zero_safe, ~, zero_truth_pc, zero_truth_details] = evaluate_maneuver( ...
        withheld, zeros(3, 1), c, 0, true);
    assert(zero_truth_details.completed, 'Truth zero-burn context failed.');
    truth_context = zero_truth_details.evaluation_context;
    R_burn = hill_to_eci(message.target_state_eci_at_message);
    [reserved_truth_safe, ~, reserved_truth_pc, reserved_truth_details] = ...
        evaluate_maneuver(withheld, R_burn * reserved_dv, ...
        c, 0, true, truth_context);
    [fixed_truth_safe, ~, fixed_truth_pc, fixed_truth_details] = ...
        evaluate_maneuver(withheld, R_burn * fixed_dv, ...
        c, 0, true, truth_context);

    direction_index = 0;
    direction_label = "stay";
    label_dv = zeros(3, 1);
    label_status = "stay";
    label_truth_pc = zero_truth_pc;
    label_truth_safe = zero_safe;
    label_completed = zero_truth_details.completed;
    label_audit_evaluations = 0;
    interval_pass = ~triggered;
    direction_pass = ~triggered;
    if triggered && oracle_maneuver && optimizer_magnitude > 0
        preferred_direction = optimizer_dv / optimizer_magnitude;
        alignments = search.direction_vectors_hill' * preferred_direction;
        [alignment, direction_index] = max(alignments);
        assert(alignment > 1 - 1e-10, ...
            'Optimizer returned a non-axis direction.');
        direction_label = string(search.direction_labels{direction_index});
        audit_config = struct('magnitude_step_mps', ...
            contract.magnitude_step_mps, 'refinement_iterations', ...
            contract.refinement_iterations);
        [label_dv, audit] = find_bounded_truth_audited_maneuver( ...
            withheld, R_burn, preferred_direction, optimizer_magnitude, ...
            norm(reserved_dv), c, truth_context, audit_config);
        label_status = string(audit.status);
        label_audit_evaluations = audit.evaluations;
        if audit.verified_safe
            [label_truth_safe, ~, label_truth_pc, label_details] = ...
                evaluate_maneuver(withheld, R_burn * label_dv, ...
                c, 0, true, truth_context);
            label_completed = label_details.completed;
            label_magnitude = norm(label_dv);
            interval_pass = label_magnitude + 1e-12 >= ...
                optimizer_magnitude && label_magnitude <= ...
                norm(reserved_dv) + 1e-12;
            direction_pass = dot(label_dv / label_magnitude, ...
                preferred_direction) > 1 - 1e-10;
        else
            label_truth_safe = false;
            label_truth_pc = Inf;
            label_completed = audit.completed;
        end
    elseif triggered
        label_dv(:) = NaN;
        label_status = "optimizer_incomplete";
        label_truth_pc = Inf;
        label_truth_safe = false;
        label_completed = false;
        interval_pass = false;
        direction_pass = false;
    end
    label_magnitude = norm(label_dv);
    label_contract_pass = label_completed && label_truth_safe && ...
        interval_pass && direction_pass;

    lla = eci2lla(tracking.state(1:3)', datevec(decision_epoch));
    weather = space_weather_at_utc( ...
        scenario.truth_model.space_weather_profile, decision_epoch, lla(2));
    features = build_truth_audited_features( ...
        message, tracking, robust_zero_pc, weather);
    [feature_names, ~, feature_version] = truth_audited_feature_schema();
    combined_norm = norm(message.combined_position_covariance_rtn_m2, 'fro');
    relative_identity_error = diagnostics.relative_covariance_identity_error / ...
        max(1, combined_norm);
    covariance_pass = covariance_ok(tracking.covariance) && ...
        covariance_ok(tca.covariance) && ...
        diagnostics.cross_covariance_position_fro > 0 && ...
        relative_identity_error <= contract.relative_identity_tolerance;
    trigger_invariant = oracle_maneuver == triggered;
    reserved_planning_remediated = ~triggered || ...
        (reserved_planning_details.completed && ...
        reserved_planning_pc <= c.pc_target_remediation);

    row = struct('geometry_id', item.geometry_id, 'seed', item.seed, ...
        'family', string(item.family), 'band', item.band, ...
        'split', string(item.split), 'arm', string(arm.name), ...
        'srp_enabled_truth_diagnostic_only', arm.srp_enabled, ...
        'triggered', triggered, 'dual_only_trigger', dual_only, ...
        'decision_pc', message.collision_probability, ...
        'robust_zero_burn_pc', robust_zero_pc, 'trigger_pc', trigger_pc, ...
        'trigger_invariant_pass', trigger_invariant, ...
        'optimizer_status', string(oracle_info.status), ...
        'optimizer_magnitude_mps', optimizer_magnitude, ...
        'optimizer_direction_index', direction_index, ...
        'optimizer_direction', direction_label, ...
        'optimizer_dv_radial_mps', optimizer_dv(1), ...
        'optimizer_dv_along_track_mps', optimizer_dv(2), ...
        'optimizer_dv_cross_track_mps', optimizer_dv(3), ...
        'reserved_magnitude_mps', norm(reserved_dv), ...
        'reserved_planning_pc', reserved_planning_pc, ...
        'reserved_planning_remediated', reserved_planning_remediated, ...
        'reserved_truth_pc', reserved_truth_pc, ...
        'reserved_truth_safe', reserved_truth_safe && ...
            reserved_truth_details.completed, ...
        'fixed_magnitude_mps', norm(fixed_dv), ...
        'fixed_planning_pc', fixed_planning_pc, ...
        'fixed_planning_complete', fixed_planning_details.completed, ...
        'fixed_truth_pc', fixed_truth_pc, ...
        'fixed_truth_safe', fixed_truth_safe && fixed_truth_details.completed, ...
        'label_status', label_status, 'label_completed', label_completed, ...
        'label_truth_pc', label_truth_pc, ...
        'label_truth_safe', label_truth_safe, ...
        'label_dv_radial_mps', label_dv(1), ...
        'label_dv_along_track_mps', label_dv(2), ...
        'label_dv_cross_track_mps', label_dv(3), ...
        'label_dv_magnitude_mps', label_magnitude, ...
        'label_direction_index', direction_index, ...
        'label_direction', direction_label, ...
        'label_interval_pass', interval_pass, ...
        'label_direction_pass', direction_pass, ...
        'label_contract_pass', label_contract_pass, ...
        'truth_audit_evaluations', label_audit_evaluations, ...
        'zero_burn_truth_pc_diagnostic_only', zero_truth_pc, ...
        'zero_burn_truth_safe_diagnostic_only', zero_safe, ...
        'covariance_invariants_pass', covariance_pass, ...
        'relative_covariance_identity_error_relative', ...
            relative_identity_error, ...
        'cross_covariance_position_fro', ...
            diagnostics.cross_covariance_position_fro, ...
        'feature_schema_version', feature_version, ...
        'model_feature_count', numel(features), ...
        'model_features_finite', all(isfinite(features)), ...
        'tracking_mean_nis12_operational', tracking.diagnostics.mean_nis12, ...
        'tracking_mean_nees12_truth_diagnostic_only', ...
            tracking.diagnostics.mean_nees12, ...
        'target_ballistic_coefficient_truth_diagnostic_only', ...
            scenario.target_physical.ballistic_coefficient_kgpm2, ...
        'debris_ballistic_coefficient_truth_diagnostic_only', ...
            scenario.debris_physical.ballistic_coefficient_kgpm2);
    for k = 1:numel(feature_names)
        row.(['feature_', feature_names{k}]) = features(k);
    end

    planning_scenario = struct('target_physical', ...
        scenario.target_physical, 'debris_physical', ...
        scenario.debris_physical, 'truth_model', scenario.truth_model);
    context = struct('geometry_id', item.geometry_id, ...
        'seed', item.seed, 'family', string(item.family), ...
        'band', item.band, 'split', string(item.split), ...
        'arm', string(arm.name), 'features', features(:)', ...
        'message', message, ...
        'tracking', struct('state', tracking.state, ...
            'covariance', tracking.covariance), ...
        'planning_scenario', planning_scenario, 'filter', filter, ...
        'decision_epoch_utc', decision_epoch, 'withheld_truth', withheld, ...
        'truth_reuse_context', truth_context, 'R_burn', R_burn, ...
        'optimizer_dv_hill', optimizer_dv, ...
        'reserved_dv_hill', reserved_dv, 'fixed_dv_hill', fixed_dv, ...
        'label_dv_hill', label_dv);
end

function scenario = apply_arm(base, arm, seed, contract)
    scenario = base;
    physical = physical_property_strata(base.mass, contract.physical_stratum);
    scenario.target_physical = physical.target;
    scenario.debris_physical = physical.debris;
    scenario.physical_property_stratum = contract.physical_stratum;
    model = base.truth_model;
    model.version = max(model.version, 3);
    model.mode = arm.truth_mode;
    model.include_nrlmsise = true;
    model.include_srp = arm.srp_enabled;
    spec = struct('marginal_sigma_log', contract.marginal_sigma_log, ...
        'object_correlation', contract.object_correlation, ...
        'correlation_time_s', contract.correlation_time_s, ...
        'bias_log', contract.bias_log);
    model.density_residual_profile = sample_density_residual_profile( ...
        base.truth_tca_epoch_utc, contract.density_residual_seed_offset + ...
        seed, spec);
    scenario.truth_model = model;
    scenario.truth_model_mode = model.mode;
end

function segment = decision_segment(scenario, c, lead_s, tracking_s)
    duration = lead_s + tracking_s;
    context = scenario;
    context.truth_epoch_utc = scenario.truth_tca_epoch_utc;
    dynamics = truth_dynamics_pair(context, c, -duration);
    tolerance = truth_propagation_tolerance(context, ...
        struct('rel_tol', 1e-8, 'abs_tol', 1e-10));
    options = odeset('RelTol', tolerance.rel_tol, ...
        'AbsTol', tolerance.abs_tol);
    sat = ode113(dynamics.target, [0, -duration], ...
        scenario.X_cpa_sat, options);
    deb = ode113(dynamics.debris, [0, -duration], ...
        scenario.X_cpa_deb, options);
    segment = scenario;
    segment.X0_sat = sat.y(:, end);
    segment.X0_deb = deb.y(:, end);
    segment.t_to_cpa = duration;
    segment.truth_epoch_utc = scenario.truth_tca_epoch_utc - ...
        seconds(duration);
end

function withheld = truth_replay_scenario(source, segment, tracking, ...
        message, tca)
    combined = tca.combined_position_covariance_eci;
    withheld = struct( ...
        'X0_sat', tracking.diagnostics.truth_target_final(:), ...
        'X0_deb', tracking.diagnostics.truth_debris_final(:), ...
        'X_cpa_sat', source.X_cpa_sat, 'X_cpa_deb', source.X_cpa_deb, ...
        'rel_pos', source.X_cpa_sat(1:3) - source.X_cpa_deb(1:3), ...
        'rel_vel', source.X_cpa_sat(4:6) - source.X_cpa_deb(4:6), ...
        't_to_cpa', message.time_to_tca_s, ...
        'C_sat', combined / 2, 'C_deb', combined / 2, ...
        'hbr_m', message.hbr_m, 'HBR', message.hbr_m, ...
        'mass', message.spacecraft_mass_kg, ...
        'truth_epoch_utc', segment.truth_epoch_utc + ...
            seconds(tracking.tracking_duration_s), ...
        'truth_model', source.truth_model, ...
        'truth_model_mode', source.truth_model_mode, ...
        'target_physical', source.target_physical, ...
        'debris_physical', source.debris_physical, ...
        'physical_property_stratum', source.physical_property_stratum);
end

function [pc, details] = evaluate_hill(evaluator, dV_hill)
    magnitude = norm(dV_hill);
    if magnitude == 0
        direction = zeros(3, 1);
    else
        direction = dV_hill(:) / magnitude;
    end
    [pc, details] = evaluator(direction, magnitude);
end

function ok = covariance_ok(P)
    [~, status] = chol((P + P') / 2);
    ok = status == 0 && all(isfinite(P), 'all');
end

function R = hill_to_eci(X)
    X = X(:);
    radial = X(1:3) / norm(X(1:3));
    normal = cross(X(1:3), X(4:6));
    normal = normal / norm(normal);
    R = [radial, cross(normal, radial), normal];
end
