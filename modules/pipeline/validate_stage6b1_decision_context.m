function validate_stage6b1_decision_context(context)
%VALIDATE_STAGE6B1_DECISION_CONTEXT Enforce the operational information set.

    required = {'message', 'tracking', 'planning_scenario', 'filter', ...
        'decision_epoch_utc', 'weather'};
    if ~isstruct(context) || ~isequal(sort(fieldnames(context)), ...
            sort(required(:)))
        error('ACAM:Stage6b1InformationBoundary', ...
            'Decision context fields differ from the Stage 6b1 allow-list.');
    end
    reject_forbidden(context, 'decision');

    tracking_fields = {'state', 'covariance', 'mean_nis12', ...
        'measurement_available_fraction'};
    if ~isequal(sort(fieldnames(context.tracking)), ...
            sort(tracking_fields(:)))
        error('ACAM:Stage6b1InformationBoundary', ...
            'Tracking fields differ from the Stage 6b1 allow-list.');
    end
    validateattributes(context.tracking.state, {'numeric'}, ...
        {'real', 'finite', 'vector', 'numel', 16}, mfilename, ...
        'tracking.state');
    validateattributes(context.tracking.covariance, {'numeric'}, ...
        {'real', 'finite', 'size', [16, 16]}, mfilename, ...
        'tracking.covariance');
    validateattributes(context.tracking.mean_nis12, {'numeric'}, ...
        {'real', 'finite', 'scalar', 'nonnegative'}, mfilename, ...
        'tracking.mean_nis12');
    validateattributes(context.tracking.measurement_available_fraction, ...
        {'numeric'}, {'real', 'finite', 'scalar', '>=', 0, '<=', 1}, ...
        mfilename, 'tracking.measurement_available_fraction');

    planning_fields = {'target_physical', 'debris_physical', ...
        'force_environment', 'information_source'};
    if ~isequal(sort(fieldnames(context.planning_scenario)), ...
            sort(planning_fields(:))) || ...
            ~strcmp(context.planning_scenario.information_source, ...
                'frozen_stage6b1_sensitivity_assumptions')
        error('ACAM:Stage6b1InformationBoundary', ...
            'Planning sensitivity assumptions are not Stage 6b1 allow-listed.');
    end
    weather_fields = {'f107_average', 'f107_daily', ...
        'magnetic_index', 'local_solar_time_h'};
    if ~isequal(sort(fieldnames(context.weather)), sort(weather_fields(:)))
        error('ACAM:Stage6b1InformationBoundary', ...
            'Weather fields differ from the Stage 6b1 allow-list.');
    end
    assert(isdatetime(context.decision_epoch_utc) && ...
        isscalar(context.decision_epoch_utc), ...
        'Decision epoch must be one datetime value.');
end

function reject_forbidden(value, path)
    if isa(value, 'function_handle')
        error('ACAM:Stage6b1InformationBoundary', ...
            'Function handle found inside decision context at %s.', path);
    end
    if isstruct(value)
        names = fieldnames(value);
        forbidden = {'truth', 'withheld', 'oracle', 'label', 'future'};
        for k = 1:numel(names)
            lowered = lower(names{k});
            if any(cellfun(@(token) contains(lowered, token), forbidden))
                error('ACAM:Stage6b1InformationBoundary', ...
                    'Forbidden decision-context field %s.%s.', path, names{k});
            end
            for item = 1:numel(value)
                reject_forbidden(value(item).(names{k}), ...
                    sprintf('%s.%s', path, names{k}));
            end
        end
    elseif iscell(value)
        for k = 1:numel(value)
            reject_forbidden(value{k}, sprintf('%s{%d}', path, k));
        end
    end
end
