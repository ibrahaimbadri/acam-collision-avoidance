function results = c2_summarize(evaluation_records, selected, contract)
%C2_SUMMARIZE Frozen Stage C2 paired analysis over completed replay records.
%
% Single implementation of the Stage C2 statistics, shared by the primary
% pilot runner and the v2 correction runner so that both apply exactly the
% same criteria to their records.

    status_rows = cellfun(@replay_status_row, evaluation_records, ...
                          'UniformOutput', false);
    replay_status = struct2table([status_rows{:}]');
    complete = evaluation_records(cellfun(@(x) ...
        ~isempty(x) && strcmp(x.status, 'complete'), evaluation_records));
    % Rows from an arm that completed inside a pair that later failed. These
    % are excluded from every paired analysis below and exist only so the
    % completed control is auditable rather than discarded.
    partial_rows = {};
    for i = 1:numel(evaluation_records)
        record = evaluation_records{i};
        if isempty(record) || strcmp(record.status, 'complete') || ...
                ~isfield(record, 'partial_rows') || isempty(record.partial_rows)
            continue;
        end
        partial_rows = [partial_rows; num2cell(record.partial_rows)]; %#ok<AGROW>
    end
    if isempty(partial_rows)
        partial_table = table();
    else
        partial_table = struct2table([partial_rows{:}]');
    end
    rows = {};
    for i = 1:numel(complete)
        rows = [rows; num2cell(complete{i}.rows)]; %#ok<AGROW>
    end
    if isempty(rows)
        results = c2_inconclusive_results(contract, zeros(2), NaN, '');
        results.partial_arm_table = partial_table;
        return;
    end
    detail = struct2table([rows{:}]');
    [paired, pairing_ok] = paired_rows(detail, contract);
    cell_counts = zeros(2);
    for f = 1:2
        for b = 1:2
            cell_counts(f, b) = nnz([selected.terminal_bin] == ...
                contract.target_bins(b) & strcmp({selected.family}, ...
                                                 contract.families{f}));
        end
    end
    summary = paired_summary(paired, contract);
    cells = cell_summary(detail, paired, contract);
    [verdict, contributor, matched_pass] = ...
        c2_verdict(summary, cells, cell_counts, pairing_ok, contract);
    results = struct('contract', contract, 'verdict', verdict, ...
        'risk_level_contributor', contributor, ...
        'matched_boundary_gates_pass', matched_pass, ...
        'cell_counts', cell_counts, 'detail_table', detail, ...
        'paired_table', paired, 'summary_table', summary, ...
        'cell_table', cells, 'selected', selected, ...
        'replay_status_table', replay_status, ...
        'partial_arm_table', partial_table, ...
        'complete_pairs', numel(complete), ...
        'failed_pairs', numel(evaluation_records) - numel(complete));
end

function [paired, pairing_ok] = paired_rows(detail, contract)
    keys = unique(detail(:, {'seed', 'lead_hours'}), 'rows');
    rows = cell(height(keys), 1);
    row_index = 0;
    pairing_ok = true;
    for i = 1:height(keys)
        part = detail(detail.seed == keys.seed(i) & ...
                      detail.lead_hours == keys.lead_hours(i), :);
        matched = part(part.stratum == "matched", :);
        changed = part(part.stratum == "differential_4x", :);
        if height(matched) ~= 1 || height(changed) ~= 1
            pairing_ok = false;
            continue;
        end
        decision_move = safe_log10(changed.decision_pc, contract.log_pc_floor) - ...
                        safe_log10(matched.decision_pc, contract.log_pc_floor);
        terminal_move = safe_log10(changed.terminal_pc, contract.log_pc_floor) - ...
                        safe_log10(matched.terminal_pc, contract.log_pc_floor);
        row_index = row_index + 1;
        rows{row_index} = struct( ...
            'seed', matched.seed, 'family', matched.family, ...
            'control_bin', matched.control_bin, ...
            'lead_hours', matched.lead_hours, ...
            'matched_decision_pc', matched.decision_pc, ...
            'changed_decision_pc', changed.decision_pc, ...
            'matched_terminal_pc', matched.terminal_pc, ...
            'changed_terminal_pc', changed.terminal_pc, ...
            'matched_absolute_log_error', matched.absolute_log_error, ...
            'changed_absolute_log_error', changed.absolute_log_error, ...
            'absolute_log_error_change', changed.absolute_log_error - ...
                                         matched.absolute_log_error, ...
            'worsened', changed.absolute_log_error > matched.absolute_log_error, ...
            'decision_log_movement', decision_move, ...
            'terminal_log_movement', terminal_move, ...
            'residual_log_divergence', decision_move - terminal_move, ...
            'absolute_residual_log_divergence', ...
                abs(decision_move - terminal_move), ...
            'matched_trigger', matched.decision_trigger, ...
            'changed_trigger', changed.decision_trigger, ...
            'trigger_0_to_1', ~matched.decision_trigger & changed.decision_trigger, ...
            'trigger_1_to_0', matched.decision_trigger & ~changed.decision_trigger, ...
            'matched_correct_own', matched.correct_against_own_terminal, ...
            'changed_correct_own', changed.correct_against_own_terminal, ...
            'correct_to_wrong', matched.correct_against_own_terminal & ...
                                ~changed.correct_against_own_terminal, ...
            'wrong_to_correct', ~matched.correct_against_own_terminal & ...
                                changed.correct_against_own_terminal); ...
    end
    rows = rows(1:row_index);
    paired = struct2table([rows{:}]');
end

function summary = paired_summary(paired, contract)
    groups = ["all", string(contract.families)];
    rows = cell(numel(groups) * numel(contract.lead_hours), 1);
    index = 0;
    for g = 1:numel(groups)
        for lead = contract.lead_hours
            index = index + 1;
            mask = paired.lead_hours == lead;
            if groups(g) ~= "all", mask = mask & paired.family == groups(g); end
            part = paired(mask, :);
            differences = part.absolute_log_error_change;
            [boot_lo, boot_hi] = bootstrap_median_interval(differences, ...
                contract.bootstrap_samples, contract.bootstrap_seed + index);
            [fraction, fraction_ci] = binofit(nnz(part.worsened), height(part));
            trigger_up = nnz(part.trigger_0_to_1);
            trigger_down = nnz(part.trigger_1_to_0);
            correct_bad = nnz(part.correct_to_wrong);
            correct_good = nnz(part.wrong_to_correct);
            rows{index} = struct('group', groups(g), 'lead_hours', lead, ...
                'n', height(part), ...
                'median_matched_abs_log_error', ...
                    median_finite(part.matched_absolute_log_error), ...
                'median_changed_abs_log_error', ...
                    median_finite(part.changed_absolute_log_error), ...
                'median_abs_log_error_increase', median_finite(differences), ...
                'median_increase_bootstrap_low', boot_lo, ...
                'median_increase_bootstrap_high', boot_hi, ...
                'fraction_worsened', fraction, ...
                'fraction_worsened_ci_low', fraction_ci(1), ...
                'fraction_worsened_ci_high', fraction_ci(2), ...
                'median_abs_residual_divergence', ...
                    median_finite(part.absolute_residual_log_divergence), ...
                'trigger_0_to_1', trigger_up, ...
                'trigger_1_to_0', trigger_down, ...
                'trigger_mcnemar_exact_p', exact_discordant_p(trigger_up, trigger_down), ...
                'correct_to_wrong', correct_bad, ...
                'wrong_to_correct', correct_good, ...
                'correctness_mcnemar_exact_p', ...
                    exact_discordant_p(correct_bad, correct_good));
        end
    end
    summary = struct2table([rows{:}]');
end

function cells = cell_summary(detail, paired, contract)
    rows = cell(numel(contract.families) * numel(contract.target_bins) * ...
                numel(contract.lead_hours), 1);
    index = 0;
    for f = 1:numel(contract.families)
        for b = contract.target_bins
            for lead = contract.lead_hours
                index = index + 1;
                matched = detail(detail.stratum == "matched" & ...
                    detail.family == string(contract.families{f}) & ...
                    detail.control_bin == b & detail.lead_hours == lead, :);
                changed = detail(detail.stratum == "differential_4x" & ...
                    detail.family == string(contract.families{f}) & ...
                    detail.control_bin == b & detail.lead_hours == lead, :);
                pair = paired(paired.family == string(contract.families{f}) & ...
                    paired.control_bin == b & paired.lead_hours == lead, :);
                up = nnz(pair.trigger_0_to_1);
                down = nnz(pair.trigger_1_to_0);
                rows{index} = struct('family', string(contract.families{f}), ...
                    'control_bin', b, 'lead_hours', lead, ...
                    'n_common', height(pair), ...
                    'matched_trigger_rate', mean(matched.decision_trigger), ...
                    'changed_trigger_rate', mean(changed.decision_trigger), ...
                    'matched_own_accuracy', ...
                        mean(matched.correct_against_own_terminal), ...
                    'changed_own_accuracy', ...
                        mean(changed.correct_against_own_terminal), ...
                    'median_abs_log_error_increase', ...
                        median_finite(pair.absolute_log_error_change), ...
                    'fraction_worsened', mean(pair.worsened), ...
                    'trigger_0_to_1', up, 'trigger_1_to_0', down, ...
                    'trigger_mcnemar_exact_p', exact_discordant_p(up, down));
            end
        end
    end
    cells = struct2table([rows{:}]');
end

function row = replay_status_row(record)
    if isempty(record)
        row = struct('seed', NaN, 'family', "", 'control_bin', NaN, ...
            'status', "missing", 'failure_reason', "not evaluated");
        return;
    end
    row = struct('seed', record.seed, 'family', string(record.family), ...
        'control_bin', record.control_bin, 'status', string(record.status), ...
        'failure_reason', string(record.failure_reason));
end

function value = safe_log10(pc, floor_value)
    value = log10(max(pc, floor_value));
end

function [low, high] = bootstrap_median_interval(values, n_boot, seed)
    values = values(isfinite(values));
    if isempty(values), low = NaN; high = NaN; return; end
    stream = RandStream('mt19937ar', 'Seed', seed);
    boot = zeros(n_boot, 1);
    for k = 1:n_boot
        indices = randi(stream, numel(values), numel(values), 1);
        boot(k) = median(values(indices));
    end
    interval = prctile(boot, [2.5, 97.5]);
    low = interval(1);
    high = interval(2);
end

function value = median_finite(values)
    values = values(isfinite(values));
    if isempty(values), value = NaN; else, value = median(values); end
end
