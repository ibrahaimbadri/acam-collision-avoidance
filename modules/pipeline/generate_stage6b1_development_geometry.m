function record = generate_stage6b1_development_geometry( ...
        item, generation, c)
%GENERATE_STAGE6B1_DEVELOPMENT_GEOMETRY Build one paired production unit.

    try
        config = generation.scenario_config;
        config.force_encounter_family = char(item.family);
        config.pc_band_index = item.risk_band;
        base = generate_synthetic_scenario(config, c, item.seed);
        assert(~isempty(base), 'Stage 6b1 geometry generation failed.');
        c_local = c2_scenario_constants(c, base);
        filter = stage5h_drag_filter_config(generation.fixed_candidate);
        rows = cell(numel(generation.arms), 1);
        contexts = cell(numel(generation.arms), 1);
        for arm_index = 1:numel(generation.arms)
            arm = generation.arms(arm_index);
            scenario = apply_arm(base, arm, item.seed, generation);
            segment = decision_segment(scenario, c_local, ...
                generation.lead_s, filter.max_tracking_duration_s);
            [tracking, ~] = run_joint_drag_tracking(segment, c_local, ...
                filter, generation.measurement_seed_offset + item.seed, []);
            event_id = sprintf('stage_6b1-%d-%s', item.seed, arm.name);
            platform = struct('event_id', event_id, ...
                'spacecraft_mass_kg', scenario.mass, 'hbr_m', scenario.hbr_m);
            estimate = struct('state', tracking.state, ...
                'covariance', tracking.covariance);
            [message, diagnostics, tca] = generate_joint_drag_cdm( ...
                estimate, platform, c_local, generation.lead_s, filter, ...
                event_id);
            [rows{arm_index}, contexts{arm_index}] = build_arm( ...
                item, arm, scenario, segment, tracking, message, ...
                diagnostics, tca, filter, c_local, generation);
        end
        record = struct('status', "complete", ...
            'geometry_id', string(item.geometry_id), 'seed', item.seed, ...
            'family', string(item.family), 'rows', vertcat(rows{:}), ...
            'contexts', vertcat(contexts{:}), 'error_id', "", ...
            'error_message', "");
    catch ME
        record = struct('status', "failed", ...
            'geometry_id', string(item.geometry_id), 'seed', item.seed, ...
            'family', string(item.family), 'rows', struct([]), ...
            'contexts', struct([]), 'error_id', string(ME.identifier), ...
            'error_message', string(ME.message));
    end
end

function [row, context] = build_arm(item, arm, scenario, segment, ...
        tracking, message, diagnostics, tca, filter, c, generation)
    decision_epoch = segment.truth_epoch_utc + ...
        seconds(tracking.tracking_duration_s);
    lla = eci2lla(tracking.state(1:3)', datevec(decision_epoch));
    weather = space_weather_at_utc( ...
        scenario.truth_model.space_weather_profile, decision_epoch, lla(2));
    decision = build_stage6b1_decision_context(message, tracking, filter, ...
        decision_epoch, weather);
    target_timer = tic;
    target = generate_stage6b1_optimizer_target(decision, c);
    target_runtime_s = toc(target_timer);
    [feature_names, ~, feature_version] = truth_audited_feature_schema();

    combined_norm = norm(message.combined_position_covariance_rtn_m2, 'fro');
    relative_identity_error = diagnostics.relative_covariance_identity_error / ...
        max(1, combined_norm);
    covariance_pass = covariance_ok(tracking.covariance) && ...
        covariance_ok(tca.covariance) && ...
        diagnostics.cross_covariance_position_fro > 0 && ...
        relative_identity_error <= generation.relative_identity_tolerance;
    target_available = target.status == "success";
    fallback_required = target.status == "fallback_required";
    target_direction_supported = ~target_available || ...
        any(target.direction == ["prograde", "retrograde"]);
    target_vector_valid = (~target.triggered && ...
        target.status == "stay" && norm(target.dV_hill) == 0) || ...
        (target_available && all(isfinite(target.dV_hill)) && ...
        abs(target.dV_hill(1)) <= 1e-12 && ...
        abs(target.dV_hill(3)) <= 1e-12 && ...
        target.magnitude_mps > 0 && target.magnitude_mps <= ...
        c.max_maneuver_mps / generation.reserve_factor) || ...
        (fallback_required && all(isnan(target.dV_hill)));

    row = struct('geometry_id', string(item.geometry_id), ...
        'seed', item.seed, 'family', string(item.family), ...
        'risk_band', item.risk_band, 'split', string(item.split), ...
        'arm', string(arm.name), ...
        'fit_eligible', item.split == "train" && ...
            string(arm.name) == "primary_drag", ...
        'calibration_eligible', item.split == "calibration" && ...
            string(arm.name) == "primary_drag", ...
        'srp_enabled_truth_diagnostic_only', arm.srp_enabled, ...
        'target_status', target.status, 'triggered', target.triggered, ...
        'target_available', target_available, ...
        'fallback_required', fallback_required, ...
        'target_direction', target.direction, ...
        'target_magnitude_mps', target.magnitude_mps, ...
        'target_dv_radial_mps', target.dV_hill(1), ...
        'target_dv_along_track_mps', target.dV_hill(2), ...
        'target_dv_cross_track_mps', target.dV_hill(3), ...
        'decision_pc', message.collision_probability, ...
        'robust_zero_burn_pc', target.robust_zero_burn_pc, ...
        'trigger_pc', target.trigger_pc, ...
        'target_runtime_s', target_runtime_s, ...
        'target_information_set_pass', ...
            target.information_set == "stage6b1_decision_context_v1", ...
        'complete_evaluator_pass', contains(target.evaluator_fidelity, ...
            'full 16-state covariance'), ...
        'target_direction_supported', target_direction_supported, ...
        'target_vector_valid', target_vector_valid, ...
        'covariance_invariants_pass', covariance_pass, ...
        'relative_covariance_identity_error_relative', ...
            relative_identity_error, ...
        'cross_covariance_position_fro', ...
            diagnostics.cross_covariance_position_fro, ...
        'feature_schema_version', feature_version, ...
        'model_feature_count', numel(target.features), ...
        'model_features_finite', all(isfinite(target.features)), ...
        'tracking_mean_nis12_operational', ...
            decision.tracking.mean_nis12, ...
        'tracking_mean_nees12_truth_diagnostic_only', ...
            tracking.diagnostics.mean_nees12);
    for k = 1:numel(feature_names)
        row.(['feature_', feature_names{k}]) = target.features(k);
    end

    withheld = truth_replay_scenario(scenario, segment, tracking, ...
        message, tca);
    audit = struct('message', message, 'tracking', decision.tracking, ...
        'filter', filter, 'withheld_truth', withheld, ...
        'R_burn', hill_to_eci(message.target_state_eci_at_message));
    context = struct('geometry_id', string(item.geometry_id), ...
        'seed', item.seed, 'family', string(item.family), ...
        'risk_band', item.risk_band, 'split', string(item.split), ...
        'arm', string(arm.name), 'decision', decision, ...
        'target', target, 'audit', audit);
end

function scenario = apply_arm(base, arm, seed, generation)
    scenario = base;
    physical = physical_property_strata(base.mass, ...
        generation.physical_stratum);
    scenario.target_physical = physical.target;
    scenario.debris_physical = physical.debris;
    scenario.physical_property_stratum = generation.physical_stratum;
    model = base.truth_model;
    model.version = max(model.version, 3);
    model.mode = arm.truth_mode;
    model.include_nrlmsise = true;
    model.include_srp = arm.srp_enabled;
    specification = struct( ...
        'marginal_sigma_log', generation.marginal_sigma_log, ...
        'object_correlation', generation.object_correlation, ...
        'correlation_time_s', generation.correlation_time_s, ...
        'bias_log', generation.bias_log);
    model.density_residual_profile = sample_density_residual_profile( ...
        base.truth_tca_epoch_utc, ...
        generation.density_residual_seed_offset + seed, specification);
    scenario.truth_model = model;
    scenario.truth_model_mode = model.mode;
end

function segment = decision_segment(scenario, c, lead_s, tracking_s)
    duration = lead_s + tracking_s;
    context = scenario;
    context.truth_epoch_utc = scenario.truth_tca_epoch_utc;
    dynamics = truth_dynamics_pair(context, c, -duration);
    tolerance = truth_propagation_tolerance(context, ...
        struct('rel_tol', 1e-8, 'abs_tol', 1e-10));
    options = odeset('RelTol', tolerance.rel_tol, ...
        'AbsTol', tolerance.abs_tol);
    target = ode113(dynamics.target, [0, -duration], ...
        scenario.X_cpa_sat, options);
    debris = ode113(dynamics.debris, [0, -duration], ...
        scenario.X_cpa_deb, options);
    segment = scenario;
    segment.X0_sat = target.y(:, end);
    segment.X0_deb = debris.y(:, end);
    segment.t_to_cpa = duration;
    segment.truth_epoch_utc = scenario.truth_tca_epoch_utc - ...
        seconds(duration);
end

function withheld = truth_replay_scenario(source, segment, tracking, ...
        message, tca)
    combined = tca.combined_position_covariance_eci;
    withheld = struct( ...
        'X0_sat', tracking.diagnostics.truth_target_final(:), ...
        'X0_deb', tracking.diagnostics.truth_debris_final(:), ...
        'X_cpa_sat', source.X_cpa_sat, 'X_cpa_deb', source.X_cpa_deb, ...
        'rel_pos', source.X_cpa_sat(1:3) - source.X_cpa_deb(1:3), ...
        'rel_vel', source.X_cpa_sat(4:6) - source.X_cpa_deb(4:6), ...
        't_to_cpa', message.time_to_tca_s, 'C_sat', combined / 2, ...
        'C_deb', combined / 2, 'hbr_m', message.hbr_m, ...
        'HBR', message.hbr_m, 'mass', message.spacecraft_mass_kg, ...
        'truth_epoch_utc', segment.truth_epoch_utc + ...
            seconds(tracking.tracking_duration_s), ...
        'truth_model', source.truth_model, ...
        'truth_model_mode', source.truth_model_mode, ...
        'target_physical', source.target_physical, ...
        'debris_physical', source.debris_physical, ...
        'physical_property_stratum', source.physical_property_stratum);
end

function ok = covariance_ok(P)
    [~, status] = chol((P + P') / 2);
    ok = status == 0 && all(isfinite(P), 'all');
end

function R = hill_to_eci(X)
    X = X(:);
    radial = X(1:3) / norm(X(1:3));
    normal = cross(X(1:3), X(4:6));
    assert(norm(normal) > eps, 'Invalid target Hill frame.');
    normal = normal / norm(normal);
    R = [radial, cross(normal, radial), normal];
end
