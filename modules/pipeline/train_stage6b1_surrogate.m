function model = train_stage6b1_surrogate( ...
        X, direction, magnitude_mps, frozen)
%TRAIN_STAGE6B1_SURROGATE Fit the two frozen Gate D forests once.

    validateattributes(X, {'numeric'}, {'real', 'finite', '2d', 'nonempty'});
    direction = string(direction(:));
    magnitude_mps = magnitude_mps(:);
    assert(size(X, 1) == numel(direction) && ...
        numel(direction) == numel(magnitude_mps), ...
        'Stage 6b1 training dimensions disagree.');
    assert(size(X, 2) == 42 && ...
        all(ismember(direction, frozen.direction_classes)) && ...
        all(magnitude_mps > 0 & isfinite(magnitude_mps)), ...
        'Stage 6b1 training targets violate the frozen contract.');
    for k = 1:numel(frozen.direction_classes)
        assert(nnz(direction == frozen.direction_classes(k)) >= 30, ...
            'Stage 6b1 has insufficient training direction support.');
    end

    rng(frozen.random_seed, frozen.random_stream);
    direction_classifier = TreeBagger(frozen.tree_count, X, ...
        cellstr(direction), 'Method', 'classification', ...
        'MinLeafSize', frozen.minimum_leaf_size, ...
        'NumPredictorsToSample', frozen.classifier_predictors_per_split, ...
        'SampleWithReplacement', 'on', 'Surrogate', 'off', ...
        'OOBPrediction', 'off', 'OOBPredictorImportance', 'off');
    rng(frozen.random_seed, frozen.random_stream);
    magnitude_regressor = TreeBagger(frozen.tree_count, X, ...
        log10(magnitude_mps), 'Method', 'regression', ...
        'MinLeafSize', frozen.minimum_leaf_size, ...
        'NumPredictorsToSample', frozen.regressor_predictors_per_split, ...
        'SampleWithReplacement', 'on', 'Surrogate', 'off', ...
        'OOBPrediction', 'off', 'OOBPredictorImportance', 'off');

    model = struct('version', 1, ...
        'model_type', 'stage6b1_binary_direction_log_magnitude', ...
        'direction_classifier', direction_classifier, ...
        'magnitude_regressor', magnitude_regressor, ...
        'direction_classes', frozen.direction_classes, ...
        'feature_count', size(X, 2), 'training_rows', size(X, 1), ...
        'calibration_log10_correction', 0, 'config', frozen);
end
