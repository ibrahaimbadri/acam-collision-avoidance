function model = train_truth_oracle_surrogate(X, action_required, ...
        direction_index, magnitude_mps, config)
%TRAIN_TRUTH_ORACLE_SURROGATE Fit the frozen Stage 6b0 exploratory model.

    validateattributes(X, {'numeric'}, {'real', 'finite', '2d', 'nonempty'});
    n = size(X, 1);
    action_required = logical(action_required(:));
    direction_index = direction_index(:);
    magnitude_mps = magnitude_mps(:);
    assert(numel(action_required) == n && numel(direction_index) == n && ...
        numel(magnitude_mps) == n, 'Training target dimensions disagree.');
    assert(numel(unique(action_required)) == 2, ...
        'Both action classes are required for training.');
    maneuver = action_required;
    assert(nnz(maneuver) >= config.minimum_action_rows, ...
        'Too few action-required training rows.');
    assert(all(ismember(direction_index(maneuver), 1:6)) && ...
        all(magnitude_mps(maneuver) > 0 & ...
            magnitude_mps(maneuver) <= config.maximum_magnitude_mps), ...
        'Invalid maneuver targets.');
    assert(numel(unique(direction_index(maneuver))) >= 2, ...
        'At least two maneuver-direction classes are required.');

    rng(config.random_seed, 'twister');
    action_classifier = TreeBagger(config.tree_count, X, ...
        double(action_required), 'Method', 'classification', ...
        'MinLeafSize', config.minimum_leaf_size, ...
        'OOBPrediction', 'on', 'OOBPredictorImportance', 'on');
    direction_classifier = TreeBagger(config.tree_count, X(maneuver, :), ...
        direction_index(maneuver), 'Method', 'classification', ...
        'MinLeafSize', config.minimum_leaf_size, ...
        'OOBPrediction', 'on', 'OOBPredictorImportance', 'on');
    magnitude_regressor = TreeBagger(config.tree_count, X(maneuver, :), ...
        log10(magnitude_mps(maneuver)), 'Method', 'regression', ...
        'MinLeafSize', config.minimum_leaf_size, ...
        'OOBPrediction', 'on', 'OOBPredictorImportance', 'on');

    model = struct('version', 1, 'model_type', ...
        'random_forest_action_direction_log_magnitude', ...
        'action_classifier', action_classifier, ...
        'direction_classifier', direction_classifier, ...
        'magnitude_regressor', magnitude_regressor, 'config', config, ...
        'feature_count', size(X, 2), 'training_rows', n, ...
        'training_action_rows', nnz(maneuver), ...
        'training_direction_classes', unique(direction_index(maneuver))');
end
