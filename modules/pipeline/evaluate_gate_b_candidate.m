function [comparison, details] = evaluate_gate_b_candidate( ...
        context, dV_hill, c)
%EVALUATE_GATE_B_CANDIDATE Compare fixed and post-burn action evaluation.

    validateattributes(dV_hill, {'numeric'}, ...
        {'real', 'finite', 'vector', 'numel', 3}, mfilename, 'dV_hill');
    dV_hill = dV_hill(:);
    magnitude_mps = norm(dV_hill);
    if magnitude_mps == 0
        direction_hill = zeros(3, 1);
    else
        direction_hill = dV_hill / magnitude_mps;
    end
    assert(magnitude_mps <= c.max_maneuver_mps * (1 + 1e-12), ...
        'Gate B candidate exceeds the actuator limit.');

    [planning_evaluator, ~] = ...
        build_gate_b_joint_drag_evaluator(context.message, ...
            context.tracking, context.planning_scenario, context.filter, ...
            c, context.decision_epoch_utc);
    dV_eci = context.R_burn * dV_hill;
    truth = context.withheld_truth;
    [truth_complete_safe, ~, truth_complete_pc, ...
        truth_complete_details] = evaluate_joint_drag_truth_candidate( ...
            context, dV_hill, c);
    truth_tca_only_pc = truth_complete_details.tca_only_pc;

    [legacy_truth_safe, ~, legacy_truth_pc, legacy_truth_details] = ...
        evaluate_maneuver(truth, dV_eci, c, 0, true, ...
            context.truth_reuse_context);
    [planning, planning_details] = planning_evaluator( ...
        direction_hill, magnitude_mps);

    comparison = struct( ...
        'planning_legacy_pc', planning.legacy_pc, ...
        'planning_tca_only_pc', planning.tca_only_pc, ...
        'planning_complete_pc', planning.complete_pc, ...
        'truth_legacy_pc', legacy_truth_pc, ...
        'truth_tca_only_pc', truth_tca_only_pc, ...
        'truth_complete_pc', truth_complete_pc);
    comparison_values = [planning.legacy_pc, planning.tca_only_pc, ...
        planning.complete_pc, legacy_truth_pc, truth_tca_only_pc, ...
        truth_complete_pc];
    details = struct( ...
        'completed', planning_details.completed && ...
            legacy_truth_details.completed && ...
            truth_complete_details.completed && ...
            all(isfinite(comparison_values)), ...
        'magnitude_mps', magnitude_mps, 'dV_hill_mps', dV_hill, ...
        'dV_eci_mps', dV_eci, 'planning', planning_details, ...
        'truth_tca_s', truth_complete_details.truth_tca_s, ...
        'truth_tca_shift_s', truth_complete_details.truth_tca_shift_s, ...
        'truth_tca_diagnostics', ...
            truth_complete_details.truth_tca_diagnostics, ...
        'truth_legacy_safe', legacy_truth_safe, ...
        'truth_complete_safe', truth_complete_safe, ...
        'truth_legacy_details', legacy_truth_details, ...
        'truth_complete_details', truth_complete_details, ...
        'truth_complete_covariance_eci', ...
            truth_complete_details.relative_covariance_eci, ...
        'truth_covariance_change_relative', ...
            truth_complete_details.covariance_change_relative, ...
        'truth_relative_covariance_identity_error', ...
            truth_complete_details.relative_covariance_identity_error, ...
        'truth_cross_covariance_position_fro', ...
            truth_complete_details.cross_covariance_position_fro);
end
