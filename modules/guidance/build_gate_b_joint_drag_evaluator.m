function [evaluate_candidate, metadata] = ...
        build_gate_b_joint_drag_evaluator(message, tracking, scenario, ...
                                            filter, c, decision_epoch_utc, ...
                                            compare_legacy)
%BUILD_GATE_B_JOINT_DRAG_EVALUATOR Compare legacy and complete action risk.
%
% The complete path re-searches every robust member's post-burn TCA and
% samples one continuous, maneuver-dependent full joint covariance path at
% those epochs. The effective-drag and SRP members remain mean sensitivities.

    if nargin < 7 || isempty(compare_legacy)
        compare_legacy = true;
    end
    validateattributes(compare_legacy, {'logical', 'numeric'}, ...
        {'real', 'finite', 'scalar'}, mfilename, 'compare_legacy');
    compare_legacy = logical(compare_legacy);

    [legacy_evaluator, envelope] = build_joint_drag_robust_evaluator( ...
        message, tracking, scenario, filter, c, decision_epoch_utc, ...
        'legacy');
    nominal_tca_s = message.time_to_tca_s;
    half_width_s = min(3600, 0.25 * nominal_tca_s);
    search_interval_s = [max(60, nominal_tca_s - half_width_s), ...
        nominal_tca_s + half_width_s];
    state_points = repmat(tracking.state(:), 1, ...
        size(envelope.drag_state_points, 2));
    state_points(13:16, :) = envelope.drag_state_points;
    R_burn = hill_to_eci(message.target_state_eci_at_message);
    H = zeros(3, filter.state_dimension);
    H(:, 1:3) = eye(3);
    H(:, 7:9) = -eye(3);

    if isfield(scenario, 'force_environment')
        force_environment = scenario.force_environment;
    else
        force_environment = scenario.truth_model;
    end
    nominal_end_epoch = decision_epoch_utc + seconds(nominal_tca_s);
    sun_start = planetEphemeris(juliandate(decision_epoch_utc), ...
        'Earth', 'Sun', '432t', 'km')' * 1e3;
    sun_end = planetEphemeris(juliandate(nominal_end_epoch), ...
        'Earth', 'Sun', '432t', 'km')' * 1e3;
    srp = struct('sun_start_m', sun_start, 'sun_end_m', sun_end, ...
        'duration_s', nominal_tca_s, ...
        'solar_pressure_npm2', force_environment.solar_pressure_npm2, ...
        'astronomical_unit_m', force_environment.astronomical_unit_m);
    metadata = envelope;
    metadata.contract_version = 2;
    metadata.search_interval_s = search_interval_s;
    metadata.nominal_tca_s = nominal_tca_s;
    metadata.compare_legacy = compare_legacy;
    metadata.covariance_fidelity = ['candidate nominal joint-drag mean; ', ...
        'full 16-state covariance and target-debris cross-covariance; ', ...
        'sampled at each robust-member post-burn TCA'];
    metadata.srp_covariance_limitation = ['SRP is a deterministic mean ', ...
        'sensitivity and is not represented in the frozen EKF ', ...
        'covariance model'];
    evaluate_candidate = @evaluate;

    function [comparison, details] = evaluate( ...
            direction_hill, magnitude_mps, additional_epochs_s)
        if nargin < 3 || isempty(additional_epochs_s)
            additional_epochs_s = zeros(0, 1);
        end
        direction_hill = direction_hill(:);
        validateattributes(direction_hill, {'numeric'}, ...
            {'real', 'finite', 'vector', 'numel', 3}, mfilename, ...
            'direction_hill');
        validateattributes(magnitude_mps, {'numeric'}, ...
            {'real', 'finite', 'scalar', 'nonnegative'}, mfilename, ...
            'magnitude_mps');
        validateattributes(additional_epochs_s, {'numeric'}, ...
            {'real', 'finite', 'vector', 'nonnegative'}, mfilename, ...
            'additional_epochs_s');
        assert(all(additional_epochs_s(:) <= search_interval_s(2)), ...
            'Additional covariance epochs exceed the propagated search arc.');
        if magnitude_mps == 0
            dV_eci = zeros(3, 1);
        else
            assert(norm(direction_hill) > 0, ...
                'A nonzero maneuver requires a direction.');
            dV_eci = R_burn * direction_hill / norm(direction_hill) * ...
                magnitude_mps;
        end

        if compare_legacy
            [legacy_pc, legacy_details] = legacy_evaluator( ...
                direction_hill, magnitude_mps);
        else
            legacy_pc = NaN;
            legacy_details = struct('completed', true, ...
                'member_pc', nan(envelope.member_count, 1), ...
                'worst_member_index', NaN);
        end
        member_tca_s = nan(envelope.member_count, 1);
        member_state_tca = nan(filter.state_dimension, ...
            envelope.member_count);
        member_tca_diagnostics = cell(envelope.member_count, 1);
        member_tca_only_pc = nan(envelope.member_count, 1);
        for member = 1:envelope.member_count
            drag_index = envelope.member_drag_index(member);
            include_srp = logical(envelope.member_srp_enabled(member));
            initial = state_points(:, drag_index);
            initial(4:6) = initial(4:6) + dV_eci;
            dynamics = @(t, x) joint_drag_robust_dynamics( ...
                t, x, c, filter, include_srp, srp, ...
                scenario.target_physical, scenario.debris_physical);
            [member_tca_s(member), member_state_tca(:, member), ...
                tca_diagnostics] = find_joint_drag_tca( ...
                    initial, search_interval_s, c, filter, dynamics);
            member_tca_diagnostics{member} = tca_diagnostics;
            relative_position = member_state_tca(1:3, member) - ...
                member_state_tca(7:9, member);
            relative_velocity = member_state_tca(4:6, member) - ...
                member_state_tca(10:12, member);
            member_tca_only_pc(member) = ...
                calculate_poc_from_combined_covariance( ...
                    relative_position, relative_velocity, ...
                    envelope.combined_covariance_eci, message.hbr_m);
        end
        member_tca_diagnostics = vertcat(member_tca_diagnostics{:});

        central_initial = tracking.state(:);
        central_initial(4:6) = central_initial(4:6) + dV_eci;
        [central_tca_s, central_state_tca, central_tca_diagnostics] = ...
            find_joint_drag_tca(central_initial, search_interval_s, ...
                c, filter);
        covariance_epochs_s = [member_tca_s; central_tca_s; ...
            additional_epochs_s(:)];
        [covariance_states, joint_covariances, ...
            covariance_diagnostics] = ...
                propagate_joint_drag_covariance_epochs(central_initial, ...
                    tracking.covariance, covariance_epochs_s, c, filter);

        member_complete_pc = nan(envelope.member_count, 1);
        member_relative_covariance = nan(3, 3, envelope.member_count);
        member_covariance_change_relative = nan(envelope.member_count, 1);
        member_relative_identity_error = nan(envelope.member_count, 1);
        member_cross_covariance_position_fro = nan(envelope.member_count, 1);
        for member = 1:envelope.member_count
            joint_covariance = joint_covariances(:, :, member);
            relative_covariance = relative_position_covariance( ...
                joint_covariance, H);
            member_relative_covariance(:, :, member) = relative_covariance;
            member_covariance_change_relative(member) = norm( ...
                relative_covariance - envelope.combined_covariance_eci, ...
                'fro') / max(1, norm(envelope.combined_covariance_eci, 'fro'));
            member_relative_identity_error(member) = ...
                covariance_identity_error(joint_covariance, ...
                    relative_covariance);
            member_cross_covariance_position_fro(member) = ...
                norm(joint_covariance(1:3, 7:9), 'fro');
            relative_position = member_state_tca(1:3, member) - ...
                member_state_tca(7:9, member);
            relative_velocity = member_state_tca(4:6, member) - ...
                member_state_tca(10:12, member);
            member_complete_pc(member) = ...
                calculate_poc_from_combined_covariance( ...
                    relative_position, relative_velocity, ...
                    relative_covariance, message.hbr_m);
        end
        tca_only_pc = max(member_tca_only_pc);
        complete_pc = max(member_complete_pc);
        additional_start = envelope.member_count + 2;
        additional_count = numel(additional_epochs_s);
        additional_joint_covariances = joint_covariances(:, :, ...
            additional_start:(additional_start + additional_count - 1));
        additional_relative_covariances = nan(3, 3, additional_count);
        for k = 1:additional_count
            additional_relative_covariances(:, :, k) = ...
                relative_position_covariance( ...
                    additional_joint_covariances(:, :, k), H);
        end

        comparison = struct('legacy_pc', legacy_pc, ...
            'tca_only_pc', tca_only_pc, 'complete_pc', complete_pc);
        details = struct( ...
            'completed', legacy_details.completed && ...
                all(isfinite([member_tca_only_pc; member_complete_pc])), ...
            'magnitude_mps', magnitude_mps, 'dV_eci_mps', dV_eci, ...
            'legacy', legacy_details, ...
            'member_tca_s', member_tca_s, ...
            'member_tca_shift_s', member_tca_s - nominal_tca_s, ...
            'member_tca_diagnostics', member_tca_diagnostics, ...
            'member_tca_only_pc', member_tca_only_pc, ...
            'member_complete_pc', member_complete_pc, ...
            'tca_only_worst_member_index', ...
                find(member_tca_only_pc == tca_only_pc, 1), ...
            'complete_worst_member_index', ...
                find(member_complete_pc == complete_pc, 1), ...
            'member_relative_covariance_eci', ...
                member_relative_covariance, ...
            'member_covariance_change_relative', ...
                member_covariance_change_relative, ...
            'member_relative_identity_error', ...
                member_relative_identity_error, ...
            'member_cross_covariance_position_fro', ...
                member_cross_covariance_position_fro, ...
            'central_tca_s', central_tca_s, ...
            'central_tca_diagnostics', central_tca_diagnostics, ...
            'central_covariance_state_position_error_m', norm( ...
                covariance_states([1:3, 7:9], ...
                    envelope.member_count + 1) - ...
                central_state_tca([1:3, 7:9])), ...
            'covariance_diagnostics', covariance_diagnostics, ...
            'additional_epochs_s', additional_epochs_s(:), ...
            'additional_joint_covariances', ...
                additional_joint_covariances, ...
            'additional_relative_covariances_eci', ...
                additional_relative_covariances, ...
            'search_interval_s', search_interval_s, ...
            'legacy_covariance_eci', envelope.combined_covariance_eci);
    end
end

function covariance = relative_position_covariance(joint_covariance, H)
    covariance = H * joint_covariance * H';
    covariance = (covariance + covariance') / 2;
    assert_spd(covariance, 'relative position covariance');
end

function error_relative = covariance_identity_error(P, combined)
    direct = P(1:3, 1:3) + P(7:9, 7:9) - ...
        P(1:3, 7:9) - P(7:9, 1:3);
    error_relative = norm(combined - direct, 'fro') / ...
        max(1, norm(combined, 'fro'));
end

function assert_spd(P, label)
    [~, status] = chol((P + P') / 2);
    assert(status == 0 && all(isfinite(P), 'all'), ...
        '%s is not finite SPD.', label);
end

function R = hill_to_eci(X)
    X = X(:);
    radial = X(1:3) / norm(X(1:3));
    normal = cross(X(1:3), X(4:6));
    assert(norm(normal) > eps, 'Invalid target Hill frame.');
    normal = normal / norm(normal);
    R = [radial, cross(normal, radial), normal];
end
