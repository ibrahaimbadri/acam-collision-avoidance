function assessment = assess_maneuver_operability( ...
        decision_cdm, terminal_reference, c, config)
%ASSESS_MANEUVER_OPERABILITY Plan and audit one delayed finite-duration CAM.

    fixed_delay_s = config.decision_processing_s + ...
        config.command_validation_upload_s + ...
        config.attitude_slew_settle_s + ...
        config.execution_contingency_s;
    lead_s = decision_cdm.time_to_tca_s;
    assessment = empty_assessment(lead_s, fixed_delay_s, config);
    if decision_cdm.collision_probability <= c.pc_maneuver_threshold
        assessment.status = 'stay';
        assessment.timeline_feasible = true;
        return;
    end

    max_burn_s = c.max_maneuver_mps / config.nominal_acceleration_mps2;
    burn_midpoint_s = fixed_delay_s + max_burn_s / 2;
    if lead_s <= fixed_delay_s + config.minimum_post_burn_margin_s || ...
            burn_midpoint_s >= lead_s
        assessment.status = 'insufficient_time';
        return;
    end

    X_sat_burn = propagate_state( ...
        decision_cdm.target_state_eci_at_message, burn_midpoint_s, c);
    X_deb_burn = propagate_state( ...
        decision_cdm.chaser_state_eci_at_message, burn_midpoint_s, c);
    remaining_s = lead_s - burn_midpoint_s;
    R_tca = hill_to_eci(decision_cdm.target_state_eci_tca);
    % Planning consumes relative covariance. Splitting the published
    % combined block equally preserves it exactly even when it contains
    % target-debris cross-covariance. For legacy independent CDMs the
    % combined field is already the sum, so this is algebraically unchanged.
    C_combined = R_tca * ...
        decision_cdm.combined_position_covariance_rtn_m2 * R_tca';
    C_sat = C_combined / 2;
    C_deb = C_combined / 2;
    estimated_scenario = build_scenario( ...
        X_sat_burn, X_deb_burn, decision_cdm.target_state_eci_tca, ...
        decision_cdm.chaser_state_eci_tca, remaining_s, C_sat, C_deb, ...
        decision_cdm.hbr_m);
    search_config = maneuver_search_config(config.direction_scope);
    search_config.coarse_grid_count = config.coarse_grid_count;
    search_config.refinement_iterations = config.refinement_iterations;
    [dV_eci, search] = find_minimum_safe_maneuver( ...
        X_sat_burn, estimated_scenario, c, remaining_s, ...
        estimated_scenario.rel_pos, estimated_scenario.rel_vel, ...
        estimated_scenario.X_cpa_sat, C_sat, C_deb, X_deb_burn, ...
        search_config);
    assessment.search_status = search.status;
    assessment.planned_delta_v_mps = norm(dV_eci);
    assessment.planned_direction = string(search.selected_direction);
    assessment.estimated_final_pc = search.achieved_pc;
    if ~strcmp(search.status, 'success')
        assessment.status = ['search_', search.status];
        return;
    end

    burn_duration_s = norm(dV_eci) / config.nominal_acceleration_mps2;
    burn_start_s = burn_midpoint_s - burn_duration_s / 2;
    burn_end_s = burn_midpoint_s + burn_duration_s / 2;
    post_burn_margin_s = lead_s - burn_end_s;
    assessment.burn_start_s = burn_start_s;
    assessment.burn_midpoint_s = burn_midpoint_s;
    assessment.burn_duration_s = burn_duration_s;
    assessment.post_burn_margin_s = post_burn_margin_s;
    assessment.timeline_feasible = ...
        burn_start_s >= fixed_delay_s && ...
        post_burn_margin_s >= config.minimum_post_burn_margin_s;
    accelerations = config.acceleration_sensitivity_mps2;
    assessment.acceleration_sensitivity_mps2 = accelerations;
    assessment.timeline_margin_sensitivity_s = lead_s - fixed_delay_s - ...
        norm(dV_eci) ./ accelerations - config.minimum_post_burn_margin_s;
    if ~assessment.timeline_feasible
        assessment.status = 'insufficient_time';
        return;
    end

    reference_cdm = terminal_reference.cdm;
    truth_context = struct();
    if isfield(terminal_reference, 'truth') && ...
            isfield(terminal_reference.truth, 'truth_model')
        truth = terminal_reference.truth;
        truth_context.truth_model = truth.truth_model;
        truth_context.truth_epoch_utc = truth.truth_tca_epoch_utc;
        truth_context.target_physical = truth.target_physical;
        truth_context.debris_physical = truth.debris_physical;
        X_sat_tca_truth = truth.target_state_eci_tca;
        X_deb_tca_truth = truth.chaser_state_eci_tca;
    else
        X_sat_tca_truth = reference_cdm.target_state_eci_tca;
        X_deb_tca_truth = reference_cdm.chaser_state_eci_tca;
    end
    backward_dynamics = truth_dynamics_pair( ...
        truth_context, c, -remaining_s);
    truth_tolerance = truth_propagation_tolerance(truth_context, ...
        struct('rel_tol', 1e-8, 'abs_tol', 1e-10));
    X_sat_reference = propagate_state( ...
        X_sat_tca_truth, -remaining_s, c, backward_dynamics.target, ...
        truth_tolerance);
    X_deb_reference = propagate_state( ...
        X_deb_tca_truth, -remaining_s, c, backward_dynamics.debris, ...
        truth_tolerance);
    R_reference = hill_to_eci(reference_cdm.target_state_eci_tca);
    C_sat_reference = R_reference * ...
        reference_cdm.target_position_covariance_rtn_m2 * R_reference';
    C_deb_reference = R_reference * ...
        reference_cdm.chaser_position_covariance_rtn_m2 * R_reference';
    reference_scenario = build_scenario( ...
        X_sat_reference, X_deb_reference, ...
        X_sat_tca_truth, X_deb_tca_truth, remaining_s, ...
        C_sat_reference, C_deb_reference, reference_cdm.hbr_m);
    if ~isempty(fieldnames(truth_context))
        reference_scenario.truth_model = truth_context.truth_model;
        reference_scenario.truth_epoch_utc = ...
            truth_context.truth_epoch_utc - seconds(remaining_s);
        reference_scenario.target_physical = truth_context.target_physical;
        reference_scenario.debris_physical = truth_context.debris_physical;
    end
    [~, ~, reference_pc, details] = evaluate_maneuver( ...
        reference_scenario, dV_eci, c, 0, true);
    assessment.reference_final_pc = reference_pc;
    assessment.reference_evaluation_completed = details.completed;
    assessment.reference_remediation_success = details.completed && ...
        reference_pc <= c.pc_target_remediation;
    assessment.operational_success = assessment.timeline_feasible && ...
        assessment.reference_remediation_success;
    if assessment.operational_success
        assessment.status = 'success';
    else
        assessment.status = 'reference_remediation_failed';
    end
end

function assessment = empty_assessment(lead_s, fixed_delay_s, config)
    assessment = struct( ...
        'status', 'not_assessed', ...
        'search_status', '', ...
        'lead_time_s', lead_s, ...
        'fixed_preparation_s', fixed_delay_s, ...
        'burn_start_s', NaN, ...
        'burn_midpoint_s', NaN, ...
        'burn_duration_s', NaN, ...
        'post_burn_margin_s', lead_s - fixed_delay_s, ...
        'planned_delta_v_mps', 0, ...
        'planned_direction', "", ...
        'estimated_final_pc', NaN, ...
        'reference_final_pc', NaN, ...
        'timeline_feasible', false, ...
        'reference_evaluation_completed', false, ...
        'reference_remediation_success', false, ...
        'operational_success', false, ...
        'acceleration_sensitivity_mps2', ...
            config.acceleration_sensitivity_mps2, ...
        'timeline_margin_sensitivity_s', nan(size( ...
            config.acceleration_sensitivity_mps2)));
end

function scenario = build_scenario(X_sat, X_deb, X_sat_tca, X_deb_tca, ...
        remaining_s, C_sat, C_deb, hbr_m)
    scenario = struct( ...
        'X0_sat', X_sat, 'X0_deb', X_deb, ...
        'X_cpa_sat', X_sat_tca, 'X_cpa_deb', X_deb_tca, ...
        'rel_pos', X_sat_tca(1:3) - X_deb_tca(1:3), ...
        'rel_vel', X_sat_tca(4:6) - X_deb_tca(4:6), ...
        't_to_cpa', remaining_s, 'C_sat', C_sat, 'C_deb', C_deb, ...
        'hbr_m', hbr_m, 'HBR', hbr_m);
end

function X_final = propagate_state( ...
        X_initial, duration_s, c, dynamics, tolerance)
    if nargin < 4 || isempty(dynamics)
        dynamics = @(t, X) twoBodyJ2Drag_simple(t, X, c);
    end
    if nargin < 5 || isempty(tolerance)
        tolerance = struct('rel_tol', 1e-8, 'abs_tol', 1e-10);
    end
    options = odeset('RelTol', tolerance.rel_tol, ...
        'AbsTol', tolerance.abs_tol, ...
        'Events', @(t, X) earth_collision_event(t, X, c));
    solution = ode113(dynamics, ...
                      [0, duration_s], X_initial(:), options);
    if abs(solution.x(end) - duration_s) > max(1, 1e-9 * abs(duration_s))
        error('ACAM:ManeuverOperabilityPropagationFailed', ...
              'Maneuver-operability propagation stopped early.');
    end
    X_final = solution.y(:, end);
end

function R_h2e = hill_to_eci(X)
    r_hat = X(1:3) / norm(X(1:3));
    h_hat = cross(X(1:3), X(4:6));
    h_hat = h_hat / norm(h_hat);
    R_h2e = [r_hat, cross(h_hat, r_hat), h_hat];
end
