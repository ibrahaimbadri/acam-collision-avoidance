function [evaluate_candidate, envelope] = ...
        build_joint_drag_robust_evaluator(message, tracking, scenario, ...
                                            filter, c, decision_epoch_utc, ...
                                            evaluation_mode)
%BUILD_JOINT_DRAG_ROBUST_EVALUATOR Canonical complete joint-risk evaluator.

    if nargin < 7 || isempty(evaluation_mode)
        evaluation_mode = 'complete';
    end
    evaluation_mode = validatestring(evaluation_mode, ...
        {'complete', 'legacy'});
    complete_evaluator = [];
    if strcmp(evaluation_mode, 'complete')
        [complete_evaluator, envelope] = ...
            build_gate_b_joint_drag_evaluator(message, tracking, scenario, ...
                filter, c, decision_epoch_utc, false);
        envelope.fidelity = envelope.covariance_fidelity;
        evaluate_candidate = @evaluate_complete;
        return;
    end

    validateattributes(tracking.state, {'numeric'}, ...
        {'real', 'finite', 'vector', 'numel', 16}, mfilename, ...
        'tracking.state');
    validateattributes(tracking.covariance, {'numeric'}, ...
        {'real', 'finite', 'size', [16, 16]}, mfilename, ...
        'tracking.covariance');
    validateattributes(message.time_to_tca_s, {'numeric'}, ...
        {'real', 'finite', 'scalar', 'positive'}, mfilename, ...
        'message.time_to_tca_s');
    if isempty(decision_epoch_utc.TimeZone)
        decision_epoch_utc.TimeZone = 'UTC';
    end
    required = {'target_physical', 'debris_physical'};
    assert(all(isfield(scenario, required)), ...
        'Stage 5v robust planning context is incomplete.');
    assert(isfield(scenario, 'force_environment') || ...
        isfield(scenario, 'truth_model'), ...
        'Robust planning force environment is incomplete.');
    assert(filter.state_dimension == 16 && ...
        filter.differential_density_enabled, ...
        'Stage 5v requires the frozen 16-state differential-density EKF.');

    state_mean = tracking.state(:);
    assert(norm(state_mean(1:6) - ...
        message.target_state_eci_at_message(:)) < 1e-6 && ...
        norm(state_mean(7:12) - ...
        message.chaser_state_eci_at_message(:)) < 1e-6, ...
        'CDM and robust-envelope decision states do not match.');
    [states, effective_covariance] = drag_envelope( ...
        state_mean, tracking.covariance);
    R_burn = hill_to_eci(message.target_state_eci_at_message);
    R_tca = hill_to_eci(message.target_state_eci_tca);
    combined_eci = R_tca * ...
        message.combined_position_covariance_rtn_m2 * R_tca';
    combined_eci = (combined_eci + combined_eci') / 2;
    assert_covariance(combined_eci, 'combined relative position covariance');

    if isfield(scenario, 'force_environment')
        force_environment = scenario.force_environment;
    else
        force_environment = scenario.truth_model;
    end
    end_epoch = decision_epoch_utc + seconds(message.time_to_tca_s);
    sun_start = planetEphemeris(juliandate(decision_epoch_utc), ...
        'Earth', 'Sun', '432t', 'km')' * 1e3;
    sun_end = planetEphemeris(juliandate(end_epoch), ...
        'Earth', 'Sun', '432t', 'km')' * 1e3;
    srp = struct('sun_start_m', sun_start, 'sun_end_m', sun_end, ...
        'duration_s', message.time_to_tca_s, ...
        'solar_pressure_npm2', force_environment.solar_pressure_npm2, ...
        'astronomical_unit_m', force_environment.astronomical_unit_m);
    options = odeset('RelTol', filter.state_propagation_rel_tol, ...
        'AbsTol', filter.state_propagation_abs_tol);
    srp_enabled = [false, true];
    member_drag_index = repelem((1:size(states, 2))', 2);
    member_srp_enabled = repmat(srp_enabled(:), size(states, 2), 1);
    envelope = struct( ...
        'contract_version', 1, ...
        'chi2_2d_95', 5.991464547107979, ...
        'drag_state_points', states(13:16, :), ...
        'effective_drag_covariance', effective_covariance, ...
        'srp_states', srp_enabled, ...
        'member_drag_index', member_drag_index, ...
        'member_srp_enabled', member_srp_enabled, ...
        'member_count', numel(member_drag_index), ...
        'combined_covariance_eci', combined_eci, ...
        'decision_epoch_utc', decision_epoch_utc, ...
        'fidelity', ['joint_c060_d035 mean model; 95% effective-drag ', ...
                     'principal axes; SRP off/on']);
    evaluate_candidate = @evaluate;

    function [worst_pc, details] = evaluate(direction_hill, magnitude_mps)
        direction_hill = direction_hill(:);
        validateattributes(direction_hill, {'numeric'}, ...
            {'real', 'finite', 'vector', 'numel', 3}, mfilename, ...
            'direction_hill');
        validateattributes(magnitude_mps, {'numeric'}, ...
            {'real', 'finite', 'scalar', 'nonnegative'}, mfilename, ...
            'magnitude_mps');
        if magnitude_mps == 0
            dV_eci = zeros(3, 1);
        else
            assert(norm(direction_hill) > 0, ...
                'A nonzero maneuver requires a direction.');
            dV_eci = R_burn * ...
                (direction_hill / norm(direction_hill) * magnitude_mps);
        end
        member_pc = nan(envelope.member_count, 1);
        member = 0;
        for drag_index = 1:size(states, 2)
            for use_srp = srp_enabled
                member = member + 1;
                initial = states(:, drag_index);
                initial(4:6) = initial(4:6) + dV_eci;
                solution = ode113(@(t, x) robust_dynamics( ...
                    t, x, c, filter, logical(use_srp), srp, ...
                    scenario.target_physical, scenario.debris_physical), ...
                    [0, message.time_to_tca_s], initial, options);
                final = solution.y(:, end);
                relative_position = final(1:3) - final(7:9);
                relative_velocity = final(4:6) - final(10:12);
                member_pc(member) = calculate_poc_from_combined_covariance( ...
                    relative_position, relative_velocity, combined_eci, ...
                    message.hbr_m);
            end
        end
        worst_pc = max(member_pc);
        details = struct('member_pc', member_pc, ...
            'worst_member_index', find(member_pc == worst_pc, 1), ...
            'completed', all(isfinite(member_pc)), ...
            'magnitude_mps', magnitude_mps, 'dV_eci_mps', dV_eci);
    end

    function [worst_pc, details] = evaluate_complete( ...
            direction_hill, magnitude_mps)
        [comparison, details] = complete_evaluator( ...
            direction_hill, magnitude_mps);
        worst_pc = comparison.complete_pc;
        details.member_pc = details.member_complete_pc;
        details.worst_member_index = ...
            details.complete_worst_member_index;
        details.evaluation_mode = 'complete_post_burn_tca_joint_covariance';
    end
end

function [states, effective_covariance] = drag_envelope(mean_state, covariance)
    indices = 13:16;
    G = [1, 0, 1, 1; 0, 1, 1, -1];
    Pz = covariance(indices, indices);
    Pz = (Pz + Pz') / 2;
    effective_covariance = G * Pz * G';
    effective_covariance = (effective_covariance + ...
        effective_covariance') / 2;
    assert_covariance(effective_covariance, ...
        'effective target/debris log-drag covariance');
    [vectors, values] = eig(effective_covariance, 'vector');
    [values, order] = sort(values, 'descend');
    vectors = vectors(:, order);
    radius = sqrt(5.991464547107979);
    states = repmat(mean_state(:), 1, 5);
    column = 1;
    for axis = 1:2
        effective_delta = radius * sqrt(values(axis)) * vectors(:, axis);
        state_delta = Pz * G' * (effective_covariance \ effective_delta);
        states(indices, column + 1) = mean_state(indices) + state_delta;
        states(indices, column + 2) = mean_state(indices) - state_delta;
        column = column + 2;
    end
end

function derivative = robust_dynamics(t, state, c, filter, include_srp, ...
        srp, target_physical, debris_physical)
    derivative = joint_drag_dynamics(t, state, c, filter);
    if ~include_srp
        return;
    end
    fraction = min(max(t / srp.duration_s, 0), 1);
    sun_position = srp.sun_start_m + fraction * ...
        (srp.sun_end_m - srp.sun_start_m);
    derivative(4:6) = derivative(4:6) + srp_acceleration( ...
        state(1:3), sun_position, c, srp, target_physical);
    derivative(10:12) = derivative(10:12) + srp_acceleration( ...
        state(7:9), sun_position, c, srp, debris_physical);
end

function acceleration = srp_acceleration(position, sun_position, c, ...
        environment, physical)
    sun_direction = sun_position / norm(sun_position);
    behind_earth = dot(position, sun_direction) < 0;
    shadow_distance = norm(position - ...
        dot(position, sun_direction) * sun_direction);
    if behind_earth && shadow_distance < c.Re
        acceleration = zeros(3, 1);
        return;
    end
    to_sun = sun_position - position;
    acceleration = -environment.solar_pressure_npm2 * ...
        physical.reflectivity_coefficient * ...
        (physical.srp_area_m2 / physical.mass_kg) * ...
        (environment.astronomical_unit_m / norm(to_sun))^2 * ...
        (to_sun / norm(to_sun));
end

function assert_covariance(P, label)
    [~, status] = chol((P + P') / 2);
    assert(status == 0 && all(isfinite(P), 'all'), ...
        '%s is not finite SPD.', label);
end

function R = hill_to_eci(X)
    X = X(:);
    radial = X(1:3) / norm(X(1:3));
    normal = cross(X(1:3), X(4:6));
    assert(norm(normal) > eps, 'Invalid target Hill frame.');
    normal = normal / norm(normal);
    R = [radial, cross(normal, radial), normal];
end
