function dataset = validate_dataset_contract(dataset)
%VALIDATE_DATASET_CONTRACT Reject datasets that do not match the schema.

    if ~isstruct(dataset)
        error('ACAM:DatasetContractMissing', ...
              'The artifact must contain a dataset struct.');
    end

    required = {'X', 'y_action', 'y_dv_hill', 'feature_names', ...
                'feature_units', 'schema_version', 'scenario_metadata', ...
                'generator_config', 'seed', 'created_at'};
    for k = 1:numel(required)
        if ~isfield(dataset, required{k})
            error('ACAM:DatasetContractMissing', ...
                  'Dataset field "%s" is missing.', required{k});
        end
    end

    [expected_names, expected_units, expected_version] = feature_schema();
    if ~isequal(dataset.schema_version, expected_version) || ...
            ~isequal(dataset.feature_names, expected_names) || ...
            ~isequal(dataset.feature_units, expected_units)
        error('ACAM:FeatureSchemaMismatch', ...
              'Dataset feature schema does not match version %d.', ...
              expected_version);
    end

    validateattributes(dataset.X, {'numeric'}, ...
        {'2d', 'finite', 'ncols', numel(expected_names)}, ...
        mfilename, 'dataset.X');
    validateattributes(dataset.y_action, {'numeric', 'logical'}, ...
        {'vector', 'finite'}, mfilename, 'dataset.y_action');
    validateattributes(dataset.y_dv_hill, {'numeric'}, ...
        {'2d', 'finite', 'ncols', 3}, mfilename, 'dataset.y_dv_hill');

    n = size(dataset.X, 1);
    if any(~ismember(double(dataset.y_action(:)), [0, 1]))
        error('ACAM:DatasetLabelMismatch', ...
              'dataset.y_action must contain only 0/1 labels.');
    end
    if numel(dataset.y_action) ~= n || size(dataset.y_dv_hill, 1) ~= n
        error('ACAM:DatasetShapeMismatch', ...
              'Feature and label row counts must match.');
    end

    metadata_fields = {'requested_risk_band', 'actual_tca_s', 'tca_verified', ...
        'tca_orthogonality_residual', 'orbital_energy_valid', ...
        'perigee_valid', 'propagation_fidelity', 'fallback_used', ...
        'round_trip_position_error_m', 'optimizer_exit_status', ...
        'initial_pc', 'final_pc', 'random_seed'};
    if ~isstruct(dataset.scenario_metadata) || ...
            numel(dataset.scenario_metadata) ~= n
        error('ACAM:DatasetShapeMismatch', ...
              'scenario_metadata must contain one row per scenario.');
    end
    for k = 1:numel(metadata_fields)
        if ~isfield(dataset.scenario_metadata, metadata_fields{k})
            error('ACAM:DatasetContractMissing', ...
                  'scenario_metadata.%s is missing.', metadata_fields{k});
        end
    end

    validateattributes(dataset.seed, {'numeric'}, ...
        {'real', 'finite', 'scalar'}, mfilename, 'dataset.seed');
    if ~isstruct(dataset.generator_config) || isempty(dataset.created_at)
        error('ACAM:DatasetContractMissing', ...
              'generator_config and created_at must be present.');
    end
end
