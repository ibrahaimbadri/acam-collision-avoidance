function features = build_truth_audited_features( ...
        message, tracking, robust_zero_burn_pc, weather)
%BUILD_TRUTH_AUDITED_FEATURES Build the operational-only pilot feature row.

    metadata = struct('relative_state_convention', ...
        'target minus chaser', 'risk_scale', 'probability', ...
        'maneuver_validation_supported', true, ...
        'notes', 'Truth-audited pilot model-facing decision CDM');
    sequence = struct('event_id', message.event_id, ...
        'source', message.source, 'messages', message, 'metadata', metadata);
    base = build_features_from_cdm(sequence, [], struct());
    validateattributes(tracking.state, {'numeric'}, ...
        {'real', 'finite', 'vector', 'numel', 16}, mfilename, ...
        'tracking.state');
    validateattributes(tracking.covariance, {'numeric'}, ...
        {'real', 'finite', 'size', [16, 16]}, mfilename, ...
        'tracking.covariance');
    validateattributes(robust_zero_burn_pc, {'numeric'}, ...
        {'real', 'finite', 'scalar', '>=', 0, '<=', 1}, mfilename, ...
        'robust_zero_burn_pc');
    required_weather = {'f107_average', 'f107_daily', ...
        'magnetic_index', 'local_solar_time_h'};
    assert(all(isfield(weather, required_weather)), ...
        'Operational space-weather fields are incomplete.');
    validateattributes(weather.magnetic_index, {'numeric'}, ...
        {'real', 'finite', 'vector', 'numel', 7}, mfilename, ...
        'weather.magnetic_index');

    covariance = message.combined_position_covariance_rtn_m2;
    covariance = (covariance + covariance') / 2;
    covariance_shape = covariance([1, 4, 7, 5, 8, 9]);
    drag_state = tracking.state(13:16);
    drag_covariance = tracking.covariance(13:16, 13:16);
    drag_covariance = (drag_covariance + drag_covariance') / 2;
    drag_covariance_shape = drag_covariance([1, 5, 9, 13, ...
        6, 10, 14, 11, 15, 16]);
    mean_nis = tracking.diagnostics.mean_nis12;
    measurement_fraction = mean(tracking.measurement_available);
    magnetic = weather.magnetic_index(:);
    extras = [covariance_shape(:); robust_zero_burn_pc; drag_state(:); ...
        drag_covariance_shape(:); mean_nis; measurement_fraction; ...
        weather.f107_average; weather.f107_daily; magnetic(1); magnetic(2); ...
        weather.local_solar_time_h];
    features = [base(:); extras];
    [names, ~] = truth_audited_feature_schema();
    assert(numel(features) == numel(names) && all(isfinite(features)), ...
        'Truth-audited operational feature row is incomplete.');
end

