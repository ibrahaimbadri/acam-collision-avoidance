function checks = test_stage6b1_development_pipeline()
%TEST_STAGE6B1_DEVELOPMENT_PIPELINE Artifact-free launch preflight.

    project_root = fileparts(mfilename('fullpath'));
    [design, correction] = ...
        stage6b1_development_correction_contract(project_root);
    development = design.geometry_plan(~design.geometry_plan.sealed, :);
    names = [ ...
        "valid_gate_d_hash"; "valid_correction_hash"; ...
        "development_geometry_count"; ...
        "sealed_schedule_excluded"; "development_split_counts"; ...
        "development_seed_bounds"; "geometry_ids_unique"; ...
        "source_filter_preserved"; "filter_metadata_removed"; ...
        "filter_numerics_preserved"; "forbidden_filter_still_rejected"; ...
        "gate_c_regression"; "synthetic_model_fit"; ...
        "synthetic_binary_classes"; "synthetic_proposal_valid"; ...
        "synthetic_proposal_bounded"; "no_production_artifact_created"];
    passed = false(numel(names), 1);
    detail = strings(numel(names), 1);

    gate_d_path = fullfile(project_root, 'outputs', ...
        'stage_6b1_gate_d_design_validation_v2', ...
        'stage_6b1_gate_d_results.mat');
    passed(1) = strcmpi(sha256_file(gate_d_path), ...
        'BB1C2CAA1B4A341CCBFB370A85BB2EEF03C3A64562A862B84C5C4141F2056E71');
    passed(2) = strcmpi(sha256_file(correction.source_document), ...
        correction.source_document_sha256);
    passed(3) = height(development) == 550;
    passed(4) = ~any(development.sealed) && ...
        ~any(development.split == "sealed_test");
    passed(5) = isequal([nnz(development.split == "train"), ...
        nnz(development.split == "calibration"), ...
        nnz(development.split == "development_validation")], ...
        [300, 100, 150]);
    passed(6) = min(development.seed) == 2800001 && ...
        max(development.seed) == 3300075 && all(development.seed < 3400001);
    passed(7) = numel(unique(development.geometry_id)) == 550;

    source_filter = stage5h_drag_filter_config('joint_c060_d035');
    source_tracking = struct('state', zeros(16, 1), ...
        'covariance', eye(16), 'diagnostics', struct('mean_nis12', 1), ...
        'measurement_available', [true; false]);
    message = struct('spacecraft_mass_kg', 500, ...
        'collision_probability', 2e-4);
    weather = struct('f107_average', 150, 'f107_daily', 155, ...
        'magnetic_index', ones(7, 1), 'local_solar_time_h', 12);
    epoch = datetime(2026, 8, 29, 0, 0, 0, 'TimeZone', 'UTC');
    decision = build_stage6b1_decision_context(message, source_tracking, ...
        source_filter, epoch, weather);
    passed(8) = isfield(source_filter, 'measurement_model_label');
    passed(9) = ~isfield(decision.filter, 'measurement_model_label');
    passed(10) = decision.filter.state_dimension == ...
        source_filter.state_dimension && ...
        decision.filter.state_propagation_rel_tol == ...
        source_filter.state_propagation_rel_tol && ...
        decision.filter.state_propagation_abs_tol == ...
        source_filter.state_propagation_abs_tol;
    poisoned = decision;
    poisoned.filter.future_state = zeros(16, 1);
    passed(11) = throws_boundary(@() ...
        validate_stage6b1_decision_context(poisoned));
    gate_c_checks = test_stage6b1_gate_c();
    passed(12) = height(gate_c_checks) == 18 && all(gate_c_checks.passed);

    rng(6310, 'twister');
    X = randn(80, design.features.count);
    X(1:40, 1) = X(1:40, 1) + 3;
    X(41:80, 1) = X(41:80, 1) - 3;
    direction = [repmat("prograde", 40, 1); ...
        repmat("retrograde", 40, 1)];
    magnitude = logspace(-3, -1, 80)';
    config = design.model;
    config.minimum_magnitude_mps = ...
        design.calibration.lower_magnitude_mps;
    config.maximum_magnitude_mps = ...
        design.calibration.upper_magnitude_mps;
    model = train_stage6b1_surrogate(X, direction, magnitude, config);
    passed(13) = model.training_rows == 80 && model.feature_count == 42;
    passed(14) = isequal(model.direction_classes, ...
        ["prograde", "retrograde"]);
    proposal = propose_stage6b1_action(model, X(1, :));
    passed(15) = any(proposal.direction == ...
        ["prograde", "retrograde"]) && isfinite(proposal.magnitude_mps);
    passed(16) = proposal.magnitude_mps >= ...
        design.calibration.lower_magnitude_mps && ...
        proposal.magnitude_mps <= ...
        design.calibration.upper_magnitude_mps;
    production_result = fullfile(project_root, 'outputs', ...
        'stage_6b1_development_pipeline_v2', ...
        'stage_6b1_development_results.mat');
    passed(17) = ~isfile(production_result);
    detail(17) = "Preflight fits synthetic arrays only and opens no seed.";
    checks = table(names, passed, detail, ...
        'VariableNames', {'check_name', 'passed', 'detail'});
end

function tf = throws_boundary(callback)
    tf = false;
    try
        callback();
    catch ME
        tf = strcmp(ME.identifier, 'ACAM:Stage6b1InformationBoundary');
    end
end

function digest = sha256_file(path)
    algorithm = System.Security.Cryptography.SHA256.Create();
    stream = System.IO.File.OpenRead(char(path));
    cleanup = onCleanup(@() stream.Close());
    bytes = uint8(algorithm.ComputeHash(stream));
    digest = upper(reshape(dec2hex(bytes, 2).', 1, []));
    assert(~isempty(cleanup));
end
