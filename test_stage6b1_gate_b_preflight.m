function test_stage6b1_gate_b_preflight()
%TEST_STAGE6B1_GATE_B_PREFLIGHT Artifact-free source and fixture smoke test.

    root = fileparts(mfilename('fullpath'));
    setup_project;
    contract = stage6b1_gate_b_contract(root);
    assert(strcmpi(file_sha256(contract.source_document), ...
        contract.source_document_sha256), ...
        'Gate B contract hash changed after freezing.');

    fixture_path = fullfile(root, 'outputs', ...
        'stage_6b0_development_ml_pipeline_pilot_v1', ...
        'stage_6b0_progress.mat');
    fixture = load(fixture_path, 'state');
    fixture_index = find(fixture.state.done, 1);
    assert(~isempty(fixture_index), 'No completed Stage 6b0 fixture exists.');
    contexts = fixture.state.records{fixture_index}.contexts;
    context = contexts(strcmp(string({contexts.arm}), 'primary_drag'));
    context = context(1);
    c = load_constants();
    c = c2_scenario_constants(c, context.withheld_truth);

    [comparison, details] = evaluate_gate_b_candidate( ...
        context, zeros(3, 1), c);
    assert(details.completed, 'Gate B fixture evaluation did not complete.');
    assert(all(isfinite([comparison.planning_legacy_pc, ...
        comparison.planning_tca_only_pc, comparison.planning_complete_pc, ...
        comparison.truth_legacy_pc, comparison.truth_tca_only_pc, ...
        comparison.truth_complete_pc])), ...
        'Gate B fixture returned nonfinite Pc.');
    assert(numel(details.planning.member_tca_s) == 10, ...
        'Gate B did not retain the frozen ten-member robust envelope.');
    assert(all([details.planning.member_tca_diagnostics. ...
        tca_inside_interval]), 'A robust-member TCA reached a search edge.');
    assert(details.truth_tca_diagnostics.tca_inside_interval, ...
        'The truth TCA reached a search edge.');
    assert(max(abs(details.planning.member_relative_identity_error)) <= ...
        contract.relative_identity_tolerance, ...
        'Planning relative-covariance identity failed.');
    assert(details.truth_relative_covariance_identity_error <= ...
        contract.relative_identity_tolerance, ...
        'Truth relative-covariance identity failed.');
    assert(all(details.planning. ...
        member_cross_covariance_position_fro > 0) && ...
        details.truth_cross_covariance_position_fro > 0, ...
        'Target-debris cross-covariance was lost.');
    assert(max(abs([details.planning.member_tca_diagnostics. ...
        induced_miss_error_m])) <= ...
        contract.tca_induced_miss_error_tolerance_m, ...
        'A planning TCA failed the induced-miss-error tolerance.');
    assert(abs(details.truth_tca_diagnostics.induced_miss_error_m) <= ...
        contract.tca_induced_miss_error_tolerance_m, ...
        'The truth TCA failed the induced-miss-error tolerance.');

    [legacy_evaluator, ~] = build_joint_drag_robust_evaluator( ...
        context.message, context.tracking, context.planning_scenario, ...
        context.filter, c, context.decision_epoch_utc, 'legacy');
    legacy_pc = legacy_evaluator(zeros(3, 1), 0);
    assert(abs(legacy_pc - comparison.planning_legacy_pc) <= ...
        1e-14 * max(1, abs(legacy_pc)), ...
        'Gate B changed the frozen legacy planning evaluator.');
    [canonical_evaluator, canonical_envelope] = ...
        build_joint_drag_robust_evaluator(context.message, ...
            context.tracking, context.planning_scenario, context.filter, ...
            c, context.decision_epoch_utc);
    [canonical_pc, canonical_details] = ...
        canonical_evaluator(zeros(3, 1), 0);
    assert(abs(canonical_pc - comparison.planning_complete_pc) <= ...
        1e-14 * max(1, abs(canonical_pc)), ...
        'Canonical planning did not adopt the complete evaluator.');
    assert(strcmp(canonical_details.evaluation_mode, ...
        'complete_post_burn_tca_joint_covariance') && ...
        contains(canonical_envelope.fidelity, 'full 16-state covariance'), ...
        'Canonical evaluator fidelity metadata is incomplete.');
    assert(abs(canonical_pc - legacy_pc) > ...
        1e-14 * max(1, abs(canonical_pc)), ...
        'Fixture does not distinguish the complete and legacy evaluators.');
    fprintf(['Stage 6b1 Gate B preflight PASS. planning Pc ', ...
        '[%.6g %.6g %.6g], truth Pc [%.6g %.6g %.6g].\n'], ...
        comparison.planning_legacy_pc, comparison.planning_tca_only_pc, ...
        comparison.planning_complete_pc, comparison.truth_legacy_pc, ...
        comparison.truth_tca_only_pc, comparison.truth_complete_pc);
end

function hash = file_sha256(path)
    file = fopen(path, 'rb');
    assert(file >= 0, 'Cannot read %s.', path);
    cleaner = onCleanup(@() fclose(file));
    bytes = fread(file, Inf, '*uint8');
    hasher = System.Security.Cryptography.SHA256.Create();
    hash = upper(sprintf('%02x', uint8(hasher.ComputeHash(bytes))));
end
