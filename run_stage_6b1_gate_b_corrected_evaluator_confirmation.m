        'source_document_sha256', ...
            '957E3F8C723EA6F11BA6BC7F46D793CD7FE78944D79C089B18A2E0194FFFDF55', ...
        'gate_b_result_path', fullfile(project_root, 'outputs', ...
            'stage_6b1_gate_b_maneuver_evaluation_v1', ...
            'stage_6b1_gate_b_results.mat'), ...
