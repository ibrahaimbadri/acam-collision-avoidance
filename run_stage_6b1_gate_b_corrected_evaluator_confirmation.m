function results = ...
        run_stage_6b1_gate_b_corrected_evaluator_confirmation( ...
            output_dir, use_parallel)
%RUN_STAGE_6B1_GATE_B_CORRECTED_EVALUATOR_CONFIRMATION Confirm integration.

    setup_project;
    project_root = fileparts(mfilename('fullpath'));
    contract = confirmation_contract(project_root);
    verify_contract(contract);
    contract.source_hash_manifest = source_hash_manifest(project_root);
    if nargin < 1 || isempty(output_dir)
        output_dir = contract.output_directory;
    end
    if nargin < 2 || isempty(use_parallel)
        use_parallel = true;
    end
    result_path = fullfile(output_dir, ...
        'stage_6b1_gate_b_confirmation_results.mat');
    if isfile(result_path)
        error('ACAM:Stage6b1GateBConfirmationOutputExists', ...
            'Refusing to overwrite completed output %s.', output_dir);
    end
    output_lock = acquire_output_lock(output_dir, mfilename);
    diary(fullfile(output_dir, 'console_log.txt'));
    diary_cleanup = onCleanup(@() diary('off'));

    fixture = load(contract.fixture_path, 'state');
    cases = confirmation_cases(fixture.state, contract);
    checkpoint = fullfile(output_dir, ...
        'stage_6b1_gate_b_confirmation_progress.mat');
    state = struct('contract', contract, ...
        'records', {cell(contract.expected_rows, 1)}, ...
        'done', false(contract.expected_rows, 1));
    if isfile(checkpoint)
        saved = load(checkpoint, 'state');
        assert(isequaln(saved.state.contract, contract), ...
            'Existing confirmation checkpoint has a different contract.');
        state = saved.state;
    end
    if use_parallel && isempty(gcp('nocreate'))
        parpool('Processes', 2);
    end

    c = load_constants();
    timer = tic;
    remaining = find(~state.done);
    fprintf('Corrected-evaluator confirmation: %d fixture rows.\n', ...
        contract.expected_rows);
    if use_parallel && ~isempty(remaining)
        futures = parallel.FevalFuture.empty;
        for k = 1:numel(remaining)
            index = remaining(k);
            futures(k) = parfeval(@evaluate_safe, 1, ...
                cases(index), c, contract);
        end
        for k = 1:numel(futures)
            [future_index, record] = fetchNext(futures);
            index = remaining(future_index);
            state.records{index} = record;
            state.done(index) = true;
            save_checkpoint(checkpoint, state);
            fprintf('  %d/%d rows complete, elapsed %.1f min.\n', ...
                nnz(state.done), contract.expected_rows, toc(timer) / 60);
        end
    else
        for index = remaining(:)'
            state.records{index} = evaluate_safe( ...
                cases(index), c, contract);
            state.done(index) = true;
            save_checkpoint(checkpoint, state);
            fprintf('  %d/%d rows complete, elapsed %.1f min.\n', ...
                nnz(state.done), contract.expected_rows, toc(timer) / 60);
        end
    end

    [rows, failures] = collate(state.records);
    gate = evaluate_gate(rows, failures, state, contract);
    writetable(rows, fullfile(output_dir, ...
        'stage_6b1_gate_b_confirmation_rows.csv'));
    writetable(failures, fullfile(output_dir, ...
        'stage_6b1_gate_b_confirmation_failures.csv'));
    if gate.pass
        verdict = ["CORRECTED EVALUATOR CONFIRMATION PASS: canonical ", ...
            "planning/verifier and truth-audit APIs use the complete ", ...
            "post-burn covariance evaluator. Gate C may proceed."];
    else
        verdict = ["CORRECTED EVALUATOR CONFIRMATION FAIL: integration ", ...
            "must be corrected before Gate C."];
    end
    results = struct('contract', contract, 'gate', gate, 'rows', rows, ...
        'failures', failures, 'gate_c_authorized', gate.pass, ...
        'gate_d_authorized', false, 'ml_training_authorized', false, ...
        'verdict', join(verdict, ''), 'runtime_seconds', toc(timer), ...
        'completed_at', datetime('now'));
    save(result_path, 'results', '-v7.3');
    digest = sha256_file(result_path);
    write_text([result_path, '.sha256'], sprintf('%s\n', digest));
    write_result(output_dir, results, digest);
    fprintf('\n%s\n', results.verdict);
    assert(~isempty(output_lock) && ~isempty(diary_cleanup));
end

