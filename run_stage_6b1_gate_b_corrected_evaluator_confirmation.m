        'geometry_ids', [1, 21], ...
        'arm_labels', {{'primary_drag', 'srp_sensitivity'}}, ...
        'candidate_labels', {{'zero', 'reserved'}}, ...
        'expected_rows', 8, 'relative_identity_tolerance', 1e-10, ...
        'output_directory', fullfile(project_root, 'outputs', ...
