function verify_contract(contract)
    assert(strcmpi(sha256_file(contract.source_document), ...
        contract.source_document_sha256), ...
        'Confirmation contract changed after freezing.');
    assert(strcmpi(sha256_file(contract.gate_b_result_path), ...
        contract.gate_b_result_sha256), 'Gate B result artifact changed.');
    assert(strcmpi(sha256_file(contract.fixture_path), ...
        contract.fixture_sha256), 'Confirmation fixture changed.');
end

function cases = confirmation_cases(fixture, contract)
    case_cells = cell(contract.expected_rows, 1);
    row = 0;
    for geometry_id = contract.geometry_ids
        record_index = find(cellfun(@(item) ...
            item.geometry_id == geometry_id, fixture.records), 1);
        assert(~isempty(record_index) && fixture.done(record_index), ...
            'Required fixture geometry is unavailable.');
        contexts = fixture.records{record_index}.contexts;
        for arm_index = 1:numel(contract.arm_labels)
            context_index = find(strcmp(string({contexts.arm}), ...
                contract.arm_labels{arm_index}), 1);
            assert(~isempty(context_index), ...
                'Required fixture arm is unavailable.');
            context = contexts(context_index);
            vectors = {zeros(3, 1), context.reserved_dv_hill};
            for candidate_index = 1:numel(contract.candidate_labels)
                row = row + 1;
                case_cells{row} = struct('context', context, ...
                    'candidate', string( ...
                        contract.candidate_labels{candidate_index}), ...
                    'dV_hill', vectors{candidate_index});
            end
        end
    end
    cases = vertcat(case_cells{:});
end

function record = evaluate_safe(item, c, contract)
    try
        context = item.context;
        c_local = c2_scenario_constants(c, context.withheld_truth);
        magnitude = norm(item.dV_hill);
        if magnitude == 0
            direction = zeros(3, 1);
        else
            direction = item.dV_hill / magnitude;
        end
        [evaluator, envelope] = build_joint_drag_robust_evaluator( ...
            context.message, context.tracking, ...
            context.planning_scenario, context.filter, c_local, ...
            context.decision_epoch_utc);
        [planning_pc, planning] = evaluator(direction, magnitude);
        [~, ~, truth_pc, truth] = evaluate_joint_drag_truth_candidate( ...
            context, item.dV_hill, c_local);
        relative_spd = true;
        for k = 1:size(planning.member_relative_covariance_eci, 3)
            [~, status] = chol((planning.member_relative_covariance_eci( ...
                :, :, k) + planning.member_relative_covariance_eci( ...
                :, :, k)') / 2);
            relative_spd = relative_spd && status == 0;
        end
        [~, truth_relative_status] = chol((truth.relative_covariance_eci + ...
            truth.relative_covariance_eci') / 2);
        [~, truth_joint_status] = chol((truth.joint_covariance + ...
            truth.joint_covariance') / 2);
        row = struct( ...
            'geometry_id', context.geometry_id, 'seed', context.seed, ...
            'family', string(context.family), 'arm', string(context.arm), ...
            'candidate', item.candidate, 'dv_magnitude_mps', magnitude, ...
            'planning_pc', planning_pc, 'truth_pc', truth_pc, ...
            'planning_completed', planning.completed, ...
            'truth_completed', truth.completed, ...
            'complete_mode', strcmp(planning.evaluation_mode, ...
                'complete_post_burn_tca_joint_covariance'), ...
            'legacy_comparison_disabled', ~envelope.compare_legacy, ...
            'member_count', numel(planning.member_pc), ...
            'planning_pc_identity_error', abs(planning_pc - ...
                max(planning.member_complete_pc)), ...
            'planning_tca_inside', all([planning. ...
                member_tca_diagnostics.tca_inside_interval]), ...
            'truth_tca_inside', truth.truth_tca_diagnostics. ...
                tca_inside_interval, ...
            'relative_covariances_spd', relative_spd && ...
                truth_relative_status == 0, ...
            'truth_joint_covariance_spd', truth_joint_status == 0, ...
            'maximum_identity_error', max([planning. ...
                member_relative_identity_error; ...
                truth.relative_covariance_identity_error]), ...
            'minimum_cross_covariance_fro', min([planning. ...
                member_cross_covariance_position_fro; ...
                truth.cross_covariance_position_fro]), ...
            'action_limit_pass', magnitude <= ...
                c_local.max_maneuver_mps * (1 + 1e-12), ...
            'contract_identity_tolerance', ...
                contract.relative_identity_tolerance);
        record = struct('status', "complete", 'row', row, ...
            'planning_details', planning, 'truth_details', truth, ...
            'error_id', "", 'error_message', "");
    catch ME
        record = struct('status', "failed", 'row', struct([]), ...
            'planning_details', struct(), 'truth_details', struct(), ...
            'error_id', string(ME.identifier), ...
            'error_message', string(ME.message));
    end
end

function [rows, failures] = collate(records)
    complete = cellfun(@(item) strcmp(item.status, "complete"), records);
    if any(complete)
        selected = records(complete);
        row_cells = cell(numel(selected), 1);
        for k = 1:numel(selected)
            row_cells{k} = selected{k}.row;
        end
        rows = struct2table(vertcat(row_cells{:}));
    else
        rows = table();
    end
    failed = records(~complete);
    if isempty(failed)
        failures = table('Size', [0, 2], ...
            'VariableTypes', {'string', 'string'}, ...
            'VariableNames', {'error_id', 'error_message'});
    else
        error_id = strings(numel(failed), 1);
        error_message = strings(numel(failed), 1);
        for k = 1:numel(failed)
            error_id(k) = failed{k}.error_id;
            error_message(k) = failed{k}.error_message;
        end
        failures = table(error_id, error_message, ...
            'VariableNames', {'error_id', 'error_message'});
    end
end

function gate = evaluate_gate(rows, failures, state, contract)
    count_pass = nnz(state.done) == contract.expected_rows && ...
        height(rows) == contract.expected_rows;
    if isempty(rows)
        invariant_pass = false;
    else
        invariant_pass = all(rows.planning_completed & ...
            rows.truth_completed & rows.complete_mode & ...
            rows.legacy_comparison_disabled & rows.member_count == 10 & ...
            rows.planning_pc_identity_error <= 1e-14 & ...
            rows.planning_tca_inside & rows.truth_tca_inside & ...
            rows.relative_covariances_spd & ...
            rows.truth_joint_covariance_spd & ...
            rows.maximum_identity_error <= ...
                contract.relative_identity_tolerance & ...
            rows.minimum_cross_covariance_fro > 0 & ...
            rows.action_limit_pass & isfinite(rows.planning_pc) & ...
            isfinite(rows.truth_pc));
    end
    gate = struct('pass', count_pass && height(failures) == 0 && ...
        invariant_pass, 'observed_rows', height(rows), ...
        'failure_count', height(failures), 'count_pass', count_pass, ...
        'invariant_pass', invariant_pass);
end

function manifest = source_hash_manifest(project_root)
    runner = fullfile(project_root, ...
        'run_stage_6b1_gate_b_corrected_evaluator_confirmation.m');
    files = string(matlab.codetools.requiredFilesAndProducts(runner));
    files = files(:);
    files = unique([files(startsWith(lower(files), ...
        lower(string(project_root)))); string(fullfile(project_root, ...
        'STAGE_6B1_GATE_B_CORRECTED_EVALUATOR_CONFIRMATION_CONTRACT.md'))]);
    files = sort(files);
    relative_path = strings(numel(files), 1);
    sha256 = strings(numel(files), 1);
    for k = 1:numel(files)
        relative_path(k) = erase(files(k), string(project_root) + filesep);
        sha256(k) = sha256_file(files(k));
    end
    manifest = table(relative_path, sha256);
end

function save_checkpoint(path, state)
    temporary = [path, '.partial'];
    save(temporary, 'state', '-v7.3');
    movefile(temporary, path, 'f');
end

function digest = sha256_file(path)
    algorithm = System.Security.Cryptography.SHA256.Create();
    stream = System.IO.File.OpenRead(char(path));
    cleanup = onCleanup(@() stream.Close());
    bytes = uint8(algorithm.ComputeHash(stream));
    digest = upper(reshape(dec2hex(bytes, 2).', 1, []));
    assert(~isempty(cleanup));
end

function write_text(path, content)
    file = fopen(path, 'w');
    assert(file >= 0, 'Could not write confirmation output.');
    cleanup = onCleanup(@() fclose(file));
    fprintf(file, '%s', content);
    assert(~isempty(cleanup));
end

function write_result(output_dir, results, digest)
    path = fullfile(output_dir, 'RESULT.md');
    content = sprintf([ ...
        '# Stage 6b1 Gate B corrected-evaluator confirmation\n\n', ...
        '**%s**\n\n', ...
        '- Rows: %d / %d\n', ...
        '- Execution failures: %d\n', ...
        '- Gate pass: %d\n', ...
        '- Gate C authorized: %d\n', ...
        '- ML training authorized: 0\n', ...
        '- Result MAT SHA-256: `%s`\n'], ...
        results.verdict, results.gate.observed_rows, ...
        results.contract.expected_rows, results.gate.failure_count, ...
        results.gate.pass, results.gate_c_authorized, digest);
    write_text(path, content);
end
