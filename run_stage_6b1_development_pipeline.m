    inherited = stage6a_contract(project_root);
    generation = struct('version', 1, ...
        'scenario_config', inherited.scenario_config, ...
        'fixed_candidate', inherited.fixed_candidate, ...
        'arms', inherited.arms, 'lead_s', inherited.lead_s, ...
        'measurement_seed_offset', inherited.measurement_seed_offset, ...
        'density_residual_seed_offset', ...
            inherited.density_residual_seed_offset, ...
        'physical_stratum', inherited.physical_stratum, ...
        'marginal_sigma_log', inherited.marginal_sigma_log, ...
        'object_correlation', inherited.object_correlation, ...
        'correlation_time_s', inherited.correlation_time_s, ...
        'bias_log', inherited.bias_log, ...
        'relative_identity_tolerance', inherited.relative_identity_tolerance, ...
        'reserve_factor', design.policy.reserve_factor);
    assert(strcmp(generation.fixed_candidate, 'joint_c060_d035') && ...
        strcmp(generation.physical_stratum, 'differential_4x') && ...
        generation.lead_s == 3 * 3600 && ...
        isequal(string({generation.arms.name}), design.arms), ...
        'Inherited scientific generation settings changed.');
end

function launch = verify_or_create_launch(output_dir, design, correction, ...
        generation, source_manifest, environment)
    launch_path = fullfile(output_dir, 'stage_6b1_development_launch.mat');
    if isfile(launch_path)
        saved = load(launch_path, 'launch');
        launch = saved.launch;
        assert(isequaln(launch.design, design) && ...
            isequaln(launch.correction, correction) && ...
            isequaln(launch.generation, generation) && ...
            isequaln(launch.source_hash_manifest, source_manifest) && ...
            isequaln(launch.environment, environment), ...
            'Launch contract or source hashes changed; resume refused.');
        return;
    end
    launch = struct('version', 2, 'design', design, ...
        'correction', correction, 'generation', generation, ...
        'source_hash_manifest', source_manifest, ...
        'environment', environment, 'sealed_geometry_count_opened', 0, ...
        'created_at', datetime('now', 'TimeZone', 'Europe/Berlin'));
    save(launch_path, 'launch', '-v7.3');
    write_hash_sidecar(launch_path, sha256_file(launch_path));
    writetable(source_manifest, fullfile(output_dir, ...
        'stage_6b1_development_source_hashes.csv'));
    writetable(environment.products, fullfile(output_dir, ...
        'stage_6b1_development_matlab_products.csv'));
end

function records = run_generation(cases, generation, c, checkpoint_dir, ...
        output_dir, use_parallel, timer)
    count = numel(cases);
    records = cell(count, 1);
    done = false(count, 1);
    for index = 1:count
        path = checkpoint_path(checkpoint_dir, index, cases(index).seed);
        if isfile(path)
            saved = load(path, 'record', 'item');
            assert(saved.item.seed == cases(index).seed && ...
                string(saved.item.geometry_id) == ...
                string(cases(index).geometry_id), ...
                'Generation checkpoint case identity changed.');
            records{index} = saved.record;
            done(index) = true;
        end
    end
    remaining = find(~done);
    session_start = numel(remaining);
    if use_parallel && ~isempty(remaining)
        futures = parallel.FevalFuture.empty;
        for k = 1:numel(remaining)
            index = remaining(k);
            futures(k) = parfeval( ...
                @generate_stage6b1_development_geometry, 1, ...
                cases(index), generation, c);
        end
        for k = 1:numel(futures)
            [future_index, record] = fetchNext(futures);
            index = remaining(future_index);
            records{index} = record;
            done(index) = true;
            save_record(checkpoint_path(checkpoint_dir, index, ...
                cases(index).seed), record, cases(index));
            fail_if_incomplete(record, futures);
            print_progress('generation', done, session_start, timer, ...
                output_dir);
        end
    else
        for index = remaining(:)'
            record = generate_stage6b1_development_geometry( ...
                cases(index), generation, c);
            records{index} = record;
            done(index) = true;
            save_record(checkpoint_path(checkpoint_dir, index, ...
                cases(index).seed), record, cases(index));
            fail_if_incomplete(record, parallel.FevalFuture.empty);
            print_progress('generation', done, session_start, timer, ...
                output_dir);
        end
    end
end

function records = run_evaluation(indices, cases, generation_records, ...
        model, c, checkpoint_dir, use_parallel, timer)
    count = numel(indices);
    records = cell(count, 1);
    done = false(count, 1);
    for position = 1:count
        index = indices(position);
        path = checkpoint_path(checkpoint_dir, position, cases(index).seed);
        if isfile(path)
            saved = load(path, 'record', 'item');
            assert(saved.item.seed == cases(index).seed, ...
                'Evaluation checkpoint case identity changed.');
            records{position} = saved.record;
            done(position) = true;
        end
    end
    remaining = find(~done);
    session_start = numel(remaining);
    if use_parallel && ~isempty(remaining)
        futures = parallel.FevalFuture.empty;
        for k = 1:numel(remaining)
            position = remaining(k);
            index = indices(position);
            futures(k) = parfeval( ...
                @evaluate_stage6b1_development_geometry, 1, ...
                generation_records{index}.contexts, model, c, position);
        end
        for k = 1:numel(futures)
            [future_index, record] = fetchNext(futures);
            position = remaining(future_index);
            index = indices(position);
            records{position} = record;
            done(position) = true;
            save_record(checkpoint_path(checkpoint_dir, position, ...
                cases(index).seed), record, cases(index));
            fail_if_incomplete(record, futures);
            print_progress('evaluation', done, session_start, timer, ...
                fileparts(checkpoint_dir));
        end
    else
        for position = remaining(:)'
            index = indices(position);
            record = evaluate_stage6b1_development_geometry( ...
                generation_records{index}.contexts, model, c, position);
            records{position} = record;
            done(position) = true;
            save_record(checkpoint_path(checkpoint_dir, position, ...
                cases(index).seed), record, cases(index));
            fail_if_incomplete(record, parallel.FevalFuture.empty);
            print_progress('evaluation', done, session_start, timer, ...
                fileparts(checkpoint_dir));
        end
    end
end

function [rows, contexts, failures] = collate_generation(records)
    complete = cellfun(@(item) item.status == "complete", records);
    if any(complete)
        row_cells = cellfun(@(item) item.rows, records(complete), ...
            'UniformOutput', false);
        context_cells = cellfun(@(item) item.contexts, records(complete), ...
            'UniformOutput', false);
        rows = struct2table(vertcat(row_cells{:}));
        contexts = vertcat(context_cells{:});
    else
        rows = table();
        contexts = struct([]);
    end
    failures = failure_table(records, complete);
end

function [rows, failures] = collate_evaluation(records)
    complete = cellfun(@(item) item.status == "complete", records);
    if any(complete)
        row_cells = cellfun(@(item) item.rows, records(complete), ...
            'UniformOutput', false);
        rows = struct2table(vertcat(row_cells{:}));
    else
        rows = table();
    end
    failures = failure_table(records, complete);
end

function failures = failure_table(records, complete)
    failed = records(~complete);
    if isempty(failed)
        failures = table('Size', [0, 4], 'VariableTypes', ...
            {'string', 'double', 'string', 'string'}, ...
            'VariableNames', {'geometry_id', 'seed', 'error_id', ...
            'error_message'});
        return;
    end
    geometry_id = strings(numel(failed), 1);
    seed = nan(numel(failed), 1);
    error_id = strings(numel(failed), 1);
    error_message = strings(numel(failed), 1);
    for k = 1:numel(failed)
        geometry_id(k) = failed{k}.geometry_id;
        if isfield(failed{k}, 'seed')
            seed(k) = failed{k}.seed;
        end
        error_id(k) = failed{k}.error_id;
        error_message(k) = failed{k}.error_message;
    end
    failures = table(geometry_id, seed, error_id, error_message);
end

function gate = generation_gate(rows, failures, design)
    if isempty(rows)
        gate = struct('pass', false, 'observed_rows', 0, ...
            'failure_count', height(failures));
        return;
    end
    complete = isempty(failures) && height(rows) == 1100 && ...
        numel(unique(rows.geometry_id)) == 550 && ...
        ~any(rows.split == "sealed_test");
    invariants = complete && all(rows.covariance_invariants_pass) && ...
        all(rows.target_information_set_pass) && ...
        all(rows.complete_evaluator_pass) && ...
        all(rows.target_direction_supported) && ...
        all(rows.target_vector_valid) && ...
        all(rows.model_features_finite) && ...
        all(rows.model_feature_count == design.features.count) && ...
        all(rows.feature_schema_version == design.features.schema_version);
    split_counts = [nnz(rows.split == "train"), ...
        nnz(rows.split == "calibration"), ...
        nnz(rows.split == "development_validation")];
    split_pass = isequal(split_counts, [600, 200, 300]);
    isolation = true;
    try
        validate_stage6b1_split_isolation(rows(:, ...
            {'geometry_id', 'arm', 'split', 'fit_eligible'}));
    catch
        isolation = false;
    end
    retained = all(~rows.triggered | rows.target_available | ...
        rows.fallback_required) && all(rows.triggered | ...
        rows.target_status == "stay");
    direction_counts = zeros(3, 2);
    split_labels = ["train", "calibration", "development_validation"];
    minimum_counts = [design.composition.training_minimum_per_direction, ...
        design.composition.calibration_minimum_per_direction, ...
        design.composition.development_minimum_per_direction];
    support = true;
    for split_index = 1:3
        for direction_index = 1:2
            selected = rows.split == split_labels(split_index) & ...
                rows.arm == "primary_drag" & rows.target_available & ...
                rows.target_direction == ...
                design.model.direction_classes(direction_index);
            direction_counts(split_index, direction_index) = nnz(selected);
            support = support && ...
                direction_counts(split_index, direction_index) >= ...
                minimum_counts(split_index);
        end
    end
    availability = nan(3, 2);
    availability_pass = true;
    for split_index = 1:3
        for arm_index = 1:2
            selected = rows.split == split_labels(split_index) & ...
                rows.arm == design.arms(arm_index) & rows.triggered;
            availability(split_index, arm_index) = ...
                nnz(selected & rows.target_available) / max(nnz(selected), 1);
            availability_pass = availability_pass && ...
                availability(split_index, arm_index) >= ...
                design.composition.minimum_target_availability;
        end
    end
    pass = complete && invariants && split_pass && isolation && ...
        retained && support && availability_pass;
    gate = struct('pass', pass, 'complete_pass', complete, ...
        'invariants_pass', invariants, 'split_count_pass', split_pass, ...
        'split_isolation_pass', isolation, ...
        'fallback_required_retained_pass', retained, ...
        'direction_support_pass', support, ...
        'target_availability_pass', availability_pass, ...
        'observed_rows', height(rows), 'failure_count', height(failures), ...
        'split_counts', split_counts, 'direction_counts', direction_counts, ...
        'target_availability', availability);
end

function X = feature_matrix(rows, names)
    X = zeros(height(rows), numel(names));
    for k = 1:numel(names)
        X(:, k) = rows.(['feature_', names{k}]);
    end
    assert(all(isfinite(X), 'all'), 'Stage 6b1 feature matrix is invalid.');
end

function [gate, summary] = development_gate(rows, failures, design)
    arms = design.arms(:);
    arm = strings(numel(arms), 1);
    observed_rows = zeros(numel(arms), 1);
    invariant_pass = false(numel(arms), 1);
    triggered_rows = zeros(numel(arms), 1);
    target_availability = nan(numel(arms), 1);
    raw_verifier_pass_rate = nan(numel(arms), 1);
    fallback_rate = nan(numel(arms), 1);
    no_solution_count = zeros(numel(arms), 1);
    policy_unsafe_count = zeros(numel(arms), 1);
    numerical_unsafe_count = zeros(numel(arms), 1);
    excess_failure_count = zeros(numel(arms), 1);
    policy_unsafe_upper = nan(numel(arms), 1);
    numerical_unsafe_upper = nan(numel(arms), 1);
    excess_failure_upper = nan(numel(arms), 1);
    median_runtime_ratio = nan(numel(arms), 1);
    mean_runtime_ratio = nan(numel(arms), 1);
    safety_pass = false(numel(arms), 1);
    composition_pass = false(numel(arms), 1);
    runtime_pass = false(numel(arms), 1);
    arm_pass = false(numel(arms), 1);
    for k = 1:numel(arms)
        arm(k) = arms(k);
        selected = rows.arm == arms(k);
        part = rows(selected, :);
        observed_rows(k) = height(part);
        invariant_pass(k) = height(part) == design.safety.development_n && ...
            all(part.feature_identity_error <= 1e-12) && ...
            all(part.trigger_invariant_pass) && all(part.action_limit_pass) && ...
            all(isfinite(part.policy_runtime_s) & part.policy_runtime_s > 0) && ...
            all(isfinite(part.numerical_runtime_s) & ...
                part.numerical_runtime_s > 0);
        triggered = part.triggered;
        triggered_rows(k) = nnz(triggered);
        target_availability(k) = nnz(triggered & part.target_available) / ...
            max(triggered_rows(k), 1);
        raw_verifier_pass_rate(k) = nnz(triggered & ...
            part.policy_raw_proposal_verified) / max(triggered_rows(k), 1);
        fallback_rate(k) = nnz(triggered & part.policy_fallback_used) / ...
            max(triggered_rows(k), 1);
        no_solution_count(k) = nnz(part.policy_no_solution);
        policy_unsafe_count(k) = nnz(part.policy_unsafe);
        numerical_unsafe_count(k) = nnz(part.numerical_unsafe);
        excess_failure_count(k) = nnz(part.paired_excess_failure);
        policy_unsafe_upper(k) = cp_upper(policy_unsafe_count(k), ...
            height(part), design.safety.one_sided_alpha);
        numerical_unsafe_upper(k) = cp_upper(numerical_unsafe_count(k), ...
            height(part), design.safety.one_sided_alpha);
        excess_failure_upper(k) = cp_upper(excess_failure_count(k), ...
            height(part), design.safety.one_sided_alpha);
        safety_pass(k) = policy_unsafe_upper(k) <= design.safety.margin && ...
            numerical_unsafe_upper(k) <= design.safety.margin && ...
            excess_failure_upper(k) <= design.safety.margin;
        composition_pass(k) = target_availability(k) >= ...
            design.composition.minimum_target_availability && ...
            raw_verifier_pass_rate(k) >= ...
            design.composition.minimum_raw_verifier_pass_rate && ...
            fallback_rate(k) <= design.composition.maximum_fallback_rate && ...
            no_solution_count(k) <= ...
            design.composition.maximum_no_solution_count;
        timed = triggered & isfinite(part.runtime_ratio);
        if any(timed)
            median_runtime_ratio(k) = median(part.runtime_ratio(timed));
            mean_runtime_ratio(k) = mean(part.runtime_ratio(timed));
        end
        runtime_pass(k) = nnz(timed) >= ...
            design.composition.minimum_development_timing_pairs && ...
            median_runtime_ratio(k) <= ...
            design.runtime.maximum_median_paired_ratio && ...
            mean_runtime_ratio(k) <= ...
            design.runtime.maximum_mean_paired_ratio;
        arm_pass(k) = invariant_pass(k) && safety_pass(k) && ...
            composition_pass(k) && runtime_pass(k);
    end
    summary = table(arm, observed_rows, invariant_pass, triggered_rows, ...
        target_availability, raw_verifier_pass_rate, fallback_rate, ...
        no_solution_count, policy_unsafe_count, numerical_unsafe_count, ...
        excess_failure_count, policy_unsafe_upper, numerical_unsafe_upper, ...
        excess_failure_upper, median_runtime_ratio, mean_runtime_ratio, ...
        safety_pass, composition_pass, runtime_pass, arm_pass);
    gate = struct('pass', isempty(failures) && height(rows) == 300 && ...
        all(arm_pass), 'failure_count', height(failures), ...
        'observed_rows', height(rows), 'all_arms_pass', all(arm_pass));
end

function summary = delta_v_analysis(rows, arm_summary, design)
    arms = design.arms(:);
    arm = arms;
    analyzed = false(numel(arms), 1);
    mean_difference_mps = nan(numel(arms), 1);
    median_difference_mps = nan(numel(arms), 1);
    lower_95_mps = nan(numel(arms), 1);
    upper_95_mps = nan(numel(arms), 1);
    fuel_saving_supported = false(numel(arms), 1);
    rng(design.delta_v.bootstrap_seed, 'twister');
    for k = 1:numel(arms)
        if ~arm_summary.safety_pass(k)
            continue;
        end
        selected = rows.arm == arms(k);
        difference = rows.policy_dv_magnitude_mps(selected) - ...
            rows.numerical_dv_magnitude_mps(selected);
        analyzed(k) = true;
        mean_difference_mps(k) = mean(difference);
        median_difference_mps(k) = median(difference);
        bootstrap = zeros(design.delta_v.bootstrap_replicates, 1);
        n = numel(difference);
        for replicate = 1:design.delta_v.bootstrap_replicates
            bootstrap(replicate) = mean(difference(randi(n, n, 1)));
        end
        interval = prctile(bootstrap, [2.5, 95]);
        lower_95_mps(k) = interval(1);
        upper_95_mps(k) = interval(2);
        fuel_saving_supported(k) = upper_95_mps(k) < 0;
    end
    summary = table(arm, analyzed, mean_difference_mps, ...
        median_difference_mps, lower_95_mps, upper_95_mps, ...
        fuel_saving_supported);
end

