function results = run_stage_6b1_development_pipeline(output_dir, use_parallel)
%RUN_STAGE_6B1_DEVELOPMENT_PIPELINE Run the frozen 550-geometry phase.

    setup_project;
    project_root = fileparts(mfilename('fullpath'));
    gate_d_design = stage6b1_gate_d_contract(project_root);
    verify_gate_d(project_root, gate_d_design);
    [design, correction] = ...
        stage6b1_development_correction_contract(project_root);
    verify_correction(correction);
    generation = generation_config(project_root, design);
    cases = table2struct(design.geometry_plan( ...
        ~design.geometry_plan.sealed, :));
    assert(numel(cases) == 550 && ...
        ~any([cases.sealed]) && all([cases.seed] < 3400001) && ...
        min([cases.seed]) == 2800001, ...
        'The sealed Gate D block must remain inaccessible.');
    if nargin < 1 || isempty(output_dir)
        output_dir = fullfile(project_root, 'outputs', ...
            'stage_6b1_development_pipeline_v2');
    end
    if nargin < 2 || isempty(use_parallel)
        use_parallel = true;
    end
    result_path = fullfile(output_dir, 'stage_6b1_development_results.mat');
    if isfile(result_path)
        error('ACAM:Stage6b1DevelopmentOutputExists', ...
            'Refusing to overwrite completed output %s.', output_dir);
    end

    output_lock = acquire_output_lock(output_dir, mfilename);
    diary(fullfile(output_dir, 'console_log.txt'));
    diary_cleanup = onCleanup(@() diary('off'));
    source_manifest = source_hash_manifest(project_root, design, correction);
    environment = environment_manifest(design.runtime.maximum_local_workers);
    launch = verify_or_create_launch(output_dir, design, correction, ...
        generation, source_manifest, environment);
    assert(isequaln(launch.source_hash_manifest, source_manifest), ...
        'The production source manifest changed after launch.');

    if use_parallel && isempty(gcp('nocreate'))
        parpool('Processes', design.runtime.maximum_local_workers);
    end
    c = load_constants();
    generation_dir = fullfile(output_dir, 'generation_checkpoints');
    if ~isfolder(generation_dir)
        mkdir(generation_dir);
    end
    timer = tic;
    fprintf(['Stage 6b1 development: 550 independent geometries; ', ...
        'sealed cases excluded.\n']);
    generation_records = run_generation(cases, generation, c, ...
        generation_dir, output_dir, use_parallel, timer);
    [rows, contexts, failures] = collate_generation(generation_records);
    data_gate = generation_gate(rows, failures, design);
    writetable(rows, fullfile(output_dir, 'stage_6b1_development_rows.csv'));
    writetable(failures, fullfile(output_dir, ...
        'stage_6b1_development_generation_failures.csv'));
    dataset_path = fullfile(output_dir, ...
        'stage_6b1_development_dataset.mat');
    dataset = struct('version', 1, 'design', design, 'rows', rows, ...
        'contexts', contexts, 'information_boundary', ...
        'stage6b1_decision_context_v1');
    if isfile(dataset_path)
        verify_hash_sidecar(dataset_path);
    else
        save(dataset_path, 'dataset', '-v7.3');
        write_hash_sidecar(dataset_path, sha256_file(dataset_path));
    end

    if ~data_gate.pass
        results = finish_without_model(output_dir, result_path, design, ...
            source_manifest, environment, data_gate, failures, timer);
        assert(~isempty(output_lock) && ~isempty(diary_cleanup));
        return;
    end

    model_path = fullfile(output_dir, ...
        'stage_6b1_development_candidate_model.mat');
    if isfile(model_path)
        model_sha256 = verify_hash_sidecar(model_path);
        saved_model = load(model_path, 'model', 'design');
        assert(isequaln(saved_model.design, design), ...
            'The saved candidate model has a different Gate D design.');
        model = saved_model.model;
    else
        [feature_names, ~] = truth_audited_feature_schema();
        X = feature_matrix(rows, feature_names);
        training = rows.fit_eligible & rows.target_available;
        model_config = design.model;
        model_config.minimum_magnitude_mps = ...
            design.calibration.lower_magnitude_mps;
        model_config.maximum_magnitude_mps = ...
            design.calibration.upper_magnitude_mps;
        model = train_stage6b1_surrogate(X(training, :), ...
            rows.target_direction(training), ...
            rows.target_magnitude_mps(training), model_config);
        calibration = rows.calibration_eligible & rows.target_available;
        predicted_log = predict(model.magnitude_regressor, X(calibration, :));
        observed_log = log10(rows.target_magnitude_mps(calibration));
        model.calibration_log10_correction = ...
            median(observed_log - predicted_log);
        model.calibration_rows = nnz(calibration);
        model.feature_names = string(feature_names);
        model.source_hash_manifest = source_manifest;
        model.dataset_sha256 = verify_hash_sidecar(dataset_path);
        training_geometry_ids = unique(rows.geometry_id(training));
        calibration_geometry_ids = unique(rows.geometry_id(calibration));
        save(model_path, 'model', 'training_geometry_ids', ...
            'calibration_geometry_ids', 'design', '-v7.3');
        model_sha256 = sha256_file(model_path);
        write_hash_sidecar(model_path, model_sha256);
    end
    verify_or_create_evaluation_lock(output_dir, dataset_path, ...
        model_path, source_manifest);

    development_indices = find(string({cases.split}) == ...
        "development_validation");
    evaluation_dir = fullfile(output_dir, 'evaluation_checkpoints');
    if ~isfolder(evaluation_dir)
        mkdir(evaluation_dir);
    end
    evaluation_records = run_evaluation(development_indices, cases, ...
        generation_records, model, c, evaluation_dir, use_parallel, timer);
    [evaluation_rows, evaluation_failures] = ...
        collate_evaluation(evaluation_records);
    [advancement_gate, arm_summary] = development_gate( ...
        evaluation_rows, evaluation_failures, design);
    delta_v_summary = delta_v_analysis( ...
        evaluation_rows, arm_summary, design);
    writetable(evaluation_rows, fullfile(output_dir, ...
        'stage_6b1_development_policy_rows.csv'));
    writetable(evaluation_failures, fullfile(output_dir, ...
        'stage_6b1_development_evaluation_failures.csv'));
    writetable(arm_summary, fullfile(output_dir, ...
        'stage_6b1_development_arm_summary.csv'));
    writetable(delta_v_summary, fullfile(output_dir, ...
        'stage_6b1_development_delta_v_summary.csv'));

    if advancement_gate.pass
        verdict = ["STAGE 6B1 DEVELOPMENT PASS: all primary and SRP-arm ", ...
            "safety, composition, verifier/fallback, and runtime gates ", ...
            "passed. The policy is ready for separate lock verification; ", ...
            "the sealed test remains closed."];
    else
        verdict = ["STAGE 6B1 DEVELOPMENT FAIL: at least one frozen ", ...
            "development gate failed. The sealed test remains closed."];
    end
    results = struct('version', 1, 'design', design, ...
        'source_hash_manifest', source_manifest, 'environment', environment, ...
        'data_gate', data_gate, 'advancement_gate', advancement_gate, ...
        'arm_summary', arm_summary, 'delta_v_summary', delta_v_summary, ...
        'generation_failures', failures, ...
        'evaluation_failures', evaluation_failures, ...
        'model_path', string(model_path), 'model_sha256', model_sha256, ...
        'policy_lock_ready', advancement_gate.pass, ...
        'sealed_test_authorized', false, 'sealed_test_opened', false, ...
        'fuel_saving_claim_supported', ...
            delta_v_summary.fuel_saving_supported( ...
            delta_v_summary.arm == "primary_drag"), ...
        'verdict', join(verdict, ''), 'runtime_seconds', toc(timer), ...
        'completed_at', datetime('now', 'TimeZone', 'Europe/Berlin'));
    save(result_path, 'results', '-v7.3');
    result_sha256 = sha256_file(result_path);
    write_hash_sidecar(result_path, result_sha256);
    write_result(output_dir, results, result_sha256);
    fprintf('\n%s\n', results.verdict);
    assert(~isempty(output_lock) && ~isempty(diary_cleanup));
end

function verify_gate_d(project_root, design)
    result_path = fullfile(project_root, 'outputs', ...
        'stage_6b1_gate_d_design_validation_v2', ...
        'stage_6b1_gate_d_results.mat');
    expected = ...
        'BB1C2CAA1B4A341CCBFB370A85BB2EEF03C3A64562A862B84C5C4141F2056E71';
    assert(strcmpi(sha256_file(result_path), expected), ...
        'The valid Gate D result artifact changed.');
    parent = load(result_path, 'results');
    assert(parent.results.gate.pass && ...
        parent.results.development_generation_authorized && ...
        parent.results.ml_training_authorized && ...
        ~parent.results.sealed_test_authorized && ...
        isequaln(parent.results.contract, design), ...
        'Gate D does not authorize this development run.');
end

function verify_correction(correction)
    assert(strcmpi(sha256_file(correction.source_document), ...
        correction.source_document_sha256), ...
        'The implementation-correction document changed after freezing.');
    assert(strcmpi(sha256_file(correction.retired_launch_path), ...
        correction.retired_launch_sha256), ...
        'The retired v1 launch artifact changed.');
    assert(strcmpi(sha256_file(correction.retired_checkpoint_path), ...
        correction.retired_checkpoint_sha256), ...
        'The retired v1 failure checkpoint changed.');
    assert(correction.completed_scientific_geometries_v1 == 0 && ...
        correction.optimizer_targets_generated_v1 == 0 && ...
        correction.models_fitted_v1 == 0 && ...
        correction.sealed_geometries_opened_v1 == 0, ...
        'The v1 correction boundary is no longer valid.');
end

