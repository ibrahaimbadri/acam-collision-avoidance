function print_progress(label, done, session_start, timer, output_dir)
    completed_session = session_start - nnz(~done);
    elapsed = toc(timer);
    rate = completed_session / max(elapsed, eps);
    eta = nnz(~done) / max(rate, eps);
    fprintf(['  %s %d/%d complete (%.1f%%), elapsed %.1f min, ', ...
        'session ETA %.1f min.\n'], label, nnz(done), numel(done), ...
        100 * nnz(done) / numel(done), elapsed / 60, eta / 60);
    if ~isempty(output_dir) && nnz(done) >= ceil(0.10 * numel(done))
        path = fullfile(output_dir, ['stage_6b1_', label, '_eta.txt']);
        if ~isfile(path)
            write_text(path, sprintf([ ...
                'completed=%d\ntotal=%d\nelapsed_seconds=%.9g\n', ...
                'projected_remaining_seconds=%.9g\n'], ...
                nnz(done), numel(done), elapsed, eta));
        end
    end
end

