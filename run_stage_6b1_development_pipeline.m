        cancel(futures);
    end
    error('ACAM:Stage6b1GeometryFailed', ...
        'Geometry %s failed (%s): %s', record.geometry_id, ...
        record.error_id, record.error_message);
end

function verify_or_create_evaluation_lock(output_dir, dataset_path, ...
        model_path, source_manifest)
    path = fullfile(output_dir, 'stage_6b1_evaluation_lock.mat');
    value = struct('dataset_sha256', verify_hash_sidecar(dataset_path), ...
        'model_sha256', verify_hash_sidecar(model_path), ...
        'source_hash_manifest', source_manifest);
    if isfile(path)
        saved = load(path, 'value');
        assert(isequaln(saved.value, value), ...
            'Evaluation inputs changed after the model was fitted.');
        return;
    end
    save(path, 'value', '-v7.3');
    write_hash_sidecar(path, sha256_file(path));
end

function digest = verify_hash_sidecar(path)
    sidecar = [path, '.sha256'];
    assert(isfile(sidecar), 'Missing SHA-256 sidecar for %s.', path);
    digest = upper(strtrim(fileread(sidecar)));
    assert(strcmpi(digest, sha256_file(path)), ...
        'SHA-256 verification failed for %s.', path);
end

function upper = cp_upper(events, trials, alpha)
    if events == trials
        upper = 1;
    elseif events == 0
        upper = 1 - alpha^(1 / trials);
    else
        upper = betaincinv(1 - alpha, events + 1, trials - events);
    end
end

function digest = sha256_file(path)
    algorithm = System.Security.Cryptography.SHA256.Create();
    stream = System.IO.File.OpenRead(char(path));
    cleanup = onCleanup(@() stream.Close());
    bytes = uint8(algorithm.ComputeHash(stream));
    digest = upper(reshape(dec2hex(bytes, 2).', 1, []));
    assert(~isempty(cleanup));
end

function write_hash_sidecar(path, digest)
    write_text([path, '.sha256'], sprintf('%s\n', digest));
end

function write_text(path, content)
    file = fopen(path, 'w');
    assert(file >= 0, 'Could not write Stage 6b1 development artifact.');
    cleanup = onCleanup(@() fclose(file));
    fprintf(file, '%s', content);
    assert(~isempty(cleanup));
end

function write_result(output_dir, results, digest)
    content = sprintf([ ...
        '# Stage 6b1 verified-surrogate development pipeline\n\n', ...
        '**%s**\n\n', ...
        '- Generation rows: %d / 1100\n', ...
        '- Generation failures: %d\n', ...
        '- Data gate pass: %d\n', ...
        '- Policy lock ready: %d\n', ...
        '- Sealed test authorized/opened: 0 / 0\n', ...
        '- Result MAT SHA-256: `%s`\n'], ...
        results.verdict, results.data_gate.observed_rows, ...
        results.data_gate.failure_count, results.data_gate.pass, ...
        results.policy_lock_ready, digest);
    write_text(fullfile(output_dir, 'RESULT.md'), content);
end
