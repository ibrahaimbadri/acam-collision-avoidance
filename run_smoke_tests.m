function run_smoke_tests()
% Fast checks for shared physics and risk modules.

    setup_project();
    c = load_constants();
    orbit_radius = c.Re + 600e3;
    X = [orbit_radius; 0; 0; 0; sqrt(c.mu / orbit_radius); 0];

    dX = twoBodyJ2Drag_simple(0, X, c);
    assert(all(isfinite(dX)), 'Dynamics returned a non-finite state derivative.');

    options = odeset('RelTol', 1e-8, 'AbsTol', 1e-10, ...
                     'Events', @(t, state) earth_collision_event(t, state, c));
    [t_out, X_out] = ode45(@(t, state) twoBodyJ2Drag_simple(t, state, c), ...
                            [0, 3600], X, options);
    assert(abs(t_out(end) - 3600) < 1, 'LEO propagation stopped early.');
    assert(norm(X_out(end, 1:3)) > c.Re, 'LEO propagation reached Earth.');

    Phi = compute_state_transition_jacobian(X, 60, c);
    assert(isequal(size(Phi), [6, 6]) && all(isfinite(Phi(:))), ...
           'State-transition matrix is invalid.');
    [X_variational, Phi_variational] = propagate_state_and_stm(X, 60, c);
    [~, X_direct_60] = ode45(@(t, state) ...
        twoBodyJ2Drag_simple(t, state, c), [0, 60], X, options);
    assert(norm(X_variational - X_direct_60(end, :)') < 1e-3 && ...
           norm(Phi_variational - Phi, 'fro') / norm(Phi, 'fro') < 5e-4, ...
           'Variational state-transition matrix failed its finite-difference check.');

    [r_cw, v_cw] = propagate_CW_simple([0; 0; 0], [0; 1; 0], ...
                                       60, orbit_radius, c.mu);
    assert(all(isfinite([r_cw; v_cw])), 'CW propagation returned non-finite values.');

    Pc = calculatePoC([100; 0; 0], [0; 7500; 0], ...
                      diag([25; 25; 25]), diag([25; 25; 25]), c.HBR);
    assert(isfinite(Pc) && Pc >= 0 && Pc <= 1, 'Pc result is invalid.');

    % Stage 7 risk-contract checks: NASA Foster reference, numerical-range,
    % rotation, positive-definiteness, and nearly parallel encounter frames.
    omitron_r1 = 1e3 * [378.39559; 4305.721887; 5752.767554];
    omitron_v1 = 1e3 * [2.360800244; 5.580331936; -4.322349039];
    omitron_r2 = 1e3 * [374.5180598; 4307.560983; 5751.130418];
    omitron_v2 = 1e3 * [-5.388125081; -3.946827739; 3.322820358];
    omitron_C1 = 1e6 * [ ...
        44.5757544811362, 81.6751751052616, -67.8687662707124; ...
        81.6751751052616, 158.453402956163, -128.616921644857; ...
        -67.8687662707124, -128.616921644857, 105.490542562701];
    omitron_C2 = 1e6 * [ ...
        2.31067077720423, 1.69905293875632, -1.4170164577661; ...
        1.69905293875632, 1.24957388457206, -1.04174164279599; ...
        -1.4170164577661, -1.04174164279599, 0.869260558223714];
    omitron_pc = calculatePoC(omitron_r1 - omitron_r2, ...
        omitron_v1 - omitron_v2, omitron_C1, omitron_C2, 20);
    assert(abs(omitron_pc - 2.70601573490125e-5) / ...
           2.70601573490125e-5 < 1e-3, ...
           'NASA Foster Omitron reference case did not match.');

    covariance_a = diag([25, 36, 49]);
    covariance_b = diag([64, 81, 100]);
    low_pc = calculatePoC([1e5; 0; 0], [0; 7500; 0], ...
                          covariance_a, covariance_b, 10);
    assert(isfinite(low_pc) && low_pc >= 0 && low_pc <= realmin, ...
           'Near-zero Pc handling is invalid.');
    large_pc = calculatePoC([1e6; 0; 0], [0; 7500; 0], ...
                            covariance_a, covariance_b, 10);
    assert(isfinite(large_pc) && large_pc <= realmin, ...
           'Large-miss Pc handling is invalid.');

    rotated_rel_pos = [0, -1, 0; 1, 0, 0; 0, 0, 1] * [30; 20; 5];
    rotated_rel_vel = [0, -1, 0; 1, 0, 0; 0, 0, 1] * [200; 7500; 50];
    rotation = [0, -1, 0; 1, 0, 0; 0, 0, 1];
    base_pc = calculatePoC([30; 20; 5], [200; 7500; 50], ...
                           covariance_a, covariance_b, 10);
    rotated_pc = calculatePoC(rotated_rel_pos, rotated_rel_vel, ...
                              rotation * covariance_a * rotation', ...
                              rotation * covariance_b * rotation', 10);
    assert(abs(base_pc - rotated_pc) <= 1e-12 * max(1, base_pc), ...
           'Pc was not invariant to a common covariance/state rotation.');

    nearly_parallel_pc = calculatePoC([100; 0; 0], [7500; 1e-8; 0], ...
                                      covariance_a, covariance_b, 10);
    assert(isfinite(nearly_parallel_pc) && nearly_parallel_pc >= 0, ...
           'Nearly parallel encounter frame failed.');

    caught = false;
    try
        calculatePoC([100; 0; 0], [0; 7500; 0], diag([-1, 1, 1]), ...
                     eye(3), 10);
    catch ME
        caught = strcmp(ME.identifier, 'ACAM:InvalidCovariance');
    end
    assert(caught, 'Non-positive-definite covariance was not rejected.');

    caught = false;
    try
        calculatePoC([1; 0; 0], [0; 0; 0], eye(3), eye(3), c.HBR);
    catch ME
        caught = strcmp(ME.identifier, 'ACAM:InvalidRelativeVelocity');
    end
    assert(caught, 'Zero relative velocity was not rejected.');

    % Stage 3 feature and dataset contract checks.
    [feature_names, feature_units, schema_version] = feature_schema();
    assert(schema_version == 3 && numel(feature_names) == 14, ...
           'Feature schema version or width is invalid.');

    X_deb = X;
    X_deb(1) = X_deb(1) + 100;
    X_deb(5) = X_deb(5) + 1;
    scenario = struct('X0_sat', X, 'X0_deb', X_deb, ...
                      'rel_pos', X(1:3) - X_deb(1:3), ...
                      'rel_vel', X(4:6) - X_deb(4:6), ...
                      't_to_cpa', 0, 'C_sat', diag([25, 25, 25]), ...
                      'C_deb', diag([25, 25, 25]), ...
                      'altitude', 600e3, 'mass', c.m);
    features_training = build_features(scenario, c, [], struct());
    features_perfect = build_features(scenario, c);
    posterior_covariance = diag([25, 25, 25, 1e-6, 1e-6, 1e-6]);
    estimate = struct('X_sat', X, 'X_deb', X_deb, ...
                      'P_sat', posterior_covariance, ...
                      'P_deb', posterior_covariance, ...
                      'remaining_time', 0);
    features_ekf = build_features(scenario, c, estimate);
    assert(isequal(size(features_perfect), [14, 1]) && ...
           norm(features_training - features_perfect, inf) < 1e-12 && ...
           norm(features_ekf - features_perfect, inf) < 1e-12, ...
           'Identical state/covariance inputs produced different features.');
    assert(all(isfinite(features_perfect(5:10))) && ...
           features_perfect(5) < 0, ...
           'Signed Hill-frame encounter geometry is missing or unsigned.');
    mirrored_scenario = scenario;
    mirrored_scenario.X0_deb(1) = X(1) - 100;
    mirrored_scenario.rel_pos = ...
        X(1:3) - mirrored_scenario.X0_deb(1:3);
    mirrored_features = build_features(mirrored_scenario, c);
    assert(abs(mirrored_features(3) - features_perfect(3)) < 1e-12 && ...
           sign(mirrored_features(5)) == -sign(features_perfect(5)), ...
           'Feature schema discarded signed encounter geometry.');

    tracking_duration = 77;
    scenario_time = scenario;
    scenario_time.t_to_cpa = 200;
    estimate_time = estimate;
    estimate_time.remaining_time = scenario_time.t_to_cpa - tracking_duration;
    features_remaining = build_features(scenario_time, c, estimate_time);
    assert(features_remaining(2) == 123 && ...
           features_remaining(2) == scenario_time.t_to_cpa - tracking_duration, ...
           'EKF feature time did not use remaining_time.');

    % Stage 5 EKF contract: both independent posteriors are returned and a
    % positive decision window remains. Use a short smoke window for speed.
    ekf_config = ekf_tracking_config();
    propagation_contract = propagation_validation_config();
    assert(propagation_contract.version == 1 && ...
           isequal(propagation_contract.lead_hours, [6, 12, 24]) && ...
           isequal(propagation_contract.noise_modes, ...
                   {'zero_q', 'matched_q'}) && ...
           propagation_contract.primary_step_s == 600 && ...
           propagation_contract.convergence_step_s == 300, ...
           'Propagation-validation contract changed without a version update.');
    measurement_grid = measurement_contract_grid();
    q_calibration = process_noise_calibration_config();
    force_model_screen = force_model_discrepancy_config();
    candidate_ids = string({measurement_grid.candidates.id});
    position_sigmas = arrayfun(@(item) ...
        item.config.measurement_position_sigma_m, ...
        measurement_grid.candidates);
    velocity_sigmas = arrayfun(@(item) ...
        item.config.measurement_velocity_sigma_mps, ...
        measurement_grid.candidates);
    assert(measurement_grid.version == 1 && ...
           numel(unique(candidate_ids)) == 4 && ...
           isequal(sort(unique(position_sigmas(:)))', [30, 100]) && ...
           isequal(sort(unique(velocity_sigmas(:)))', [0.03, 0.10]) && ...
           measurement_grid.screening_gates.minimum_dangerous_scenarios == 8, ...
           'Measurement quality/cadence grid changed without a version update.');
    [training_contract, training_tracking] = ...
        training_row_contract('cdm_sequence', 10, 470001);
    precise = measurement_grid.candidates(strcmp( ...
        {measurement_grid.candidates.id}, 'precise_frequent')).config;
    assert(training_contract.training_contract_version == 2 && ...
           strcmp(training_contract.truth_model_mode, 'nominal') && ...
           strcmp(training_contract.training_measurement_contract_id, ...
                  'precise_frequent') && ...
           training_tracking.measurement_position_sigma_m == ...
               precise.measurement_position_sigma_m && ...
           training_tracking.measurement_velocity_sigma_mps == ...
               precise.measurement_velocity_sigma_mps && ...
           training_tracking.visibility_pass_duration_s == ...
               precise.visibility_pass_duration_s && ...
           training_tracking.visibility_period_scale == ...
               precise.visibility_period_scale, ...
           'Training-row contract changed without a version update.');
    assert(q_calibration.version == 1 && ...
           isequal(q_calibration.process_noise_scales, [0.25, 0.50, 1.00]) && ...
           isequal(q_calibration.lead_hours, [6, 3]) && ...
           q_calibration.n_scenarios == 20 && ...
           q_calibration.master_seed == 9950 && ...
           strcmp(q_calibration.measurement_candidate_id, ...
                  'precise_frequent'), ...
           'Process-noise calibration contract changed without a version update.');
    assert(force_model_screen.version == 1 && ...
           isequal(force_model_screen.altitudes_m, [350, 500, 700] * 1e3) && ...
           isequal(force_model_screen.lead_hours, [3, 6]) && ...
           force_model_screen.debris.drag_area_m2 / ...
               force_model_screen.debris.mass_kg > ...
           force_model_screen.target.drag_area_m2 / ...
               force_model_screen.target.mass_kg, ...
           'Force-model discrepancy contract changed without a version update.');
    if ~isempty(which('atmosnrlmsise00'))
        environment = struct('include_nrlmsise', true, ...
            'include_srp', true, ...
            'epoch_utc', force_model_screen.epoch_utc, ...
            'duration_s', 3600, ...
            'sun_position_start_m', ...
                [force_model_screen.astronomical_unit_m; 0; 0], ...
            'sun_position_end_m', ...
                [force_model_screen.astronomical_unit_m; 0; 0], ...
            'earth_rotation_radps', ...
                force_model_screen.earth_rotation_radps, ...
            'solar_pressure_npm2', ...
                force_model_screen.solar_pressure_npm2, ...
            'astronomical_unit_m', ...
                force_model_screen.astronomical_unit_m);
        [truth_derivative, truth_diagnostics] = ...
            truth_environment_dynamics(0, X, c, environment, ...
                                       force_model_screen.target);
        assert(all(isfinite(truth_derivative)) && ...
               truth_diagnostics.density_kgpm3 > 0 && ...
               truth_diagnostics.drag_acceleration_mps2 > 0 && ...
               truth_diagnostics.srp_acceleration_mps2 > 0, ...
               'NRLMSISE-00/SRP truth dynamics failed.');
    end
    Q_60 = process_noise_covariance(60, ekf_config);
    assert(norm(Q_60 - Q_60', 'fro') < 1e-14 && ...
           min(eig(Q_60)) >= -1e-14 && ...
           Q_60(1, 4) > 0 && Q_60(4, 4) < 1e-6, ...
           'Dimensioned white-acceleration process noise is invalid.');
    covariance_test = diag([10, 10, 10, 1e-3, 1e-3, 1e-3].^2);
    no_noise_config = ekf_config;
    no_noise_config.process_noise_scale = 0;
    no_noise_config.covariance_propagation_step_s = 60;
    [~, covariance_120, covariance_diagnostics] = ...
        propagate_state_covariance(X, covariance_test, 120, c, ...
                                   no_noise_config);
    assert(all(isfinite(covariance_120), 'all') && ...
           min(eig(covariance_120)) > 0 && ...
           covariance_diagnostics.process_noise_steps == 2 && ...
           strcmp(covariance_diagnostics.process_noise_approximation, ...
             ['short-step white acceleration, dynamically transported ', ...
              'through the nonlinear reference orbit']), ...
           'Stepwise covariance propagation contract failed.');
    ekf_config.max_tracking_duration_s = 120;
    ekf_config.reserve_before_tca_s = 60;
    ekf_config.include_initial_observation = true;
    ekf_scenario = scenario;
    ekf_scenario.t_to_cpa = 7200;
    ekf_scenario.orbital_period = 2 * pi * sqrt(orbit_radius^3 / c.mu);
    ekf_scenario.scenario_seed = 810001;
    tracking = run_ekf_tracking(ekf_scenario, c, ekf_config, 810001);
    assert(all(isfinite([tracking.X_sat_est; tracking.X_deb_est])) && ...
           tracking.tracking_duration_s < ekf_scenario.t_to_cpa && ...
           tracking.diagnostics.covariance_spd_sat && ...
           tracking.diagnostics.covariance_spd_deb && ...
           tracking.diagnostics.num_observations_sat > 0 && ...
           numel(tracking.diagnostics.truth_state_sat_final) == 6 && ...
           numel(tracking.diagnostics.truth_state_deb_final) == 6 && ...
           isfinite(tracking.diagnostics.mean_nis_sat) && ...
           isfinite(tracking.diagnostics.mean_nis_deb), ...
           'Stage 5 EKF tracking contract failed.');
    estimate_cov = struct( ...
        'X_sat', tracking.X_sat_est, 'X_deb', tracking.X_deb_est, ...
        'P_sat', tracking.P_sat, 'P_deb', tracking.P_deb, ...
        'remaining_time', ekf_scenario.t_to_cpa - tracking.tracking_duration_s);
    features_cov = build_features(ekf_scenario, c, estimate_cov);
    estimate_cov.P_deb = 10 * tracking.P_deb;
    features_deb_cov = build_features(ekf_scenario, c, estimate_cov);
    assert(features_deb_cov(1) ~= features_cov(1) && ...
           features_deb_cov(12) > features_cov(12), ...
           'Debris posterior covariance did not affect Pc/features.');
    estimate_supplied = estimate_cov;
    estimate_supplied.P_deb = tracking.P_deb;
    estimate_supplied.C_sat_tca = ekf_scenario.C_sat;
    estimate_supplied.C_deb_tca = ekf_scenario.C_deb;
    features_supplied = build_features(ekf_scenario, c, estimate_supplied);
    assert(abs(features_supplied(12) - ...
               trace(ekf_scenario.C_sat + ekf_scenario.C_deb)) < 1e-9 && ...
           features_supplied(12) < features_cov(12), ...
           'Supplied TCA covariance was not used by the feature contract.');

    metadata = struct( ...
        'requested_risk_band', 'test', 'actual_tca_s', 0, ...
        'tca_verified', true, 'tca_orthogonality_residual', 0, ...
        'orbital_energy_valid', true, 'perigee_valid', true, ...
        'propagation_fidelity', 'test', 'fallback_used', false, ...
        'round_trip_position_error_m', 0, 'optimizer_exit_status', 1, ...
        'initial_pc', features_perfect(1), 'final_pc', features_perfect(1), ...
        'random_seed', 1);
    dataset = struct('X', features_perfect', 'y_action', 0, ...
        'y_dv_hill', zeros(1, 3), 'feature_names', {feature_names}, ...
        'feature_units', {feature_units}, 'schema_version', schema_version, ...
        'scenario_metadata', metadata, 'generator_config', struct('test', true), ...
        'seed', 1, 'created_at', 'test');
    validate_dataset_contract(dataset);

    bad_dataset = dataset;
    bad_dataset.feature_names([1, 2]) = bad_dataset.feature_names([2, 1]);
    caught = false;
    try
        validate_dataset_contract(bad_dataset);
    catch ME
        caught = strcmp(ME.identifier, 'ACAM:FeatureSchemaMismatch');
    end
    assert(caught, 'Feature-order changes were not rejected.');

    % Stage 4 verified-encounter check: the shared generator must return an
    % interior nonlinear TCA with explicit fidelity and no fallback.
    scenario_config = scenario_generation_config();
    % Contract 6: the proposal covariance is per encounter family and
    % along-track dominant, fitted to the measured decision-epoch covariance.
    % A flat or cross-track-dominant proposal is the v5 defect that made the
    % requested band uninformative about the tracked band.
    proposal_sigma = scenario_config.proposal_sigma_ranges;
    assert(scenario_config.version == 6 && ...
           all(proposal_sigma.co_orbital.tangential_m > ...
               proposal_sigma.co_orbital.cross_track_m) && ...
           all(proposal_sigma.crossing.tangential_m > ...
               proposal_sigma.crossing.radial_m) && ...
           ~isequal(proposal_sigma.co_orbital, proposal_sigma.crossing), ...
           'Proposal covariance contract changed without a version update.');
    assert(scenario_config.physical_property_contract_version == 1 && ...
           strcmp(scenario_config.physical_property_stratum, 'matched') && ...
           scenario_config.truth_model_contract_version == 1 && ...
           strcmp(scenario_config.truth_model_mode, 'nominal'), ...
           'Stage-A/B scenario contract changed without versioning.');
    matched_physical = physical_property_strata(100, 'matched');
    moderate_physical = physical_property_strata(100, 'differential_4x');
    high_physical = physical_property_strata(100, 'differential_20x');
    assert(matched_physical.version == 1 && ...
           matched_physical.target.area_to_mass_m2pkg == 0.005 && ...
           matched_physical.debris.area_to_mass_m2pkg == 0.005 && ...
           moderate_physical.debris.area_to_mass_m2pkg == 0.02 && ...
           high_physical.debris.area_to_mass_m2pkg == 0.10 && ...
           moderate_physical.target.drag_coefficient == 2.2 && ...
           moderate_physical.debris.reflectivity_coefficient == 1.3, ...
           'Stage-A physical-property strata are inconsistent.');
    nominal_truth = struct('truth_model', truth_model_config('nominal'));
    nominal_pair = truth_dynamics_pair(nominal_truth, c, 60);
    assert(isequal(nominal_pair.target(0, X), ...
                   twoBodyJ2Drag_simple(0, X, c)) && ...
           isequal(nominal_pair.debris(0, X), ...
                   twoBodyJ2Drag_simple(0, X, c)), ...
           'Nominal truth path diverged from the frozen filter dynamics.');
    srp_context = struct( ...
        'truth_model', truth_model_config('nrlmsise_srp'), ...
        'truth_epoch_utc', scenario_config.truth_epoch_utc, ...
        'target_physical', moderate_physical.target, ...
        'debris_physical', moderate_physical.debris);
    srp_pair = truth_dynamics_pair(srp_context, c, 60);
    assert(all(isfinite([srp_pair.target(0, X); ...
                         srp_pair.debris(0, X)])) && ...
           strcmp(srp_pair.mode, 'nrlmsise_srp') && ...
           srp_pair.contract_version == 1, ...
           'NRLMSISE/SRP truth path is not runnable.');
    terminal_scenario_config = terminal_reference_scenario_config();
    terminal_sigma = terminal_scenario_config.proposal_sigma_ranges;
    assert(terminal_scenario_config.terminal_reference_profile_version == 3 && ...
           isequal(terminal_sigma.co_orbital.radial_m, [3, 6]) && ...
           isequal(terminal_sigma.co_orbital.tangential_m, [3, 6]) && ...
           isequal(terminal_sigma.co_orbital.cross_track_m, [3, 6]) && ...
           ... % One covariance for both families is what makes this profile
           ... % invariant under the contract-6 per-family fit, and is what
           ... % keeps C1, C2, Stage D and Stage D2 reproducible.
           isequal(terminal_sigma.co_orbital, terminal_sigma.crossing), ...
           'Terminal-reference scenario profile changed without a version update.');
    assert(isequal(terminal_scenario_config.pc_band_target_ranges(6, :), ...
                   [0.02, 0.08]) && ...
           nnz(terminal_scenario_config.pc_band_schedule == 6) == 8, ...
           'Terminal-reference risk enrichment changed without a version update.');
    scenario_config.pc_band_index = 4;
    % The co-orbital family is forced here so this long-standing check keeps
    % testing exactly what it always did.
    co_orbital_config = scenario_config;
    co_orbital_config.force_encounter_family = 'co_orbital';
    [verified_scenario, verified_metadata] = ...
        generate_synthetic_scenario(co_orbital_config, c, 700001);
    assert(verified_metadata.tca_verified && ~verified_metadata.fallback_used && ...
           verified_metadata.tca_induced_miss_error_m <= ...
               scenario_config.tca_induced_miss_error_tolerance_m && ...
           verified_metadata.pc_band_index == 4 && ...
           strcmp(verified_metadata.encounter_family, 'co_orbital') && ...
           verified_metadata.physical_property_contract_version == 1 && ...
           strcmp(verified_metadata.physical_property_stratum, 'matched') && ...
           verified_metadata.truth_model_contract_version == 1 && ...
           strcmp(verified_metadata.truth_model_mode, 'nominal') && ...
           strcmp(verified_metadata.propagation_fidelity, 'nominal') && ...
           strcmp(verified_metadata.evaluation_fidelity, 'nominal') && ...
           verified_scenario.target_physical.area_to_mass_m2pkg == 0.005 && ...
           verified_scenario.debris_physical.area_to_mass_m2pkg == 0.005 && ...
           all(isfinite([verified_scenario.X0_sat; verified_scenario.X0_deb])), ...
           'Stage 4 verified-encounter generation failed.');

    % The crossing stratum must reconstruct TCA just as accurately at
    % kilometres per second, and must produce genuinely three-dimensional
    % miss geometry. The co-orbital family cannot: its miss vector is radial
    % by construction, which is why it never yields a cross-track burn.
    crossing_config = scenario_config;
    crossing_config.force_encounter_family = 'crossing';
    [crossing_scenario, crossing_metadata] = ...
        generate_synthetic_scenario(crossing_config, c, 700001);
    crossing_frame = hill_frame(crossing_scenario.X_cpa_sat);
    crossing_miss_rtn = crossing_frame' * crossing_scenario.rel_pos;
    co_orbital_miss_rtn = hill_frame(verified_scenario.X_cpa_sat)' * ...
                          verified_scenario.rel_pos;
    assert(strcmp(crossing_metadata.encounter_family, 'crossing') && ...
           norm(crossing_scenario.rel_vel) > 1e3 && ...
           crossing_metadata.tca_induced_miss_error_m <= ...
               scenario_config.tca_induced_miss_error_tolerance_m && ...
           strcmp(crossing_metadata.tca_refinement_status, ...
                  'range_rate_root') && ...
           crossing_metadata.miss_distance_error_m <= ...
               scenario_config.tca_miss_distance_tolerance_m && ...
           crossing_metadata.pc_band_index == 4, ...
           'Crossing encounter stratum failed TCA reconstruction.');
    % Seeds are deterministic, so these are fixed contrasts, not samples:
    % the crossing miss is roughly half out-of-plane, the co-orbital miss is
    % radial to within back/forward propagation round-off.
    assert(abs(crossing_miss_rtn(3)) > 1e-2 * norm(crossing_miss_rtn) && ...
           abs(co_orbital_miss_rtn(3)) < 1e-3 * norm(co_orbital_miss_rtn), ...
           'Crossing stratum did not add out-of-plane miss geometry.');
    [~, ~, replay_pc, replay_details] = evaluate_maneuver( ...
        verified_scenario, zeros(3, 1), c, 0, true);
    assert(replay_details.completed && ...
           abs(log10(max(replay_pc, realmin)) - ...
               log10(max(verified_scenario.Pc_initial, realmin))) < 0.05, ...
           'Zero-burn replay did not preserve scenario-specific HBR/risk.');

    cdm_config = cdm_observation_config();
    cdm_a = simulate_cdm_observation(verified_scenario, c, 6 * 3600, ...
                                     770001, cdm_config);
    cdm_b = simulate_cdm_observation(verified_scenario, c, 6 * 3600, ...
                                     770001, cdm_config);
    cdm_features = build_features(verified_scenario, c, cdm_a.estimate);
    assert(isequaln(cdm_a, cdm_b) && all(isfinite(cdm_features)) && ...
           abs(cdm_features(12) - trace( ...
               cdm_a.estimate.C_sat_tca + ...
               cdm_a.estimate.C_deb_tca)) < 1e-9 && ...
           isfinite(cdm_a.diagnostics.nees_sat) && ...
           isfinite(cdm_a.diagnostics.nees_deb), ...
           'CDM observation contract is invalid or non-deterministic.');

    % Sequential CDM boundary: chronology, cutoff, and truth separation.
    [cdm_sequence, cdm_audit] = simulate_cdm_sequence( ...
        verified_scenario, c, [6, 24, 12] * 3600, 770001, cdm_config);
    [cdm_sequence_again, cdm_audit_again] = simulate_cdm_sequence( ...
        verified_scenario, c, [6, 24, 12] * 3600, 770001, cdm_config);
    [cdm_sequence_features, selected_cdm, cdm_history] = ...
        build_features_from_cdm(cdm_sequence, 12 * 3600);
    assert(isequaln(cdm_sequence, cdm_sequence_again) && ...
           isequaln(cdm_audit, cdm_audit_again) && ...
           isequal([cdm_sequence.messages.time_to_tca_s], ...
                   [24, 12, 6] * 3600) && ...
           selected_cdm.time_to_tca_s == 12 * 3600 && ...
           cdm_history.message_count == 2 && ...
           all(isfinite(cdm_sequence_features)) && ...
           cdm_sequence.contract.version == 1, ...
           'Sequential synthetic CDM contract is invalid.');
    model_fields = lower(strjoin(string( ...
        fieldnames(cdm_sequence.messages)), ' '));
    assert(~any(contains(model_fields, ...
           ["truth", "error", "nees", "actual"])), ...
           'Truth/audit data leaked into the model-facing CDM sequence.');

    % The ESA adapter converts log10 risk, sorts event history, and sends it
    % through exactly the same parser. Later rows must remain unavailable at
    % an earlier decision cutoff.
    esa_sample = table( ...
        [101; 101], [0.5; 1.0], [-4; -5], [2e-4; 3e-5], ...
        [80; 100], [12000; 11000], [10; 20], [70; 90], [30; 40], ...
        [1; 2], [11999; 10999], [3; 4], ...
        'VariableNames', {'event_id', 'time_to_tca', 'risk', ...
        'max_risk_estimate', 'miss_distance', 'relative_speed', ...
        'relative_position_r', 'relative_position_t', ...
        'relative_position_n', 'relative_velocity_r', ...
        'relative_velocity_t', 'relative_velocity_n'});
    esa_sequences = import_esa_cdm_sequences(esa_sample);
    [esa_at_24h, esa_history] = select_cdm_message( ...
        esa_sequences{1}, 24 * 3600);
    assert(esa_sequences{1}.contract.version == ...
               cdm_sequence.contract.version && ...
           esa_at_24h.time_to_tca_s == 24 * 3600 && ...
           abs(esa_at_24h.collision_probability - 1e-5) < 1e-15 && ...
           esa_history.message_count == 1 && ...
           ~esa_sequences{1}.metadata.maneuver_validation_supported, ...
           'ESA CDM conversion or decision-time isolation failed.');

    % Linked estimator chain: the second window must start from the first
    % posterior rather than drawing a new independent prior.
    linked_config = ekf_tracking_config();
    linked_config.max_tracking_duration_s = 120;
    linked_config.reserve_before_tca_s = 60;
    linked_config.include_initial_observation = true;
    [linked_sequence, linked_audit] = simulate_ekf_cdm_sequence( ...
        verified_scenario, c, [10800, 9000], 880001, linked_config);
    terminal_reference = generate_terminal_cdm_reference( ...
        verified_scenario, c, 1580001, terminal_cdm_reference_config());
    linked_features = build_features_from_cdm(linked_sequence, []);
    first_linked_tracking = linked_audit.messages{1}.tracking;

    % Schema-v3 slots 5-10 must be in the target Hill frame at the decision
    % epoch, not the CDM's RTN-at-TCA frame, so that features and the
    % Delta-V label share one frame. Check the rotation explicitly rather
    % than trusting that the two builders happen to agree.
    frame_message = linked_sequence.messages(end);
    R_tca_frame = hill_frame(frame_message.target_state_eci_tca);
    R_decision_frame = hill_frame(frame_message.target_state_eci_at_message);
    expected_rel_pos = R_decision_frame' * ...
        (R_tca_frame * frame_message.relative_position_rtn_m);
    assert(norm(linked_features(5:7) - expected_rel_pos) < 1e-9, ...
           'CDM features are not in the decision-epoch Hill frame.');
    assert(norm(frame_message.relative_position_rtn_m - expected_rel_pos) > ...
           1e-6 * norm(expected_rel_pos), ...
           'Frame test is vacuous: the two Hill frames coincide here.');
    no_state_message = frame_message;
    no_state_message.target_state_eci_at_message = nan(6, 1);
    no_state_sequence = linked_sequence;
    no_state_sequence.messages = no_state_message;
    assert_error(@() build_features_from_cdm(no_state_sequence, []), ...
                 'ACAM:IncompleteCdmForFeatures', ...
                 'A CDM without ECI states must be rejected, not rotated.');

    % The oracle used as the ML label must see only decision-epoch CDM
    % information, otherwise the surrogate is asked to predict a decision
    % made from data it cannot observe.
    [dV_cdm, ~, ~, cdm_oracle_info] = compute_cdm_oracle(frame_message, c);
    assert(numel(dV_cdm) == 3 && all(isfinite(dV_cdm)) && ...
           ismember(cdm_oracle_info.status, ...
                    {'stay', 'success', 'no_solution'}) && ...
           strcmp(cdm_oracle_info.label_information_set, ...
                  'decision-epoch CDM') && ...
           norm(dV_cdm) <= c.max_maneuver_mps * (1 + 1e-12), ...
           'CDM oracle did not return a bounded decision-time label.');
    truncated_message = frame_message;
    truncated_message.chaser_state_eci_at_message = nan(6, 1);
    assert_error(@() compute_cdm_oracle(truncated_message, c), ...
                 'ACAM:IncompleteCdmForOracle', ...
                 'CDM oracle accepted a message missing estimated states.');

    second_linked_tracking = linked_audit.messages{2}.tracking;
    assert(numel(linked_sequence.messages) == 2 && ...
           all(isfinite(linked_features)) && ...
           ~first_linked_tracking.continued_from_previous_posterior && ...
           second_linked_tracking.continued_from_previous_posterior && ...
           isfinite(terminal_reference.cdm.collision_probability) && ...
           terminal_reference.cdm.time_to_tca_s > 0 && ...
           ~any(strcmp({linked_sequence.messages.message_id}, ...
                       terminal_reference.cdm.message_id)) && ...
           linked_sequence.metadata.maneuver_validation_supported, ...
           'EKF posterior was not continued through the CDM sequence.');

    % Stage 6 maneuver-search checks: all six Hill directions, explicit
    % nonlinear verification, non-monotonic safety, and no-solution status.
    search_rel_pos = [0; 50; 0];
    search_rel_vel = [0; 0.5; 0];
    search_X_deb = X - [search_rel_pos; search_rel_vel];
    search_scenario = struct( ...
        'X0_sat', X, 'X0_deb', search_X_deb, ...
        'X_cpa_sat', X, 'X_cpa_deb', search_X_deb, ...
        'rel_pos', search_rel_pos, 'rel_vel', search_rel_vel, ...
        't_to_cpa', 0, 'C_sat', 25 * eye(3), ...
        'C_deb', 25 * eye(3), 'hbr_m', c.HBR, 'HBR', c.HBR, ...
        'mass', c.m);
    [dV_search, search_info] = find_minimum_safe_maneuver( ...
        X, search_scenario, c, 0, search_rel_pos, search_rel_vel, X, ...
        search_scenario.C_sat, search_scenario.C_deb, search_X_deb);
    [success_search, fuel_search, pc_search, eval_search] = ...
        evaluate_maneuver(search_scenario, dV_search, c, 0, true);
    assert(strcmp(search_info.status, 'success') && success_search && ...
           eval_search.completed && pc_search <= c.pc_target_remediation && ...
           abs(fuel_search - search_info.selected_magnitude_mps) < 1e-10 && ...
           ismember(search_info.selected_direction, search_info.direction_labels), ...
           'Stage 6 canonical maneuver search failed.');

    % The search may reuse the unchanged debris propagation. The cache must
    % preserve the canonical Pc exactly for the same maneuver.
    [~, ~, pc_uncached, uncached_details] = evaluate_maneuver( ...
        search_scenario, [1e-3; 2e-3; 0], c, 0, true);
    [~, ~, pc_cached, cached_details] = evaluate_maneuver( ...
        search_scenario, [1e-3; 2e-3; 0], c, 0, true, ...
        uncached_details.evaluation_context);
    assert(uncached_details.completed && cached_details.completed && ...
           abs(pc_uncached - pc_cached) <= 1e-12 * ...
           max([1, pc_uncached, pc_cached]), ...
           'Maneuver propagation cache changed the canonical Pc.');
    assert(isfield(uncached_details.evaluation_context, 'X_deb_at_burn') && ...
           norm(uncached_details.evaluation_context.X_deb_at_burn - ...
                search_scenario.X0_deb) < 1e-9, ...
           'Decision-epoch debris truth state is missing from the cache.');

    search_config = maneuver_search_config();
    search_config.refinement_iterations = 12;
    search_config.candidate_evaluator = @(direction, magnitude) ...
        1e-2 * (magnitude < 0.4 || ...
                (magnitude >= 0.6 && magnitude < 0.8)) + ...
        1e-8 * (magnitude >= 0.4 && magnitude < 0.6) + ...
        1e-9 * (magnitude >= 0.8);
    [dV_nonmonotonic, nonmonotonic_info] = find_minimum_safe_maneuver( ...
        X, search_scenario, c, 0, search_rel_pos, search_rel_vel, X, ...
        search_scenario.C_sat, search_scenario.C_deb, search_X_deb, ...
        search_config);
    assert(strcmp(nonmonotonic_info.status, 'success') && ...
           nonmonotonic_info.selected_magnitude_mps >= 0.4 && ...
           nonmonotonic_info.selected_magnitude_mps < 0.41 && ...
           norm(dV_nonmonotonic) > 0, ...
           'Non-monotonic maneuver safety was not searched correctly.');

    search_config.candidate_evaluator = @(direction, magnitude) 1e-2;
    [dV_no_solution, no_solution_info] = find_minimum_safe_maneuver( ...
        X, search_scenario, c, 0, search_rel_pos, search_rel_vel, X, ...
        search_scenario.C_sat, search_scenario.C_deb, search_X_deb, ...
        search_config);
    assert(strcmp(no_solution_info.status, 'no_solution') && ...
           norm(dV_no_solution) == 0 && ...
           ~no_solution_info.safety_constraint_satisfied, ...
           'No-solution maneuver status was not explicit.');

    along_track_config = maneuver_search_config('along_track');
    assert(isequal(along_track_config.direction_labels, ...
                   {'prograde', 'retrograde'}) && ...
           isequal(size(along_track_config.direction_vectors_hill), [3, 2]) && ...
           all(along_track_config.direction_vectors_hill(1, :) == 0) && ...
           all(along_track_config.direction_vectors_hill(3, :) == 0), ...
           'Along-track maneuver scope includes a non-tangential direction.');
    operability_config = maneuver_operability_config();
    fixed_operational_time_s = ...
        operability_config.decision_processing_s + ...
        operability_config.command_validation_upload_s + ...
        operability_config.attitude_slew_settle_s + ...
        operability_config.execution_contingency_s + ...
        operability_config.minimum_post_burn_margin_s;
    assert(operability_config.version == 1 && ...
           fixed_operational_time_s == 3600 && ...
           operability_config.nominal_acceleration_mps2 == 0.005 && ...
           isequal(operability_config.acceleration_sensitivity_mps2, ...
                   [0.001, 0.005, 0.02]) && ...
           strcmp(operability_config.direction_scope, 'along_track'), ...
           'Maneuver-operability contract changed without a version update.');
    one_hour_alert = struct('time_to_tca_s', 3600, ...
                            'collision_probability', 1e-3);
    one_hour_operability = assess_maneuver_operability( ...
        one_hour_alert, struct(), c, operability_config);
    assert(strcmp(one_hour_operability.status, 'insufficient_time') && ...
           ~one_hour_operability.timeline_feasible, ...
           'One-hour ground-assisted negative control was not rejected.');

    % A Pc between the remediation target and decision threshold is safe to
    % stay; it must not be labelled as a maneuver.
    search_config.candidate_evaluator = @(direction, magnitude) 5e-5;
    [dV_stay, stay_info] = find_minimum_safe_maneuver( ...
        X, search_scenario, c, 0, search_rel_pos, search_rel_vel, X, ...
        search_scenario.C_sat, search_scenario.C_deb, search_X_deb, ...
        search_config);
    assert(strcmp(stay_info.status, 'stay') && norm(dV_stay) == 0 && ...
           stay_info.safety_constraint_satisfied && ...
           stay_info.achieved_pc > c.pc_target_remediation && ...
           stay_info.achieved_pc <= c.pc_maneuver_threshold, ...
           'Stay maneuver status was not explicit.');

    % The coarse magnitude grid must resolve the decade the verified minimum
    % burns actually occupy. A linear grid over [0, 2] m/s puts its first
    % step at 0.1 m/s, twenty times any observed solution, which makes the
    % documented non-monotonic search nominal rather than real.
    grid_config = maneuver_search_config();
    assert(grid_config.version == 2 && ...
           strcmp(grid_config.coarse_grid_spacing, 'log') && ...
           grid_config.coarse_grid_minimum_mps <= 1e-3, ...
           'Maneuver search grid contract changed without a version update.');
    probe_magnitudes = [];
    probe_config = grid_config;
    probe_config.refinement_iterations = 4;
    probe_config.candidate_evaluator = @(direction, magnitude) ...
        record_magnitude(magnitude);
    find_minimum_safe_maneuver(X, search_scenario, c, 0, search_rel_pos, ...
        search_rel_vel, X, search_scenario.C_sat, search_scenario.C_deb, ...
        search_X_deb, probe_config);
    assert(nnz(probe_magnitudes > 0 & probe_magnitudes < 1e-2) >= 3, ...
           'Coarse grid does not sample the observed minimum-burn decade.');

    % The sized baseline must scale with the encounter instead of sweeping
    % fixed magnitudes one to two orders larger than any verified burn. It
    % must stay below the actuator limit, stay put when the CDM is already
    % safe, and grow as the time available to drift shrinks.
    assert(load_constants().comparison_contract_version == 2 && ...
           numel(load_constants().baseline_rules) == 2, ...
           'Comparison contract changed without a version update.');
    [dV_sized, sized_info] = sized_baseline_maneuver(frame_message, c);
    safe_message = frame_message;
    safe_message.collision_probability = c.pc_maneuver_threshold / 10;
    [dV_safe, safe_info] = sized_baseline_maneuver(safe_message, c);
    short_message = frame_message;
    short_message.time_to_tca_s = frame_message.time_to_tca_s / 4;
    [~, short_info] = sized_baseline_maneuver(short_message, c);
    assert(norm(dV_safe) == 0 && strcmp(safe_info.status, 'stay') && ...
           ~safe_info.triggered, ...
           'Sized baseline burned on a CDM already below the threshold.');
    assert(norm(dV_sized) <= c.max_maneuver_mps * (1 + 1e-12) && ...
           dV_sized(1) == 0 && dV_sized(3) == 0, ...
           'Sized baseline exceeded the actuator limit or left along-track.');
    if sized_info.triggered && ~sized_info.actuator_limited && ...
            ~short_info.actuator_limited
        assert(short_info.magnitude_mps > sized_info.magnitude_mps, ...
               'Sized baseline did not grow as drift time shrank.');
    end

    % Ranking skill and a cost-selected operating point replace the fixed
    % 1e-4 cutoff, which cannot transfer between two different covariances.
    perfect = evaluate_risk_discrimination([1; 2; 3; 4], ...
                                           [false; false; true; true], 5);
    inverted = evaluate_risk_discrimination([4; 3; 2; 1], ...
                                            [false; false; true; true], 5);
    assert(abs(perfect.auc - 1) < 1e-12 && abs(inverted.auc) < 1e-12 && ...
           abs(perfect.recall_at_cost_optimal - 1) < 1e-12 && ...
           perfect.false_alarm_rate_at_cost_optimal == 0 && ...
           perfect.cost_optimal_threshold >= 2 && ...
           perfect.cost_optimal_threshold < 3, ...
           'Risk discrimination metrics are wrong on a separable case.');
    % Under separation the optimum is an interval, not a point. Reporting
    % only the point invites reading an arbitrary value inside a wide gap as
    % an operational threshold.
    assert(perfect.separable && ~inverted.separable && ...
           perfect.cost_optimal_threshold_upper > ...
               perfect.cost_optimal_threshold_lower && ...
           perfect.cost_optimal_threshold_lower == ...
               perfect.cost_optimal_threshold, ...
           'Separable case did not report a cost-optimal threshold interval.');
    tied = evaluate_risk_discrimination([1; 1; 1; 1], ...
                                        [false; false; true; true], 5);
    assert(abs(tied.auc - 0.5) < 1e-12 && ...
           abs(tied.recall_at_cost_optimal - 1) < 1e-12, ...
           'Tied scores must score 0.5 AUC and favour catching dangerous cases.');
    % The Hanley-McNeil form collapses to zero under separation. That is a
    % property of the formula, not evidence of certainty, so the separable
    % flag has to carry that warning instead.
    assert(tied.auc_standard_error > 0 && perfect.auc_standard_error == 0 && ...
           perfect.separable, ...
           'AUC standard error did not follow the Hanley-McNeil form.');
    single_class = evaluate_risk_discrimination([1; 2], [true; true], 5);
    assert(isnan(single_class.auc), ...
           'AUC must be undefined when only one class is present.');

    % Calibration is predicted probability against observed frequency. The
    % checker must exercise the nonlinear truth path and report the
    % probability floor its sample count can actually resolve.
    calibration_estimate = struct( ...
        'X_sat', X, 'X_deb', X - [0; 300; 0; 0; 0.02; 0], ...
        'P_sat', blkdiag(2500 * eye(3), 1e-4 * eye(3)), ...
        'P_deb', blkdiag(2500 * eye(3), 1e-4 * eye(3)), ...
        'time_to_tca_s', 600);
    calibration = validate_pc_calibration(calibration_estimate, c, ...
        struct('num_samples', 40, 'hbr_scale', 400, 'seed', 24680));
    assert(calibration.completed_samples > 0 && ...
           calibration.empirical_frequency >= 0 && ...
           calibration.empirical_frequency <= 1 && ...
           calibration.confidence_lower <= calibration.empirical_frequency && ...
           calibration.confidence_upper >= calibration.empirical_frequency && ...
           calibration.hbr_m == c.HBR * 400 && ...
           abs(calibration.resolvable_probability_floor - ...
               3 / calibration.completed_samples) < 1e-12, ...
           'Pc calibration checker did not produce a usable frequency test.');

    % The Stage 5g transition must be nearly invariant to an arbitrary outer
    % covariance partition, while retaining the analytic density-state FOGM.
    joint_config = joint_drag_filter_config('broad');
    joint_state = [X; X + [0; 100; 0; 0; 0.1; 0]; 0; 0; 0];
    orbital_variance = [100, 100, 100, 0.1, 0.1, 0.1].^2;
    joint_covariance = diag([orbital_variance, orbital_variance, ...
        joint_config.ballistic_prior_sigma_log^2, ...
        joint_config.ballistic_prior_sigma_log^2, ...
        joint_config.density_stationary_sigma_log^2]);
    config300 = joint_config;
    config300.covariance_propagation_step_s = 300;
    config150 = joint_config;
    config150.covariance_propagation_step_s = 150;
    [state300, covariance300] = propagate_joint_drag_covariance( ...
        joint_state, joint_covariance, 600, c, config300);
    [state150, covariance150] = propagate_joint_drag_covariance( ...
        joint_state, joint_covariance, 600, c, config150);
    assert(abs(trace(covariance300) / trace(covariance150) - 1) < 1e-6 && ...
           norm((state300(1:3) - state300(7:9)) - ...
                (state150(1:3) - state150(7:9))) < 1e-2, ...
           'Time-varying joint covariance transport depends on outer partition.');
    [~, density_phi, density_q] = joint_drag_transition( ...
        joint_state, 600, c, joint_config);
    expected_phi = exp(-600 / joint_config.density_correlation_time_s);
    expected_q = joint_config.density_stationary_sigma_log^2 * ...
        (1 - expected_phi^2);
    assert(abs(density_phi(15, 15) - expected_phi) < 1e-8 && ...
           abs(density_q(15, 15) - expected_q) < 1e-8, ...
           'Density-state Gauss-Markov transition is inconsistent.');
    differential_config = stage5h_drag_filter_config('differential_015');
    differential_state = [joint_state; 0];
    [~, differential_phi, differential_q] = joint_drag_transition( ...
        differential_state, 600, c, differential_config);
    expected_differential_phi = exp(-600 / ...
        differential_config.differential_density_correlation_time_s);
    expected_differential_q = ...
        differential_config.differential_density_stationary_sigma_log^2 * ...
        (1 - expected_differential_phi^2);
    assert(isequal(size(differential_phi), [16, 16]) && ...
           abs(differential_phi(16, 16) - expected_differential_phi) < 1e-8 && ...
           abs(differential_q(16, 16) - expected_differential_q) < 1e-8, ...
           'Differential-density Gauss-Markov transition is inconsistent.');

    fprintf('ACAM shared-module smoke tests passed.\n');

    function value = record_magnitude(magnitude)
        probe_magnitudes(end + 1) = magnitude;
        value = 1e-2 * (magnitude < 5e-3) + 1e-9 * (magnitude >= 5e-3);
    end
end

function R_h2e = hill_frame(X)
    r_hat = X(1:3) / norm(X(1:3));
    h_hat = cross(X(1:3), X(4:6));
    h_hat = h_hat / norm(h_hat);
    R_h2e = [r_hat, cross(h_hat, r_hat), h_hat];
end

function assert_error(fn, expected_identifier, message)
    try
        fn();
    catch ME
        assert(strcmp(ME.identifier, expected_identifier), ...
               '%s (got %s)', message, ME.identifier);
        return;
    end
    assert(false, '%s (no error raised)', message);
end
