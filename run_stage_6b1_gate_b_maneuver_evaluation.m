function results = run_stage_6b1_gate_b_maneuver_evaluation( ...
        output_dir, use_parallel)
%RUN_STAGE_6B1_GATE_B_MANEUVER_EVALUATION Run the frozen fresh-seed gate.

    setup_project;
    project_root = fileparts(mfilename('fullpath'));
    contract = stage6b1_gate_b_contract(project_root);
    verify_contract(contract);
    contract.source_hash_manifest = source_hash_manifest(project_root);
    if nargin < 1 || isempty(output_dir)
        output_dir = contract.output_directory;
    end
    if nargin < 2 || isempty(use_parallel)
        use_parallel = true;
    end
    result_path = fullfile(output_dir, 'stage_6b1_gate_b_results.mat');
    if isfile(result_path)
        error('ACAM:Stage6b1GateBOutputExists', ...
            'Refusing to overwrite completed output %s.', output_dir);
    end
    output_lock = acquire_output_lock(output_dir, mfilename);
    diary(fullfile(output_dir, 'console_log.txt'));
    diary_cleanup = onCleanup(@() diary('off'));

    cases = gate_b_case_set(contract);
    checkpoint = fullfile(output_dir, 'stage_6b1_gate_b_progress.mat');
    state = struct('contract', contract, ...
        'records', {cell(contract.n_geometries, 1)}, ...
        'done', false(contract.n_geometries, 1));
    if isfile(checkpoint)
        saved = load(checkpoint, 'state');
        assert(isequaln(saved.state.contract, contract), ...
            'Existing Gate B checkpoint has a different frozen contract.');
        state = saved.state;
    end
    if use_parallel && isempty(gcp('nocreate'))
        parpool('Processes', 2);
    end

    c = load_constants();
    timer = tic;
    remaining = find(~state.done);
    initial_remaining = numel(remaining);
    fprintf('Stage 6b1 Gate B: %d fresh geometries, %d candidate rows.\n', ...
        contract.n_geometries, contract.expected_candidate_rows);
    if use_parallel && ~isempty(remaining)
        futures = parallel.FevalFuture.empty;
        for k = 1:numel(remaining)
            index = remaining(k);
            futures(k) = parfeval(@evaluate_geometry_safe, 1, ...
                cases(index), contract, c);
        end
        for k = 1:numel(futures)
            [future_index, record] = fetchNext(futures);
            index = remaining(future_index);
            state.records{index} = record;
            state.done(index) = true;
            save_checkpoint(checkpoint, state);
            print_progress(state, contract, timer, initial_remaining);
        end
    else
        for index = remaining(:)'
            state.records{index} = evaluate_geometry_safe( ...
                cases(index), contract, c);
            state.done(index) = true;
            save_checkpoint(checkpoint, state);
            print_progress(state, contract, timer, initial_remaining);
        end
    end

    [candidate_rows, failures] = collate_records(state.records);
    gate = evaluate_gate(candidate_rows, failures, state, contract);
    geometry_summary = summarize_geometries(candidate_rows);
    writetable(candidate_rows, fullfile(output_dir, ...
        'stage_6b1_gate_b_candidate_rows.csv'));
    writetable(geometry_summary, fullfile(output_dir, ...
        'stage_6b1_gate_b_geometry_summary.csv'));
    writetable(failures, fullfile(output_dir, ...
        'stage_6b1_gate_b_failures.csv'));

    if gate.pass
        verdict = ["STAGE 6B1 GATE B PASS: the legacy evaluator met the ", ...
            "frozen development-scope classification and numeric bounds. ", ...
            "ML training remains blocked by Gates C and D."];
    else
        verdict = ["STAGE 6B1 GATE B FAIL: the legacy maneuver evaluator ", ...
            "must be replaced by the complete post-burn evaluator and ", ...
            "confirmed before labels or ML training."];
    end
    results = struct('contract', contract, 'gate', gate, ...
        'candidate_rows', candidate_rows, ...
        'geometry_summary', geometry_summary, 'failures', failures, ...
        'legacy_evaluator_retained_for_development_labels', gate.pass, ...
        'corrected_evaluator_required', ~gate.pass, ...
        'ml_training_authorized', false, ...
        'sealed_test_authorized', false, ...
        'verdict', join(verdict, ''), 'runtime_seconds', toc(timer), ...
        'completed_at', datetime('now'));
    save(result_path, 'results', '-v7.3');
    result_sha256 = sha256_file(result_path);
    write_hash_sidecar([result_path, '.sha256'], result_sha256);
    write_result(output_dir, results, result_sha256);
    fprintf('\n%s\n', results.verdict);
    disp(struct2table(gate, 'AsArray', true));
    assert(~isempty(output_lock) && ~isempty(diary_cleanup));
end

function verify_contract(contract)
    assert(strcmpi(sha256_file(contract.source_document), ...
        contract.source_document_sha256), ...
        'Gate B contract document changed after freezing.');
    assert(contract.n_geometries == 10 && ...
        contract.expected_rows == 20 && ...
        contract.expected_candidate_rows == 80, ...
        'Gate B sample counts changed.');
    all_seeds = [contract.seed_starts(1) + (0:4), ...
        contract.seed_starts(2) + (0:4)];
    assert(numel(unique(all_seeds)) == 10 && all(all_seeds > 1700020), ...
        'Gate B seeds overlap a declared earlier-stage range.');
end

function cases = gate_b_case_set(contract)
    template = struct('geometry_id', 0, 'seed', 0, 'family', '', ...
        'band', 0, 'split', '');
    cases = repmat(template, contract.n_geometries, 1);
    index = 0;
    for family_index = 1:numel(contract.families)
        for k = 1:contract.n_per_family
            index = index + 1;
            cases(index) = struct('geometry_id', index, ...
                'seed', contract.seed_starts(family_index) + k - 1, ...
                'family', contract.families{family_index}, ...
                'band', contract.band_schedule(k), 'split', 'gate_b');
        end
    end
end

function record = evaluate_geometry_safe(item, contract, c)
    try
        [source_rows, contexts] = generate_truth_audited_geometry( ...
            item, contract, c);
        candidate_rows = cell(numel(contexts) * ...
            numel(contract.candidate_labels), 1);
        candidate_details = cell(size(candidate_rows));
        row_index = 0;
        for arm_index = 1:numel(contexts)
            context = contexts(arm_index);
            vectors = {zeros(3, 1), context.optimizer_dv_hill, ...
                context.reserved_dv_hill, context.fixed_dv_hill};
            c_local = c2_scenario_constants(c, context.withheld_truth);
            for candidate_index = 1:numel(vectors)
                row_index = row_index + 1;
                [comparison, details] = evaluate_gate_b_candidate( ...
                    context, vectors{candidate_index}, c_local);
                candidate_rows{row_index} = comparison_row( ...
                    item, context, source_rows(arm_index), ...
                    contract.candidate_labels{candidate_index}, ...
                    comparison, details, contract, c_local);
                candidate_details{row_index} = details;
            end
        end
        record = struct('status', "complete", ...
            'candidate_rows', vertcat(candidate_rows{:}), ...
            'candidate_details', {candidate_details}, ...
            'geometry_id', item.geometry_id, 'seed', item.seed, ...
            'family', string(item.family), 'error_id', "", ...
            'error_message', "");
    catch ME
        record = struct('status', "failed", ...
            'candidate_rows', struct([]), 'candidate_details', {{}}, ...
            'geometry_id', item.geometry_id, 'seed', item.seed, ...
            'family', string(item.family), ...
            'error_id', string(ME.identifier), ...
            'error_message', string(ME.message));
    end
end

function row = comparison_row(item, context, source_row, candidate_label, ...
        comparison, details, contract, c)
    planning_member_diagnostics = details.planning.member_tca_diagnostics;
    planning_tca_valid = all([planning_member_diagnostics. ...
        tca_inside_interval]) && ...
        details.planning.central_tca_diagnostics.tca_inside_interval;
    planning_tca_error_m = max(abs([planning_member_diagnostics. ...
        induced_miss_error_m]));
    truth_tca_valid = details.truth_tca_diagnostics.tca_inside_interval;
    truth_tca_error_m = abs( ...
        details.truth_tca_diagnostics.induced_miss_error_m);
    covariance_change = max([details.planning. ...
        member_covariance_change_relative; ...
        details.truth_covariance_change_relative]);
    covariance_identity_error = max([details.planning. ...
        member_relative_identity_error; ...
        details.truth_relative_covariance_identity_error]);
    cross_covariance_fro = min([details.planning. ...
        member_cross_covariance_position_fro; ...
        details.truth_cross_covariance_position_fro]);
    near_planning_log_change = near_log_change( ...
        comparison.planning_legacy_pc, comparison.planning_complete_pc, ...
        contract.near_pc_lower, contract.near_pc_upper);
    near_truth_log_change = near_log_change( ...
        comparison.truth_legacy_pc, comparison.truth_complete_pc, ...
        contract.near_pc_lower, contract.near_pc_upper);
    trigger_applicable = strcmp(candidate_label, 'zero');
    legacy_trigger = max(source_row.decision_pc, ...
        comparison.planning_legacy_pc) > c.pc_maneuver_threshold;
    complete_trigger = max(source_row.decision_pc, ...
        comparison.planning_complete_pc) > c.pc_maneuver_threshold;
    row = struct( ...
        'geometry_id', item.geometry_id, 'seed', item.seed, ...
        'family', string(item.family), 'band', item.band, ...
        'arm', string(context.arm), 'candidate', string(candidate_label), ...
        'dv_radial_mps', details.dV_hill_mps(1), ...
        'dv_along_track_mps', details.dV_hill_mps(2), ...
        'dv_cross_track_mps', details.dV_hill_mps(3), ...
        'dv_magnitude_mps', details.magnitude_mps, ...
        'planning_legacy_pc', comparison.planning_legacy_pc, ...
        'planning_tca_only_pc', comparison.planning_tca_only_pc, ...
        'planning_complete_pc', comparison.planning_complete_pc, ...
        'truth_legacy_pc', comparison.truth_legacy_pc, ...
        'truth_tca_only_pc', comparison.truth_tca_only_pc, ...
        'truth_complete_pc', comparison.truth_complete_pc, ...
        'planning_threshold_disagreement', threshold_disagreement( ...
            comparison.planning_legacy_pc, ...
            comparison.planning_complete_pc, c.pc_maneuver_threshold), ...
        'planning_remediation_disagreement', threshold_disagreement( ...
            comparison.planning_legacy_pc, ...
            comparison.planning_complete_pc, c.pc_target_remediation), ...
        'truth_safety_disagreement', threshold_disagreement( ...
            comparison.truth_legacy_pc, comparison.truth_complete_pc, ...
            c.pc_maneuver_threshold), ...
        'tca_only_planning_threshold_change', threshold_disagreement( ...
            comparison.planning_legacy_pc, ...
            comparison.planning_tca_only_pc, c.pc_maneuver_threshold), ...
        'covariance_planning_threshold_change', threshold_disagreement( ...
            comparison.planning_tca_only_pc, ...
            comparison.planning_complete_pc, c.pc_maneuver_threshold), ...
        'tca_only_truth_safety_change', threshold_disagreement( ...
            comparison.truth_legacy_pc, comparison.truth_tca_only_pc, ...
            c.pc_maneuver_threshold), ...
        'covariance_truth_safety_change', threshold_disagreement( ...
            comparison.truth_tca_only_pc, comparison.truth_complete_pc, ...
            c.pc_maneuver_threshold), ...
        'trigger_applicable', trigger_applicable, ...
        'legacy_trigger', legacy_trigger, ...
        'complete_trigger', complete_trigger, ...
        'trigger_disagreement', trigger_applicable && ...
            legacy_trigger ~= complete_trigger, ...
        'near_planning_log10_pc_change', near_planning_log_change, ...
        'near_truth_log10_pc_change', near_truth_log_change, ...
        'maximum_covariance_change_relative', covariance_change, ...
        'maximum_relative_identity_error', covariance_identity_error, ...
        'minimum_cross_covariance_position_fro', cross_covariance_fro, ...
        'maximum_member_tca_shift_s', max(abs( ...
            details.planning.member_tca_shift_s)), ...
        'truth_tca_shift_s', details.truth_tca_shift_s, ...
        'planning_tca_valid', planning_tca_valid, ...
        'truth_tca_valid', truth_tca_valid, ...
        'maximum_planning_induced_miss_error_m', planning_tca_error_m, ...
        'truth_induced_miss_error_m', truth_tca_error_m, ...
        'legacy_worst_member_index', ...
            details.planning.legacy.worst_member_index, ...
        'tca_only_worst_member_index', ...
            details.planning.tca_only_worst_member_index, ...
        'complete_worst_member_index', ...
            details.planning.complete_worst_member_index, ...
        'central_covariance_state_position_error_m', ...
            details.planning.central_covariance_state_position_error_m, ...
        'completed', details.completed);
end

function changed = threshold_disagreement(first_pc, second_pc, threshold)
    changed = (first_pc <= threshold) ~= (second_pc <= threshold);
end

function value = near_log_change(first_pc, second_pc, lower, upper)
    near = (first_pc >= lower && first_pc <= upper) || ...
        (second_pc >= lower && second_pc <= upper);
    if near
        value = abs(log10(max(first_pc, realmin)) - ...
            log10(max(second_pc, realmin)));
    else
        value = NaN;
    end
end

function [rows, failures] = collate_records(records)
    row_cells = cell(0, 1);
    failure_cells = cell(0, 1);
    for k = 1:numel(records)
        record = records{k};
        if strcmp(record.status, "complete")
            row_cells{end + 1, 1} = record.candidate_rows; %#ok<AGROW>
        else
            failure_cells{end + 1, 1} = struct( ...
                'geometry_id', record.geometry_id, 'seed', record.seed, ...
                'family', record.family, 'error_id', record.error_id, ...
                'error_message', record.error_message); %#ok<AGROW>
        end
    end
    if isempty(row_cells)
        rows = table();
    else
        rows = struct2table(vertcat(row_cells{:}));
    end
    if isempty(failure_cells)
        failures = table('Size', [0, 5], ...
            'VariableTypes', {'double', 'double', 'string', 'string', 'string'}, ...
            'VariableNames', {'geometry_id', 'seed', 'family', ...
                'error_id', 'error_message'});
    else
        failures = struct2table(vertcat(failure_cells{:}));
    end
end

function gate = evaluate_gate(rows, failures, state, contract)
    if isempty(rows)
        gate = empty_gate(contract, height(failures), nnz(state.done));
        return;
    end
    near_changes = [rows.near_planning_log10_pc_change; ...
        rows.near_truth_log10_pc_change];
    near_changes = near_changes(isfinite(near_changes));
    if isempty(near_changes)
        max_near_change = 0;
    else
        max_near_change = max(near_changes);
    end
    max_covariance_change = max(rows.maximum_covariance_change_relative);
    count_pass = nnz(state.done) == contract.n_geometries && ...
        height(rows) == contract.expected_candidate_rows;
    execution_pass = height(failures) == 0 && all(rows.completed);
    tca_pass = all(rows.planning_tca_valid & rows.truth_tca_valid) && ...
        all(rows.maximum_planning_induced_miss_error_m <= ...
            contract.tca_induced_miss_error_tolerance_m) && ...
        all(rows.truth_induced_miss_error_m <= ...
            contract.tca_induced_miss_error_tolerance_m);
    covariance_invariants_pass = all( ...
        rows.maximum_relative_identity_error <= ...
            contract.relative_identity_tolerance) && ...
        all(rows.minimum_cross_covariance_position_fro > 0);
    action_limit_pass = all(rows.dv_magnitude_mps <= 2 * (1 + 1e-12));
    classification_pass = ...
        ~any(rows.planning_threshold_disagreement) && ...
        ~any(rows.planning_remediation_disagreement) && ...
        ~any(rows.truth_safety_disagreement) && ...
        ~any(rows.trigger_disagreement);
    near_pc_bound_pass = max_near_change <= ...
        contract.max_near_log10_pc_change;
    covariance_bound_pass = max_covariance_change <= ...
        contract.max_relative_covariance_change;
    gate = struct( ...
        'pass', count_pass && execution_pass && tca_pass && ...
            covariance_invariants_pass && action_limit_pass && ...
            classification_pass && near_pc_bound_pass && ...
            covariance_bound_pass, ...
        'completed_geometries', nnz(state.done), ...
        'observed_candidate_rows', height(rows), ...
        'failure_count', height(failures), ...
        'count_pass', count_pass, 'execution_pass', execution_pass, ...
        'tca_invariants_pass', tca_pass, ...
        'covariance_invariants_pass', covariance_invariants_pass, ...
        'action_limit_pass', action_limit_pass, ...
        'classification_pass', classification_pass, ...
        'near_pc_bound_pass', near_pc_bound_pass, ...
        'covariance_bound_pass', covariance_bound_pass, ...
        'planning_threshold_disagreements', ...
            nnz(rows.planning_threshold_disagreement), ...
        'planning_remediation_disagreements', ...
            nnz(rows.planning_remediation_disagreement), ...
        'truth_safety_disagreements', ...
            nnz(rows.truth_safety_disagreement), ...
        'trigger_disagreements', nnz(rows.trigger_disagreement), ...
        'tca_only_planning_threshold_changes', ...
            nnz(rows.tca_only_planning_threshold_change), ...
        'covariance_planning_threshold_changes', ...
            nnz(rows.covariance_planning_threshold_change), ...
        'tca_only_truth_safety_changes', ...
            nnz(rows.tca_only_truth_safety_change), ...
        'covariance_truth_safety_changes', ...
            nnz(rows.covariance_truth_safety_change), ...
        'maximum_near_log10_pc_change', max_near_change, ...
        'maximum_covariance_change_relative', max_covariance_change, ...
        'maximum_member_tca_shift_s', ...
            max(rows.maximum_member_tca_shift_s), ...
        'maximum_truth_tca_shift_s', max(abs(rows.truth_tca_shift_s)));
end

function gate = empty_gate(contract, failure_count, completed_count)
    gate = struct('pass', false, ...
        'completed_geometries', completed_count, ...
        'observed_candidate_rows', 0, 'failure_count', failure_count, ...
        'count_pass', false, 'execution_pass', false, ...
        'tca_invariants_pass', false, ...
        'covariance_invariants_pass', false, ...
        'action_limit_pass', false, 'classification_pass', false, ...
        'near_pc_bound_pass', false, 'covariance_bound_pass', false, ...
        'planning_threshold_disagreements', 0, ...
        'planning_remediation_disagreements', 0, ...
        'truth_safety_disagreements', 0, 'trigger_disagreements', 0, ...
        'tca_only_planning_threshold_changes', 0, ...
        'covariance_planning_threshold_changes', 0, ...
        'tca_only_truth_safety_changes', 0, ...
        'covariance_truth_safety_changes', 0, ...
        'maximum_near_log10_pc_change', Inf, ...
        'maximum_covariance_change_relative', Inf, ...
        'maximum_member_tca_shift_s', Inf, ...
        'maximum_truth_tca_shift_s', Inf);
    assert(contract.expected_candidate_rows > 0);
end

function summary = summarize_geometries(rows)
    if isempty(rows)
        summary = table();
        return;
    end
    geometry_ids = unique(rows.geometry_id, 'stable');
    summaries = cell(numel(geometry_ids), 1);
    for k = 1:numel(geometry_ids)
        selected = rows.geometry_id == geometry_ids(k);
        part = rows(selected, :);
        summaries{k} = struct( ...
            'geometry_id', geometry_ids(k), 'seed', part.seed(1), ...
            'family', part.family(1), 'band', part.band(1), ...
            'candidate_rows', height(part), ...
            'classification_disagreements', nnz( ...
                part.planning_threshold_disagreement | ...
                part.planning_remediation_disagreement | ...
                part.truth_safety_disagreement | ...
                part.trigger_disagreement), ...
            'maximum_member_tca_shift_s', ...
                max(part.maximum_member_tca_shift_s), ...
            'maximum_truth_tca_shift_s', ...
                max(abs(part.truth_tca_shift_s)), ...
            'maximum_covariance_change_relative', ...
                max(part.maximum_covariance_change_relative));
    end
    summary = struct2table(vertcat(summaries{:}));
end

function manifest = source_hash_manifest(project_root)
    runner = fullfile(project_root, ...
        'run_stage_6b1_gate_b_maneuver_evaluation.m');
    files = matlab.codetools.requiredFilesAndProducts(runner);
    files = string(files(:));
    inside = startsWith(lower(files), lower(string(project_root)));
    files = unique([files(inside); string(fullfile(project_root, ...
        'STAGE_6B1_GATE_B_MANEUVER_EVALUATION_CONTRACT.md'))]);
    files = sort(files);
    relative_path = strings(numel(files), 1);
    sha256 = strings(numel(files), 1);
    for k = 1:numel(files)
        relative_path(k) = erase(files(k), string(project_root) + filesep);
        sha256(k) = sha256_file(files(k));
    end
    manifest = table(relative_path, sha256);
end

function save_checkpoint(path, state)
    temporary = [path, '.partial'];
    save(temporary, 'state', '-v7.3');
    movefile(temporary, path, 'f');
end

function print_progress(state, contract, timer, initial_remaining)
    completed_session = initial_remaining - nnz(~state.done);
    elapsed = toc(timer);
    rate = completed_session / max(elapsed, eps);
    eta = nnz(~state.done) / max(rate, eps);
    fprintf(['  %d/%d geometries complete (%.1f%%), elapsed %.1f min, ', ...
        'session ETA %.1f min.\n'], nnz(state.done), ...
        contract.n_geometries, 100 * nnz(state.done) / ...
        contract.n_geometries, elapsed / 60, eta / 60);
end

function digest = sha256_file(path)
    algorithm = System.Security.Cryptography.SHA256.Create();
    stream = System.IO.File.OpenRead(char(path));
    cleanup = onCleanup(@() stream.Close());
    bytes = uint8(algorithm.ComputeHash(stream));
    digest = upper(reshape(dec2hex(bytes, 2).', 1, []));
    assert(~isempty(cleanup));
end

function write_hash_sidecar(path, digest)
    file = fopen(path, 'w');
    assert(file >= 0, 'Could not create Gate B SHA-256 sidecar.');
    cleanup = onCleanup(@() fclose(file));
    fprintf(file, '%s\n', digest);
    assert(~isempty(cleanup));
end

function write_result(output_dir, results, result_sha256)
    file = fopen(fullfile(output_dir, 'RESULT.md'), 'w');
    assert(file >= 0, 'Could not create Gate B result report.');
    cleanup = onCleanup(@() fclose(file));
    gate = results.gate;
    fprintf(file, '# Stage 6b1 Gate B maneuver-evaluation validity\n\n');
    fprintf(file, '**%s**\n\n', results.verdict);
    fprintf(file, '- Geometries / candidate rows: %d / %d\n', ...
        gate.completed_geometries, gate.observed_candidate_rows);
    fprintf(file, '- Execution failures: %d\n', gate.failure_count);
    fprintf(file, '- Gate pass: %d\n', gate.pass);
    fprintf(file, '- Planning threshold disagreements: %d\n', ...
        gate.planning_threshold_disagreements);
    fprintf(file, '- Planning remediation disagreements: %d\n', ...
        gate.planning_remediation_disagreements);
    fprintf(file, '- Truth-safety disagreements: %d\n', ...
        gate.truth_safety_disagreements);
    fprintf(file, '- Dual-trigger disagreements: %d\n', ...
        gate.trigger_disagreements);
    fprintf(file, ['- TCA-only planning / truth threshold changes: ', ...
        '%d / %d\n'], gate.tca_only_planning_threshold_changes, ...
        gate.tca_only_truth_safety_changes);
    fprintf(file, ['- Covariance-increment planning / truth threshold ', ...
        'changes: %d / %d\n'], ...
        gate.covariance_planning_threshold_changes, ...
        gate.covariance_truth_safety_changes);
    fprintf(file, '- Maximum relevant log10 Pc change: %.9g decades\n', ...
        gate.maximum_near_log10_pc_change);
    fprintf(file, '- Maximum relative covariance change: %.9g\n', ...
        gate.maximum_covariance_change_relative);
    fprintf(file, '- Maximum robust-member / truth TCA shift: %.9g / %.9g s\n', ...
        gate.maximum_member_tca_shift_s, gate.maximum_truth_tca_shift_s);
    fprintf(file, '- ML training authorized: 0\n');
    fprintf(file, '- Result MAT SHA-256: `%s`\n', result_sha256);
    assert(~isempty(cleanup));
end
