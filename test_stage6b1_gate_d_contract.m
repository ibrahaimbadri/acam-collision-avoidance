function checks = test_stage6b1_gate_d_contract(contract)
%TEST_STAGE6B1_GATE_D_CONTRACT Validate the frozen design without data.

    if nargin < 1 || isempty(contract)
        contract = stage6b1_gate_d_contract();
    end
    names = strings(contract.expected_checks, 1);
    passed = false(contract.expected_checks, 1);
    detail = strings(contract.expected_checks, 1);
    index = 0;

    record('contract_document_exists', isfile(contract.source_document), '');
    record('parent_artifact_exists', isfile(contract.parent_path), '');
    record('split_labels_frozen', isequal(contract.splits, ...
        ["train", "calibration", "development_validation", "sealed_test"]), '');
    record('family_labels_frozen', isequal(contract.families, ...
        ["co_orbital", "crossing"]), '');
    record('physical_arms_frozen', isequal(contract.arms, ...
        ["primary_drag", "srp_sensitivity"]), '');
    record('split_geometry_counts', isequal(sum(contract.geometry_counts, 2)', ...
        contract.expected_split_geometries), '');
    record('total_geometry_count', height(contract.geometry_plan) == 850, '');
    record('paired_row_count', height(contract.row_plan) == 1700, '');
    record('families_balanced', all(sum(contract.geometry_counts, 1) == 425), '');
    record('band_schedule_frozen', isequal(contract.band_schedule, ...
        [1, 4, 5, 5, 6]), '');
    record('band_counts_match', verify_band_counts(contract), '');
    record('seeds_unique', numel(unique(contract.geometry_plan.seed)) == 850, '');
    record('seeds_fresh', min(contract.geometry_plan.seed) > ...
        contract.prior_reserved_seed_max, '');
    record('seed_blocks_match', verify_seed_blocks(contract), '');
    record('geometry_ids_unique', numel(unique(contract.geometry_plan.geometry_id)) ...
        == 850, '');
    record('two_rows_per_geometry', verify_geometry_pairs(contract.row_plan), '');
    record('split_isolation_validator', validator_accepts(contract.row_plan), '');
    record('fit_rows_primary_train_only', nnz(contract.row_plan.fit_eligible) == 300 ...
        && all(contract.row_plan.arm(contract.row_plan.fit_eligible) == ...
        "primary_drag") && all(contract.row_plan.split( ...
        contract.row_plan.fit_eligible) == "train"), '');
    record('calibration_rows_primary_only', ...
        nnz(contract.row_plan.calibration_eligible) == 100 && ...
        all(contract.row_plan.arm(contract.row_plan.calibration_eligible) == ...
        "primary_drag"), '');
    record('sensitivity_never_fit', ~any(contract.row_plan.fit_eligible & ...
        contract.row_plan.arm == "srp_sensitivity"), '');
    record('sealed_rows_marked', nnz(contract.geometry_plan.sealed) == 300 && ...
        all(contract.geometry_plan.split(contract.geometry_plan.sealed) == ...
        "sealed_test"), '');
    forbidden = contains(lower(contract.features.names), ...
        ["truth", "withheld", "oracle", "label", "future"]);
    record('feature_schema_frozen', contract.features.schema_version == 1 && ...
        contract.features.count == 42 && numel(unique(contract.features.names)) ...
        == 42 && ~any(forbidden), '');
    record('no_preprocessing_or_selection', ...
        strcmp(contract.features.imputation, 'none') && ...
        strcmp(contract.features.scaling, 'none') && ...
        strcmp(contract.features.selection, 'none'), '');
    record('no_action_classifier', ~contract.model.action_classifier, '');
    record('binary_direction_model', isequal(contract.model.direction_classes, ...
        ["prograde", "retrograde"]), '');
    record('forest_hyperparameters_frozen', ...
        contract.model.tree_count == 200 && ...
        contract.model.minimum_leaf_size == 5 && ...
        contract.model.classifier_predictors_per_split == 7 && ...
        contract.model.regressor_predictors_per_split == 14 && ...
        contract.model.random_seed == 6310 && ...
        ~contract.model.hyperparameter_search, '');
    record('single_calibration_rule', ...
        strcmp(contract.calibration.rule, ...
        'global_median_observed_minus_predicted_log10_magnitude') && ...
        ~contract.calibration.refit_forests, '');
    record('complete_verified_policy', ...
        strcmp(contract.policy.evaluator, ...
        'complete_maneuver_dependent_covariance') && ...
        contract.policy.reserve_factor == 1.10 && ...
        contract.policy.remediation_pc_threshold == 3.16227766016838e-6 && ...
        contract.policy.actuator_limit_mps == 2.0, '');
    record('composition_rates_coherent', ...
        contract.composition.minimum_target_availability == 0.90 && ...
        contract.composition.minimum_raw_verifier_pass_rate == 0.70 && ...
        contract.composition.maximum_fallback_rate == 0.30 && ...
        contract.composition.maximum_no_solution_count == 0, '');
    record('safety_endpoint_definition', ...
        contract.safety.margin == 0.02 && ...
        contract.safety.one_sided_alpha == 0.05 && ...
        numel(contract.safety.endpoints) == 3 && ...
        contract.safety.apply_to_arms_separately, '');
    development_zero = cp_upper(0, 150, 0.05);
    development_one = cp_upper(1, 150, 0.05);
    record('development_sample_justified', development_zero <= 0.02 && ...
        development_one > 0.02 && ...
        contract.safety.development_maximum_events == 0, ...
        sprintf('upper(0)=%.12f; upper(1)=%.12f', ...
        development_zero, development_one));
    sealed_one = cp_upper(1, 300, 0.05);
    sealed_two = cp_upper(2, 300, 0.05);
    record('sealed_sample_justified', sealed_one <= 0.02 && ...
        sealed_two > 0.02 && contract.safety.sealed_maximum_events == 1, ...
        sprintf('upper(1)=%.12f; upper(2)=%.12f', sealed_one, sealed_two));
    record('runtime_gate_frozen', ...
        contract.runtime.maximum_median_paired_ratio == 0.50 && ...
        contract.runtime.maximum_mean_paired_ratio == 0.75 && ...
        contract.composition.minimum_development_timing_pairs == 30 && ...
        contract.composition.minimum_sealed_timing_pairs == 60, '');
    record('delta_v_conditioned_on_safety', ...
        contract.delta_v.analyze_only_after_safety && ...
        ~contract.delta_v.advancement_gate && ...
        contract.delta_v.bootstrap_replicates == 10000 && ...
        contract.delta_v.bootstrap_seed == 6311, '');
    record('sealed_test_stays_locked', ...
        contract.sealing.lock_required_before_sealed_generation && ...
        ~contract.sealing.sealed_generation_authorized_by_gate_d && ...
        contract.sealing.sealed_evaluations == 1, '');
    record('no_outcome_based_case_changes', ...
        ~contract.sealing.outcome_based_stopping && ...
        ~contract.sealing.seed_replacement && ...
        strcmp(contract.sealing.failed_execution_treatment, 'unsafe'), '');
    record('reproducibility_manifest_required', ...
        contract.reproducibility.transitive_sha256_manifest_required && ...
        contract.reproducibility.environment_manifest_required && ...
        contract.reproducibility.verify_before_resume && ...
        contract.reproducibility.verify_at_policy_lock && ...
        contract.reproducibility.verify_before_sealed, '');
    record('checkpoint_and_budget_frozen', ...
        contract.reproducibility.atomic_geometry_checkpoint && ...
        contract.runtime.checkpoint_every_geometries == 1 && ...
        contract.runtime.maximum_local_workers == 2 && ...
        contract.runtime.development_wall_budget_days == 21 && ...
        contract.runtime.sealed_wall_budget_days == 14 && ...
        contract.runtime.total_wall_budget_days == 35, '');

    assert(index == contract.expected_checks, ...
        'Gate D check count changed without updating the contract.');
    checks = table(names, passed, detail, 'VariableNames', ...
        {'check_name', 'passed', 'detail'});

    function record(name, outcome, message)
        index = index + 1;
        names(index) = string(name);
        passed(index) = logical(outcome);
        detail(index) = string(message);
    end
end

function pass = verify_band_counts(contract)
    pass = true;
    for split_index = 1:numel(contract.splits)
        for family_index = 1:numel(contract.families)
            selected = contract.geometry_plan.split == ...
                contract.splits(split_index) & contract.geometry_plan.family == ...
                contract.families(family_index);
            observed = zeros(1, numel(contract.risk_bands));
            for band_index = 1:numel(contract.risk_bands)
                observed(band_index) = nnz(selected & ...
                    contract.geometry_plan.risk_band == ...
                    contract.risk_bands(band_index));
            end
            pass = pass && isequal(observed, ...
                contract.band_counts_per_family(split_index, :));
        end
    end
end

function pass = verify_seed_blocks(contract)
    pass = true;
    for split_index = 1:numel(contract.splits)
        for family_index = 1:numel(contract.families)
            selected = contract.geometry_plan.split == ...
                contract.splits(split_index) & contract.geometry_plan.family == ...
                contract.families(family_index);
            observed = sort(contract.geometry_plan.seed(selected))';
            expected = contract.seed_starts(split_index, family_index) + ...
                (0:contract.geometry_counts(split_index, family_index) - 1);
            pass = pass && isequal(observed, expected);
        end
    end
end

function pass = verify_geometry_pairs(rows)
    geometry_ids = unique(rows.geometry_id);
    pass = true;
    for k = 1:numel(geometry_ids)
        selected = rows.geometry_id == geometry_ids(k);
        pass = pass && nnz(selected) == 2 && ...
            isequal(sort(rows.arm(selected)), ...
            sort(["primary_drag"; "srp_sensitivity"])) && ...
            isscalar(unique(rows.split(selected)));
    end
end

function pass = validator_accepts(rows)
    try
        validate_stage6b1_split_isolation(rows);
        pass = true;
    catch
        pass = false;
    end
end

function upper = cp_upper(events, trials, alpha)
    if events == trials
        upper = 1;
    elseif events == 0
        upper = 1 - alpha^(1 / trials);
    else
        upper = betaincinv(1 - alpha, events + 1, trials - events);
    end
end
